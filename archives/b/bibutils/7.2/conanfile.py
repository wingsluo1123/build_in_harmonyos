#!/usr/bin/env python3
"""Conan recipe — bibutils 7.2 (custom configure + make).

bibutils uses a custom configure script (not autotools) that accepts:
  --install-dir <dir>  --install-lib <dir>  --static|--dynamic
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class BibutilsConan(ConanFile):
    name = "bibutils"
    version = "7.2"
    description = "Bibliography conversion utilities"
    license = "MIT"
    homepage = "https://sourceforge.net/projects/bibutils/"
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)
        # bibutils uses a custom configure script, not autotools
        # Run configure from source folder so it finds Makefile_start
        bin_dir = os.path.join(self.package_folder, "bin")
        lib_dir = os.path.join(self.package_folder, "lib")
        # Set CC=clang since OHOS doesn't have 'cc' symlink (E001)
        os.environ["CC"] = "clang"
        self.run(
            f'cd {self.source_folder} && ./configure --install-dir "{bin_dir}" --install-lib "{lib_dir}" --static',
            env="conanbuild"
        )
        # Makefile is generated by configure in the source folder
        self.run(f"make -C {self.source_folder} CC=clang -j1", env="conanbuild")

    def package(self):
        self.run(f"make -C {self.source_folder} CC=clang install", env="conanbuild")

    def package_info(self):
        self.cpp_info.libs = ["bibutils"]
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = ["lib"]
