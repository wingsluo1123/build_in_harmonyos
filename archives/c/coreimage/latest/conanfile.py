from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.cmake import CMake, CMakeToolchain, CMakeDeps, cmake_layout
import os


class CoreimageConan(ConanFile):
    name = "coreimage"
    version = "latest"
    description = "An image viewer app of CoreApps family"
    license = "GPL-3.0-or-later"
    homepage = "https://github.com/rahmanshaber/coreimage"
    url = ""

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("qtbase/6.11.1")
        self.requires("libcprime/latest")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        tc.variables["CMAKE_CXX_STANDARD"] = "17"
        qtbase = self.dependencies["qtbase"]
        qtbase_root = qtbase.package_folder
        tc.variables["Qt6_DIR"] = f"{qtbase_root}/lib/cmake/Qt6"
        tc.generate()

        deps = CMakeDeps(self)
        deps.set_property("qtbase", "cmake_file_name", "Qt6")
        deps.set_property("qtbase", "cmake_target_name", "Qt6::Core")
        deps.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
