#!/usr/bin/env python3
"""Conan recipe for dhcp-probe 1.3.1 — DHCP network probe tool.

Adapted for HarmonyOS PC (aarch64):
  - config.guess/config.sub patched for OHOS platform detection (E007)
  - config.status workaround for HarmonyOS mktemp temp directory issue
  - Default paths (/etc, /var/run) replaced with package prefix paths
  - Dependencies: libpcap/1.10.6, libnet/1.2 (libnet_cq_end_loop included)
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, replace_in_file
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class DhcpProbeConan(ConanFile):
    name = "dhcp-probe"
    version = "1.3.1"
    description = "Attempts to discover DHCP and BootP servers on a network"
    license = "GPL-2.0-or-later"
    homepage = "https://www.net.princeton.edu/software/dhcp_probe/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("libpcap/1.10.6")
        self.requires("libnet/1.2@ohpcd/stable")

    def layout(self):
        basic_layout(self)

    def source(self):
        # Use curl to download - server has Content-Encoding issue that breaks conan's downloader
        import shutil
        url = self.conan_data["sources"]["url"]
        tarball = os.path.join(self.source_folder, "dhcp_probe-1.3.1.tar.gz")
        self.run(f'curl -fsSL -o "{tarball}" "{url}"')
        shutil.unpack_archive(tarball, self.source_folder)
        os.remove(tarball)
        # Move contents up from dhcp_probe-1.3.1/ to source_folder (strip root)
        extracted = os.path.join(self.source_folder, "dhcp_probe-1.3.1")
        if os.path.isdir(extracted):
            for item in os.listdir(extracted):
                src = os.path.join(extracted, item)
                dst = os.path.join(self.source_folder, item)
                if os.path.exists(dst):
                    if os.path.isdir(dst):
                        shutil.rmtree(dst)
                    else:
                        os.remove(dst)
                shutil.move(src, dst)
            os.rmdir(extracted)

    def generate(self):
        tc = AutotoolsToolchain(self)
        pcap = self.dependencies["libpcap"]
        libnet = self.dependencies["libnet"]
        tc.configure_args.append(f"--with-pcap-include={pcap.cpp_info.includedirs[0]}")
        tc.configure_args.append(f"--with-pcap-lib={pcap.cpp_info.libdirs[0]}")
        tc.configure_args.append(f"--with-libnet-include={libnet.cpp_info.includedirs[0]}")
        tc.configure_args.append(f"--with-libnet-lib={libnet.cpp_info.libdirs[0]}")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        # Replace hardcoded paths with package prefix paths
        defaults_h = os.path.join(self.source_folder, "src", "defaults.h")
        replace_in_file(self, defaults_h, "/var/run/dhcp_probe.pid",
                        os.path.join(self.package_folder, "var", "run", "dhcp_probe.pid"))
        replace_in_file(self, defaults_h, "/etc/dhcp_probe.cf",
                        os.path.join(self.package_folder, "etc", "dhcp_probe.cf"))

        # Workaround: HarmonyOS restricts file creation in mktemp-created dirs.
        # Patch configure and config.status template to use a fixed temp directory.
        configure = os.path.join(self.source_folder, "configure")
        cstmp = os.path.join(self.build_folder, ".cstmp")
        os.makedirs(cstmp, exist_ok=True)
        with open(configure, "r") as f:
            content = f.read()
        content = content.replace(
            'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null` &&',
            'tmp=.cstmp &&',
        )
        content = content.replace('test -d "$tmp"', 'true')
        content = content.replace('tmp=./conf$$-$RANDOM', 'tmp=.cstmp')
        content = content.replace('(umask 077 && mkdir "$tmp")', 'true')
        # Disable trap that removes temp dir on exit
        content = content.replace(
            '{ test ! -d "$ac_tmp" || rm -fr "$ac_tmp"; } && exit $exit_status',
            'exit $exit_status',
        )
        with open(configure, "w") as f:
            f.write(content)

        autotools = Autotools(self)
        autotools.configure()

        # Also patch config.status (generated by configure with same pattern)
        config_status = os.path.join(self.build_folder, "config.status")
        if os.path.isfile(config_status):
            os.makedirs(cstmp, exist_ok=True)
            with open(config_status, "r") as f:
                content = f.read()
            content = content.replace(
                'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null` &&',
                'tmp=.cstmp &&',
            )
            content = content.replace('test -d "$tmp"', 'true')
            content = content.replace('tmp=./conf$$-$RANDOM', 'tmp=.cstmp')
            content = content.replace('(umask 077 && mkdir "$tmp")', 'true')
            content = content.replace(
                '{ test ! -d "$ac_tmp" || rm -fr "$ac_tmp"; } && exit $exit_status',
                'exit $exit_status',
            )
            with open(config_status, "w") as f:
                f.write(content)

        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.bindirs = ["bin"]
