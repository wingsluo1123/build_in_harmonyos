#!/usr/bin/env python3
"""Conan recipe — ebtables 2.0.11 (Autotools; Ethernet bridge netfilter userspace)

Upstream: https://ebtables.netfilter.org/  (tarball at ftp.netfilter.org)

Delivered — everything comes from upstream's own `make install`:

  * lib/libebtc.so.0.0.0 (+ .so.0 / .so symlinks, DT_SONAME=libebtc.so.0)
        the ruleset-manipulation library. Upstream ships it as a libtool
        library (`lib_LTLIBRARIES = libebtc.la`) but installs **no headers**
        (there is no `include_HEADERS` in Makefile.am), so the recipe installs
        the upstream `include/` tree itself — see `_install_public_headers`.
  * bin/ebtables-legacy, bin/ebtables-legacy-restore, bin/ebtablesd, bin/ebtablesu
        the four sbin_PROGRAMS of Makefile.am.
  * bin/ebtables-legacy-save (upstream sbin_SCRIPTS, generated by sed from
        ebtables-save.in).
  * etc/ethertypes (sysconf_DATA), share/man/man8/ebtables-legacy.8, licenses/COPYING.

Why this shape (details + evidence in notes.md):

  R1  explicit `--build`/`--host=<cpu>-unknown-linux-ohos` on OHOS: `uname -s`
      reports "HarmonyOS" there and the config.guess shipped by this tarball has
      no HarmonyOS case, so `configure` would abort while guessing the build
      triplet. Passing both triplets skips config.guess entirely — and
      0001-config.sub-linux-ohos.patch teaches the bundled config.sub the
      `linux-ohos` OS, which conan feeds it via `--build=`/`--host=`.
      CI #79884 showed that skipping config.guess alone is not enough: configure
      still validates *its own* `--build=` argument through config.sub, which
      rejected `aarch64-unknown-linux-ohos`.
  R2  `--sbindir=${prefix}/bin` and `--sysconfdir=/etc`: the conan package keeps
      executables in `bin/`; `--sysconfdir=/etc` makes the compiled-in
      `_PATH_ETHERTYPES` (= `${sysconfdir}/ethertypes`) a clean `/etc/ethertypes`
      instead of autoconf's `//etc/ethertypes`, while `make install DESTDIR=...`
      still lands the data file at `<pkg>/etc/ethertypes`.
  R3  `AC_DISABLE_STATIC` upstream => shared-only build (validated in configure()).
  R4  the OHOS worker unpacked a tarball whose timestamps make `make` believe
      `aclocal.m4`/`configure`/`Makefile.in` are out of date and it tries to run
      `aclocal`/`autoconf`, which do not exist on the worker (`Error 127`).
      `_fix_generated_timestamps` layers the mtimes along the dependency chain
      instead of patching upstream sources.
  R5  patches/0001 only touches the *generated* helper script
      `build-aux/config.sub` (no upstream source file, no `configure.ac`, no
      `Makefile.am`): it adds `linux-ohos*` to the two OS lists so the
      `aarch64-unknown-linux-ohos` triplet conan passes via `--build`/`--host`
      is accepted.  No upstream C source is modified by this recipe.
  R6  patches/0002 restores `umask 022` in the two places where upstream's
      pre-generated `configure` creates the config.status scratch directory
      (`umask 077 && mktemp -d ./confXXXXXX`).  On the OHOS worker's HMDFS that
      0700 directory is unusable by the UID-mapped process, so `make` dies with
      "`config.status: error: could not setup config files machinery`" /
      "`subs1.awk: Permission denied`" (CI #82335).  Identical fix + identical
      rationale as the merged archives/l/libnftnl/1.3.1 and
      archives/i/iptables/1.8.13; R4 remains a stateless mtime adjustment.
  R7  `-D_UAPI_LINUX_SOCKET_H -D__kernel_sa_family_t=sa_family_t` in
      `generate()`: the OHOS sysroot's `<linux/socket.h>` defines
      `struct sockaddr_storage` unconditionally under that guard, colliding with
      libc `<sys/socket.h>`, and its absence also strips the
      `__kernel_sa_family_t` type the kernel socket structs use.  Flags only,
      no source patch — the same pair as the merged iptables/1.8.13 (§R5) and
      libnftnl/1.3.1 (CI #85977: `redefinition of 'sockaddr_storage'` in
      communication.c and the cascading `__packed` redefinitions from
      `<linux/if_pppox.h>`).

Upstream test suites: **none**. ebtables 2.0.11 has no `TESTS`, no
`check_PROGRAMS` and no test directory; `make check` is an empty automake target.
N = 0 is reported as-is, and the hard gate is built from *source-derived*
user-space golden cases (see `_run_cli_golden_cases`) plus the real consumer use
case in test_package/.
"""
