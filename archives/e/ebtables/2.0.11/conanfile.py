def _read(path):
    if not os.path.isfile(path):
        return ""
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def _c_literals(text):
    """按出现顺序取出 C 字符串字面量（已解码 \\n 等转义）。"""
    out = []
    for match in re.finditer(r'"((?:[^"\\]|\\.)*)"', text):
        try:
            out.append(match.group(1).encode("utf-8").decode("unicode_escape"))
        except UnicodeDecodeError:                      # pragma: no cover
            out.append(match.group(1))
    return out


class EbtablesConan(ConanFile):
    name = "ebtables"
    version = "2.0.11"
    description = ("Ethernet bridge frame table administration: the ebtables "
                   "userspace tools (ebtables-legacy, ebtables-legacy-restore, "
                   "ebtablesd, ebtablesu), the libebtc ruleset library and the "
                   "ethertypes database")
    license = "GPL-2.0-or-later"
    homepage = "https://ebtables.netfilter.org/"
    url = "https://ebtables.netfilter.org/"
    topics = ("netfilter", "bridge", "firewall", "ethernet", "linux")
    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    # ── helpers ──────────────────────────────────────────────────────────
    @property
    def _ohos_triplet(self):
        """<cpu>-unknown-linux-ohos for the target arch (R1)."""
        cpu = {"armv8": "aarch64", "x86_64": "x86_64", "x86": "i686"}.get(
            str(self.settings.arch), str(self.settings.arch))
        return "{}-unknown-linux-ohos".format(cpu)

    @property
    def _is_ohos(self):
        return str(self.settings.os) == "OHOS"

    # ── conan boilerplate ───────────────────────────────────────────────
    def configure(self):
        if not self.options.shared:
            raise ConanInvalidConfiguration(
                "ebtables/2.0.11 is delivered shared-only: upstream configure.ac "
                "calls AC_DISABLE_STATIC, so `configure` never builds a static "
                "libebtc and the four sbin_PROGRAMS link libebtc.so.0")
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "ebtables targets the Linux/OHOS bridge netfilter, got {}".format(
                    self.settings.os))

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"][self.version], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args.extend([
            "--prefix=/",
            "--bindir=/bin",
            "--sbindir=/bin",          # R2 — conan 包把可执行文件放在 bin/
            "--libdir=/lib",
            "--includedir=/include",
            "--sysconfdir=/etc",       # R2 — _PATH_ETHERTYPES=/etc/ethertypes
            "--enable-shared",
            "--disable-static",
        ])
        if self._is_ohos:
            # R1 — skip config.guess (2011 vintage, does not know HarmonyOS)
            tc.configure_args.extend([
                "--build={}".format(self._ohos_triplet),
                "--host={}".format(self._ohos_triplet),
            ])
        # R7 — OHOS sysroot 的 <linux/socket.h> 无条件定义 `struct sockaddr_storage`
        # （guard 名 `_UAPI_LINUX_SOCKET_H`），与 libc <sys/socket.h> 的同名结构冲突。
        # 平台 CI #85977 的原文：
        #   communication.c:23 -> include/ebtables_u.h:28 ->
        #   include/linux/netfilter_bridge/ebtables.h:17 -> sysroot <linux/if.h>:23
        #   -> <linux/socket.h>:23:8: error: redefinition of 'sockaddr_storage'
        #      note: previous definition is here（sysroot <sys/socket.h>:377）
        #   include/linux/netfilter_bridge.h:10 -> <linux/if_pppox.h>:59/64/69/74/111:
        #   error: redefinition of '__packed' with a different type —— 同一根因的
        #   连带（这些内核结构用 `__kernel_sa_family_t`，而它正是由被跳过的
        #   <linux/socket.h> 提供的）。
        # 修法：预定义该 guard 抑制 sysroot 的那份，再把它唯一的必要声明
        # `__kernel_sa_family_t` 别名到 POSIX `sa_family_t`。与已合入的
        # iptables/1.8.13（§R5）和 libnftnl/1.3.1 完全同款（flag 对，无源码补丁）。
        # 故意对所有平台生效：glibc 上 guard 名是 `_LINUX_SOCKET_H`，此 -D 为空操作，
        # 且重复 typedef sa_family_t 是合法 C11 —— 这使该修复能在本机 Linux 上验证。
        tc.extra_cflags.extend(["-D_UAPI_LINUX_SOCKET_H",
                                "-D__kernel_sa_family_t=sa_family_t"])
        # R8 — `__packed` 本身在 OHOS sysroot 的 <linux/if_pppox.h> 里**没有被定义**。
        # 平台 CI #104951（build 105209）证明 R7 不是它的根因：抑制 <linux/socket.h>
        # 之后 `sockaddr_storage` 冲突消失，但 `if_pppox.h:59/64/69/74/111` 的
        #   error: redefinition of '__packed' with a different type:
        #          'struct sockaddr_pppol2tp' vs 'struct sockaddr_pppox'
        # 一条不少 —— 因为 `__packed` 不是宏时，`} __packed;` 在 C 语法里是**声明一个
        # 名为 __packed 的变量**，第二处声明即「类型不同的重定义」。（glibc 的
        # <linux/if_pppox.h> 用的是展开后的 `__attribute__((packed))`，所以本机不复现。）
        # 修法：仍为纯 flag（sysroot 不可改，也不该改），把内核写法补回等价的属性宏。
        # R8b — 但 `-D__packed=__attribute__((packed))` 走不通：autotools/libtool 把
        #   CFLAGS 原样拼进 shell 命令行，括号没被转义，于是**第一条编译命令**就死成
        #   `./libtool ... -D__packed=__attribute__((packed)) ... communication.c`
        #   `/data/service/hnp/bin/bash: -c: line 1: syntax error near unexpected token `('`
        #   `make[1]: *** [Makefile:804: libebtc_la-communication.lo] Error 2`
        #   （平台 CI #92758 / build 106699 —— 注意这是 **Error 2（进程起不来）**，
        #   不是编译错误，配套日志里另有 13 处 `configure: fork: retry` worker 噪声）。
        # 改用**强制包含头**：宏定义写在头文件里，命令行上只剩一个不含括号的路径。
        # 头文件由 generate() 生成到 generators_folder，不引入任何源码改动。
        uapi_compat = os.path.join(self.generators_folder, "ohos_uapi_compat.h")
        save(self, uapi_compat, _OHOS_UAPI_COMPAT_H)
        tc.extra_cflags.extend(["-include", uapi_compat])
        tc.generate()

    # ── build ───────────────────────────────────────────────────────────
    def build(self):
        self._fix_generated_timestamps()
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])
        self._upstream_test_inventory()
        self._run_cli_golden_cases()
        self._probe_kernel_cases()

    def _fix_generated_timestamps(self):
        """R4：解包后 mtime 全同 ⇒ make 会去跑不存在的 aclocal/autoconf。

        把「源」设成 now-300，生成物按 autotools 的依赖链分层设 now-240 ..
        now-120（aclocal.m4 → configure → Makefile.in/config.h.in），随后
        `autotools.configure()` 会用当前时间重写 Makefile/config.status。
        只动 mtime，不改上游任何字节。
        """
        now = time.time()
        sources = ["configure.ac", "Makefile.am"]
        m4dir = os.path.join(self.build_folder, "m4")
        if os.path.isdir(m4dir):
            sources += ["m4/" + n for n in sorted(os.listdir(m4dir))
                        if n.endswith(".m4")]
        for rel in sources:
            path = os.path.join(self.build_folder, rel)
            if os.path.isfile(path):
                os.utime(path, (now - 300, now - 300))
        for rel, back in (("aclocal.m4", 240), ("configure", 180),
                          ("config.h.in", 120), ("Makefile.in", 120)):
            path = os.path.join(self.build_folder, rel)
            if os.path.isfile(path):
                os.utime(path, (now - back, now - back))
        self.output.info(
            "[timestamps] %d autotools sources set to now-300s, generated files "
            "layered to now-240..120s (no autoreconf on the OHOS worker)" % len(sources))

    # ── 上游测试：如实登记 N = 0 ────────────────────────────────────────
    def _upstream_test_inventory(self):
        """ebtables 2.0.11 上游**没有**任何测试套件 ⇒ 如实登记 N=0。

        仍然执行一次 `make -j1 check`（automake 生成的空目标），把
        「上游无可跑测试」这件事落成日志证据，而不是靠配方里的一句声明。
        """
        makefile_am = _read(os.path.join(self.source_folder, "Makefile.am"))
        tests_var = re.search(r"(?m)^TESTS\s*=", makefile_am)
        check_progs = re.findall(r"(?m)^check_PROGRAMS\s*=(.*)$", makefile_am)
        test_dirs = [d for d in ("test", "tests", "checks", "test-suite")
                     if os.path.isdir(os.path.join(self.source_folder, d))]
        c_sources = len([n for n in os.listdir(os.path.join(self.source_folder,
                                                            "extensions"))
                         if n.endswith(".c")])
        self.output.info(
            "[upstream-tests] ebtables 2.0.11: TESTS=%s check_PROGRAMS=%d "
            "test-dirs=%s extensions/*.c=%d ⇒ upstream N=0 (the tarball carries no "
            "test suite at all)"
            % ("present" if tests_var else "absent", len(check_progs),
               test_dirs or "none", c_sources))
        for rel in ("README", "INSTALL", "THANKS", "ChangeLog"):
            text = _read(os.path.join(self.source_folder, rel))
            if "test" in text.lower():
                self.output.info(
                    "[upstream-tests]   note: %s mentions 'test' in prose; no automake "
                    "test target is registered (see TESTS/check_PROGRAMS check above)"
                    % rel)
        self.output.info("[upstream-tests] running 'make -j1 check' anyway "
                         "(empty automake target ⇒ proves N=0)")
        self.run("make -j1 check", cwd=self.build_folder)
        self.output.info(
            "[upstream-tests] HMBS_UPSTREAM_TESTS upstream=0 executed=0 "
            "reason=no-tests-in-upstream-tarball")

    # ── 从上游源码派生期望值（外部可核对真值）──────────────────────────
    def _derive_version_line(self):
        """由 configure.ac + Makefile.am + include/ebtables_u.h 派生版本行。

        PRINT_VERSION 宏的字符串拼接 + PROGNAME/PROGVERSION/PROGDATE 的取值
        全部来自上游源码，因此这是「外部真值」而不是配方自己写死的常量。
        """
        cfgfile = os.path.join(self.source_folder, "configure.ac")
        cfg = _read(cfgfile)
        m = re.search(r"AC_INIT\(\[([^\]]+)\]\s*,\s*\[([^\]]+)\]\)", cfg)
        if not m:
            raise ConanException("cannot derive AC_INIT from %s" % cfgfile)
        name, version = m.group(1), m.group(2)
        mk = _read(os.path.join(self.source_folder, "Makefile.am"))
        md = re.search(r"(?m)^PROGDATE\s*=\s*(.+?)\s*$", mk)
        date = md.group(1).replace("\\ ", " ") if md else ""
        hdr = _read(os.path.join(self.source_folder, "include", "ebtables_u.h"))
        pm = re.search(r"(?m)^#define\s+PRINT_VERSION\s+printf\((.*)\)\s*$", hdr)
        if not pm:
            raise ConanException("cannot derive PRINT_VERSION from include/ebtables_u.h")
        values = {"PROGNAME": name, "PROGVERSION": version, "PROGDATE": date}
        parts = []
        for tok in re.finditer(r'"(?:[^"\\]|\\.)*"|[A-Za-z_]\w*', pm.group(1)):
            text = tok.group(0)
            if text.startswith('"'):
                parts.append(_c_literals(text)[0])
            else:
                parts.append(values.get(text, ""))
        line = "".join(parts)
        # printf 的结尾 '\n' 在宏里是转义序列，_c_literals 已解码
        self.output.info("[cli-golden] derived version line from upstream sources: %r" % line)
        return line.strip("\n")

    def _derive_registry(self):
        """从 extensions/*.c 派生「上游注册了哪些扩展」。

        register 调用 → 结构体定义 → `.name`（宏形式从 include/**/*.h 的
        #define 解析）+ `.help` 指向的 help 函数。这是配方里所有扩展相关
        断言的外部真值来源。
        """
        defines = {}
        incroot = os.path.join(self.source_folder, "include")
        for root, _dirs, files in os.walk(incroot):
            for fname in files:
                if not fname.endswith(".h"):
                    continue
                text = _read(os.path.join(root, fname))
                for m in re.finditer(
                        r'(?m)^\s*#\s*define\s+([A-Za-z_]\w*)\s+"([^"]*)"', text):
                    defines[m.group(1)] = m.group(2)
        extdir = os.path.join(self.source_folder, "extensions")
        registry = {}
        for fname in sorted(os.listdir(extdir)):
            if not fname.endswith(".c"):
                continue
            text = _read(os.path.join(extdir, fname))
            for m in re.finditer(r"ebt_register_(\w+)\s*\(\s*&\s*([A-Za-z_]\w*)", text):
                category = _REGISTER_CATEGORY.get("ebt_register_" + m.group(1))
                if category is None:
                    continue
                var = m.group(2)
                block = re.search(
                    r"struct\s+ebt_u_\w+\s+" + re.escape(var) + r"\s*=\s*\{(.*?)\n\};",
                    text, re.S)
                if not block:
                    raise ConanException(
                        "extensions/%s: cannot locate struct definition of %s "
                        "registered through ebt_register_%s" % (fname, var, m.group(1)))
                body = block.group(1)
                name_m = re.search(r'\.name\s*=\s*(?:"([^"]*)"|([A-Za-z_]\w*))', body)
                help_m = re.search(r"\.help\s*=\s*([A-Za-z_]\w*)", body)
                if not name_m:
                    raise ConanException("extensions/%s: %s has no .name" % (fname, var))
                if name_m.group(1) is not None:
                    name = name_m.group(1)
                else:
                    name = defines.get(name_m.group(2), "<unresolved:%s>" % name_m.group(2))
                literals = []
                if help_m:
                    fn = re.search(
                        r"(?m)^(?:static\s+)?void\s+" + re.escape(help_m.group(1))
                        + r"\s*\([^)]*\)\s*\{(.*?)\n\}", text, re.S)
                    if fn:
                        literals = [s for s in _c_literals(fn.group(1))
                                    if s.strip() and "%" not in s]
                registry.setdefault(category, []).append(
                    {"name": name, "file": "extensions/" + fname,
                     "help": help_m.group(1) if help_m else None,
                     "literals": literals})
        return registry

    def _derive_hooknames(self):
        """由 include/linux/netfilter_bridge.h 的 NF_BR_* 与 libebtc.c 的
        ebt_hooknames[] 初始值派生 hook 下标 → 名字。"""
        hdr = _read(os.path.join(self.source_folder, "include", "linux",
                                 "netfilter_bridge.h"))
        index = {m.group(1): int(m.group(2)) for m in re.finditer(
            r"(?m)^#define\s+(NF_BR_\w+)\s+(\d+)\s*$", hdr)}
        lib = _read(os.path.join(self.source_folder, "libebtc.c"))
        block = re.search(r"ebt_hooknames\[NF_BR_NUMHOOKS\]\s*=\s*\{(.*?)\n\};", lib, re.S)
        if not block:
            raise ConanException("libebtc.c: cannot locate ebt_hooknames[]")
        names = {}
        for m in re.finditer(r'\[(NF_BR_\w+)\]\s*"([^"]*)"', block.group(1)):
            names[index[m.group(1)]] = m.group(2)
        return names

    def _derive_table_help(self, table, hooknames):
        """派生某张表 `-t <table> -h` 结尾的合法链列表（来自 ebtable_*.c）。"""
        path = os.path.join(self.source_folder, "extensions",
                            "ebtable_%s.c" % table)
        text = _read(path)
        hdr = _read(os.path.join(self.source_folder, "include", "linux",
                                 "netfilter_bridge.h"))
        fn = re.search(r"static void print_help\([^)]*\)\s*\{(.*?)\n\}", text, re.S)
        literals = [s for s in _c_literals(fn.group(1)) if "%" not in s] if fn else []
        macro = re.search(r"#define\s+\w*VALID_HOOKS\s+((?:[^\n]*\\\n)*[^\n]*)", text)
        if macro:
            indices = []
            for hook in re.findall(r"\(1\s*<<\s*(NF_BR_\w+)\)", macro.group(1)):
                idx = re.search(r"(?m)^#define\s+%s\s+(\d+)\s*$" % hook, hdr)
                if not idx:
                    raise ConanException("%s: unknown hook macro %s" % (path, hook))
                indices.append(int(idx.group(1)))
            expected = "".join(hooknames[i] + " " for i in sorted(indices)) + "\n"
        else:
            single = re.search(r"hn\[(NF_BR_\w+)\]", text)
            if not single:
                raise ConanException("%s: cannot derive chain list" % path)
            idx = re.search(r"(?m)^#define\s+%s\s+(\d+)\s*$" % single.group(1), hdr)
            expected = hooknames[int(idx.group(1))] + "\n"
        return literals, expected

    # ── CLI 黄金用例（离线、确定性、外部可核对真值）────────────────────
    def _cli_binary(self):
        """真实 ELF（不是 libtool 的 shell wrapper）。

        build 树里的 `./ebtables-legacy` 是 libtool wrapper（`#!/bin/sh`），
        OHOS 上没有 /bin/sh 可执行 ELF，因此直接用 .libs/ 下的真 ELF 并显式
        提供 LD_LIBRARY_PATH（与 wrapper 做的事等价）。
        """
        for cand in (os.path.join(self.build_folder, ".libs", "ebtables-legacy"),
                     os.path.join(self.build_folder, "ebtables-legacy")):
            if os.path.isfile(cand):
                return cand
        raise ConanException("build tree has no ebtables-legacy binary")

    def _cli_env(self):
        env = dict(os.environ)
        libdir = os.path.join(self.build_folder, ".libs")
        env["LD_LIBRARY_PATH"] = libdir + os.pathsep + env.get("LD_LIBRARY_PATH", "")
        return env

    def _run(self, binary, args, env):
        proc = subprocess.run([binary] + list(args), capture_output=True,
                              text=True, errors="replace", env=env, timeout=120)
        return proc.returncode, proc.stdout or "", proc.stderr or ""

    def _cli_smoke(self, binary, env):
        """返回 (ok, detail)：ok=False 仅在**平台拒绝启动这个 build 树 ELF**时。

        区分「平台限制」与「交付物缺陷」：进程起来了 rc 不对 ⇒ ok=True，交给
        后面的硬门禁去判；加载器拒载（OHOS 未签名 .so / 缺依赖）⇒ ok=False。
        """
        try:
            rc, out, err = self._run(binary, ["--version"], env)
        except OSError as exc:
            return False, "%s: %s" % (type(exc).__name__, exc)
        if rc != 0 and (rc == 127 or "Error loading shared library" in err
                        or "cannot open shared object" in err
                        or "Error relocating" in err):
            return False, "rc=%d stderr=%r" % (rc, err.strip()[:300])
        return True, "rc=%d out=%r" % (rc, out.strip()[:60])

    def _run_cli_golden_cases(self):
        """纯用户态黄金用例：全部期望值由上游源码派生，逐条硬比对。

        ebtables 的 `-L/-A/...` 需要 CAP_NET_RAW 与内核 ebtables 模块，但
        `--version` / `-h` / `-h <扩展>` / `-t <表> -h` / 错误路径都是纯用户态，
        这里把它们作为硬门禁；内核相关路径由 `_probe_kernel_cases` 逐条探测。
        """
        binary = self._cli_binary()
        if self._is_ohos:
            # OHOS 加载器拒载未签名 .so（E135/E517）：build 树里的 libebtc.so.0
            # 也要签名，否则 CLI 起不来。
            self._sign_elf(os.path.join(self.build_folder, ".libs", "libebtc.so.0.0.0"))
        env = self._cli_env()
        smoke_ok, smoke_detail = self._cli_smoke(binary, env)
        if not smoke_ok:
            message = (
                "[cli-golden][platform-limitation] 无法启动 build 树里的 %s：%s\n"
                "  这是**平台加载器**层面的拒绝（OHOS 只加载已签名 .so，硬坑 D/E；"
                "build 树的 libebtc.so.0.0.0 已尝试自签名），不是交付物缺陷。\n"
                "  用户态黄金用例共 35 条（G1..G9：--version/-V/--help/-h/"
                "-h list_extensions/21 个扩展 help/三张表 help/2 条负例/restore "
                "usage）在本次构建中"
                "**未执行**，已在此显式打印，不静默跳过；Linux 侧 conan create 里"
                "这些用例全部真跑，见 PR 正文与 notes.md。"
                % (binary, smoke_detail))
            if self._is_ohos:
                self.output.warning(message)
                self.output.info("[cli-golden] HMBS_CLI_GOLDEN checks=0 failed=0 "
                                 "degraded=platform-loader-refused")
                return
            raise ConanException(message)
        version_line = self._derive_version_line()
        registry = self._derive_registry()
        hooknames = self._derive_hooknames()

        checks = []
        failures = []

        def check(label, ok, detail, origin):
            checks.append(label)
            if not ok:
                failures.append(label)
            self.output.info("[cli-golden] %s %-52s %s (%s)"
                             % ("ok  " if ok else "FAIL", label, detail, origin))

        # G1/G2 版本行（PROGNAME/PROGVERSION/PROGDATE + PRINT_VERSION 宏）
        for flag, label in (("--version", "G1 --version"), ("-V", "G2 -V")):
            rc, out, err = self._run(binary, [flag], env)
            check(label, rc == 0 and out.strip() == version_line,
                  "rc=%d out=%r err=%r" % (rc, out.strip(), err.strip()[:80]),
                  "configure.ac AC_INIT + Makefile.am PROGDATE + ebtables_u.h PRINT_VERSION")

        # G3 --help / -h：首行版本行 + print_help() 的字面量（ebtables.c）
        eb_text = _read(os.path.join(self.source_folder, "ebtables.c"))
        ph = re.search(r"static void print_help\(\)\s*\{(.*?)\n\}", eb_text, re.S)
        help_literals = [s for s in _c_literals(ph.group(1))
                         if s.strip() and "%" not in s]
        _, filter_chains = self._derive_table_help("filter", hooknames)
        for flag in ("--help", "-h"):
            rc, out, err = self._run(binary, [flag], env)
            missing = [s for s in help_literals if s not in out]
            ok = (rc == 0 and out.splitlines()[0].strip() == version_line
                  and out.endswith(filter_chains) and not missing)
            check("G3 %s" % flag, ok,
                  "rc=%d missing=%r tail=%r" % (rc, missing[:2], out[-40:]),
                  "ebtables.c print_help() 字面量 + ebtable_filter.c 合法链")

        # G4 扩展注册表：二进制内建注册表 == 上游 extensions/*.c 派生结果
        rc, out, err = self._run(binary, ["-h", "list_extensions"], env)
        listed, section = {}, None
        for line in out.splitlines():
            if line.startswith("Loaded ") and line.endswith(":"):
                section = line[len("Loaded "):-1]
                listed.setdefault(section, set())
                continue
            if section and line.strip():
                listed[section].add(line.strip())
        for category in ("matches", "watchers", "targets", "tables"):
            derived = sorted(e["name"] for e in registry.get(category, []))
            got = sorted(listed.get(category, set()))
            check("G4 %s registry (%d)" % (category, len(derived)),
                  rc == 0 and derived == got,
                  "derived=%s got=%s" % (derived, got),
                  "extensions/*.c 的 ebt_register_* 调用 + .name（宏经 include/**/*.h 解析）")

        # G5 每个扩展的 help 文本 == 该扩展源码 help 函数的字面量；
        #    G6 三张表的合法链列表 == VALID_HOOKS / hn[NF_BR_*] 派生值
        for category in ("matches", "watchers", "targets", "tables"):
            for entry in registry.get(category, []):
                name = entry["name"]
                args = ["-t", name, "-h"] if category == "tables" else ["-h", name]
                rc, out, err = self._run(binary, args, env)
                missing = [s for s in entry["literals"] if s not in out]
                detail = "rc=%d literals=%d missing=%r" % (
                    rc, len(entry["literals"]), missing[:2])
                origin = "%s 的 %s()" % (entry["file"], entry["help"])
                if category == "tables":
                    literals, expected = self._derive_table_help(name, hooknames)
                    missing += [s for s in literals if s not in out]
                    ok = (rc == 0 and not missing and out.endswith(expected))
                    detail += " chains=%r" % expected.strip()
                    origin += " + ebtable_%s.c VALID_HOOKS/hn[]" % name
                    check("G6 -t %s -h" % name, ok, detail, origin)
                else:
                    check("G5 -h %s" % name, rc == 0 and not missing, detail, origin)

        # G7/G8 负例路径：报错文案来自上游源码字面量（+ __ebt_print_error 的 ".\n"）
        lib_text = _read(os.path.join(self.source_folder, "libebtc.c"))
        bad_table = re.search(r'ebt_print_error\("(Bad table name \'%s\')"', lib_text)
        not_found = re.search(r'ebt_print_error2\("(Extension \'%s\' not found)"', eb_text)
        for label, args, literal, arg in (
                ("G7 -t bogus -L", ["-t", "bogus", "-L"],
                 bad_table.group(1) if bad_table else None, "bogus"),
                ("G8 -h no_such_extension", ["-h", "no_such_extension"],
                 not_found.group(1) if not_found else None, "no_such_extension")):
            if literal is None:
                raise ConanException("cannot derive the %s message from upstream" % label)
            expected = (literal % arg) + ".\n"
            rc, out, err = self._run(binary, args, env)
            check(label, rc == 255 and err == expected,
                  "rc=%d err=%r expected=%r" % (rc, err, expected),
                  "上游源码字面量 + libebtc.c __ebt_print_error 的 '\\n.' 后缀")

        # G9 ebtables-legacy-restore 的 usage（ebtables-restore.c 字面量）
        restore = os.path.join(self.build_folder, ".libs", "ebtables-legacy-restore")
        rest_text = _read(os.path.join(self.source_folder, "ebtables-restore.c"))
        usage = re.search(r'fprintf\(stderr,\s*"(Usage: ebtables-restore[^"]*)"', rest_text)
        if not os.path.isfile(restore) or not usage:
            raise ConanException("ebtables-legacy-restore / its usage literal not found")
        rc, out, err = self._run(restore, ["--help"], env)
        usage_text = _c_literals('"%s"' % usage.group(1))[0]
        last_line = (err.strip().splitlines() or [""])[-1]
        check("G9 ebtables-legacy-restore --help", rc != 0 and usage_text in err,
              "rc=%d stderr_tail=%r expected=%r" % (rc, last_line, usage_text),
              "ebtables-restore.c fprintf(stderr, ...) 字面量")

        self.output.info(
            "[cli-golden] %d/%d user-space golden cases reproduced from the build tree "
            "(expectations derived from the upstream sources, not hard-coded)"
            % (len(checks) - len(failures), len(checks)))
        self.output.info("HMBS_CLI_GOLDEN checks=%d failed=%d" % (len(checks), len(failures)))
        if failures:
            raise ConanException(
                "build() 用户态黄金用例失败 %d/%d：%s（每条的期望值都由上游源码派生，"
                "见上方 [cli-golden] 明细）"
                % (len(failures), len(checks), ", ".join(failures)))

    # ── 内核相关路径：能力探测 + 逐条打印分类 ───────────────────────────
    def _probe_kernel_cases(self):
        """逐条探测 CAP_NET_RAW / 内核 ebtables 模块。

        可用就真跑并按上游 listing 格式断言；不可用就打印 SKIP 与理由
        （绝不静默跳过）。
        """
        binary = self._cli_binary()
        env = self._cli_env()
        hooknames = self._derive_hooknames()
        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_RAW)
            sock.close()
            sock_ok, sock_why = True, "socket(AF_INET, SOCK_RAW, IPPROTO_RAW) ok"
        except OSError as exc:
            sock_ok, sock_why = False, "%s: %s" % (type(exc).__name__, exc)

        ran = skipped = 0
        atomic = os.path.join(self.build_folder, "probe-atomic-table")
        listing_cases = []
        for table in ("filter", "nat", "broute"):
            _lits, chains = self._derive_table_help(table, hooknames)
            listing_cases.append(("-t %s -L" % table, ["-t", table, "-L"],
                                  [chain.strip() for chain in chains.split()],
                                  "Bridge table: %s" % table))
        for label, args, chains, table_line in listing_cases:
            rc, out, err = self._run(binary, args, env)
            if rc == 0 and table_line in out:
                missing = [c for c in chains
                           if not re.search(r"Bridge chain: %s, entries: \d+, policy: " % re.escape(c), out)]
                self.output.info(
                    "[kernel-probe] RUN  %-16s rc=0 chains=%s policy-lines=%s missing=%s"
                    % (label, chains, len(re.findall(r"Bridge chain: ", out)), missing))
                if missing:
                    raise ConanException(
                        "内核可用且 %s 返回 0，但缺少合法链的 listing 行：%s" % (label, missing))
                ran += 1
            else:
                self.output.info(
                    "[kernel-probe] SKIP %-16s reason=rc=%d stderr=%r socket=%s"
                    % (label, rc, err.strip()[:120], sock_why))
                skipped += 1
        # atomic 往返：--atomic-save 落盘后从文件再读回（纯用户态读文件路径）
        rc, out, err = self._run(binary, ["--atomic-file", atomic, "--atomic-save"], env)
        if rc == 0 and os.path.isfile(atomic) and os.path.getsize(atomic) > 0:
            rc2, out2, err2 = self._run(binary, ["--atomic-file", atomic, "-t", "filter", "-L"], env)
            ok = rc2 == 0 and "Bridge table: filter" in out2
            self.output.info(
                "[kernel-probe] RUN  atomic-file round trip rc=0 size=%d reread_rc=%d ok=%s"
                % (os.path.getsize(atomic), rc2, ok))
            if not ok:
                raise ConanException(
                    "内核可用且 --atomic-save 成功，但从 %s 读回失败：rc=%d stderr=%r"
                    % (atomic, rc2, err2.strip()[:200]))
            ran += 1
        else:
            self.output.info(
                "[kernel-probe] SKIP atomic-file round trip reason=rc=%d stderr=%r "
                "socket=%s" % (rc, err.strip()[:120], sock_why))
            skipped += 1
        if not sock_ok:
            self.output.info(
                "[kernel-probe] CAP_NET_RAW unavailable (%s) — the %d kernel-bound "
                "cases above were classified, never silently skipped" % (sock_why, skipped))
        self.output.info("[kernel-probe] HMBS_KERNEL_PROBE run=%d skip=%d" % (ran, skipped))

    # ── package ─────────────────────────────────────────────────────────
    def package(self):
        # `make install` must not run parallel on the OHOS worker: conan's
        # Autotools.install() defaults to -j<jobs> and on a loaded worker the
        # forked install/libtool children die with
        #   ./libtool: fork: Resource temporarily unavailable
        #   make[1]: *** [Makefile:1052: install-sysconfDATA] Error 127
        # (platform CI #106938 / #107452 -- the compile and the whole
        # [cli-golden] suite had already passed by then).  Same rationale as the
        # recipe's serial `make -j1` in build().
        Autotools(self).install(args=["-j1"])
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        self._install_public_headers()
        self._drop_libtool_archives()
        self._sign_ohos_elfs()

    def _install_public_headers(self):
        """安装上游 include/ 树（上游 Makefile.am 没有 include_HEADERS）。

        上游把 libebtc 作为 libtool 库交付，却从不安装它的头；要「用得起」
        这个库必须自己装。这里逐字节复制上游 tarball 里的 include/ 树，
        不做任何改写：ebtables_u.h（公共 API）、ethernetdb.h（ethertypes
        数据库接口）、linux/netfilter_bridge/**.h（ebtables 私有 UAPI 副本）
        与 linux/types.h。
        """
        srcdir = os.path.join(self.source_folder, "include")
        dstdir = os.path.join(self.package_folder, "include")
        copy(self, "*.h", src=srcdir, dst=dstdir, keep_path=True)
        installed = []
        for root, _dirs, files in os.walk(dstdir):
            for fname in files:
                installed.append(os.path.relpath(os.path.join(root, fname), dstdir))
        self.output.info("[headers] installed %d upstream headers into include/ "
                         "(Makefile.am declares no include_HEADERS)" % len(installed))

    def _drop_libtool_archives(self):
        """丢掉 .la：内含绝对构建路径，conan 消费者不需要它。"""
        removed = 0
        for root, _dirs, files in os.walk(self.package_folder):
            for fname in files:
                if fname.endswith(".la"):
                    os.remove(os.path.join(root, fname))
                    removed += 1
        self.output.info("[package] removed %d libtool archive(s) from the package" % removed)

    def _has_ohos_signature(self, path):
        with open(path, "rb") as handle:
            data = handle.read()
        return b".codesign" in data or b".note.ohos" in data

    def _sign_elf(self, path):
        """OHOS 自签名（E135/E517 + 硬坑 D）。

        `binary-sign-tool` 必须写到**另一个**输出文件：inFile==outFile 时会
        「自报成功但实际没签上」（dbmate/2.33.0 实证）。stderr 全量保留。
        """
        if not os.path.isfile(path) or os.path.islink(path):
            return False
        with open(path, "rb") as handle:
            if handle.read(4) != b"\x7fELF":
                return False
        if self._has_ohos_signature(path):
            os.chmod(path, 0o755)
            return True
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        objcopy = shutil.which("llvm-objcopy") or "/data/service/hnp/bin/llvm-objcopy"
        if not os.path.isfile(signer):
            raise ConanException("OHOS build requires binary-sign-tool at %s" % signer)
        signed = path + ".signed"
        if os.path.exists(signed):
            os.remove(signed)
        if os.path.isfile(objcopy):
            subprocess.run([objcopy, "--remove-section", ".codesign", path],
                           capture_output=True, timeout=60)
        res = subprocess.run([signer, "sign", "-selfSign", "1",
                              "-inFile", path, "-outFile", signed],
                             capture_output=True, text=True, timeout=300)
        if res.returncode != 0 or not os.path.isfile(signed) or os.path.getsize(signed) == 0:
            raise ConanException(
                "binary-sign-tool failed for %s: rc=%s stdout=%r stderr=%r"
                % (path, res.returncode, (res.stdout or "")[-300:], (res.stderr or "")[-300:]))
        os.replace(signed, path)
        os.chmod(path, 0o755)
        if not self._has_ohos_signature(path):
            raise ConanException("signature section missing after signing %s" % path)
        return True

    def _sign_ohos_elfs(self):
        """给交付的库 .so 与 bin/ 下的 ELF 逐个自签名。"""
        if not self._is_ohos:
            self.output.info("[sign] non-OHOS build: no .codesign step required")
            return
        targets = []
        libdir = os.path.join(self.package_folder, "lib")
        if os.path.isdir(libdir):
            targets += [os.path.join(libdir, n) for n in sorted(os.listdir(libdir))
                        if ".so" in n]
        bindir = os.path.join(self.package_folder, "bin")
        if os.path.isdir(bindir):
            targets += [os.path.join(bindir, n) for n in sorted(os.listdir(bindir))]
        signed = failed = 0
        for path in targets:
            if not os.path.isfile(path) or os.path.islink(path):
                continue
            if self._sign_elf(path):
                signed += 1
            else:
                failed += 1
                self.output.warning("[sign] not an ELF, skipped: %s" % path)
        self.output.info("[sign] signed %d/%d ELF files (skipped %d non-ELF/symlinks)"
                         % (signed, signed + failed, failed))

    def package_info(self):
        self.cpp_info.libs = ["ebtc"]
        self.cpp_info.set_property("cmake_file_name", "ebtables")
        self.cpp_info.set_property("cmake_target_name", "ebtables::ebtables")
        self.cpp_info.set_property("pkg_config_name", "ebtables")
        # 编译期写死的 ethertypes 路径（configure 的 --sysconfdir=/etc）
        self.cpp_info.set_property("ebtables_ethertypes_path", "/etc/ethertypes")
        # NOTE: bindirs is deliberately left at the default ["bin"] — the
        # software-level commands.json (R38/L0k) declares the delivered tools,
        # matching the merged glib/2.84 recipe.
