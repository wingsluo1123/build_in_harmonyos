# R8b — `__packed` 是内核 UAPI 的标注宏，OHOS sysroot 的 <linux/if_pppox.h> 用了它
# 却没有提供定义；用 `-D` 传带括号的展开式会被 autotools/libtool 的 shell 命令行撕开，
# 所以改成强制包含这个小头（内容不经 shell）。glibc 的头本来就展开成属性，此头为无害空操作。
_OHOS_UAPI_COMPAT_H = """/* OHOS UAPI compatibility shim (generated by the conan recipe) */
#ifndef OHOS_UAPI_COMPAT_H
#define OHOS_UAPI_COMPAT_H
#ifndef __packed
#define __packed __attribute__((packed))
#endif
#endif /* OHOS_UAPI_COMPAT_H */
"""

