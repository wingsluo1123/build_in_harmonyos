#!/data/service/hnp/bin/bash
# Consumer verification for jigsaw-generator/0.2.7.
#
# usage: test.sh [--auto | --execute | --static-only]
#   --auto         static layer always; runtime layer iff the host has a
#                  python3 with an importable yaml module
#   --execute      static layer + runtime layer (host must have python3+yaml)
#   --static-only  static layer only
#
# Static layer
#   1  bin/jigsaw-generate exists, is a regular file and is executable
#   2  the entry script has a python3 shebang
#   3  no un-substituted @pkgdatadir@ / @PACKAGE_VERSION@ markers remain
#   4  the baked-in pkgdatadir points inside the package and exists
#   5  the python package (jigsaw/generate.py, __init__.py, appdirs.py) is installed
#      and no host .pyc leaked into the package
#   6  templates/default_config.ini is installed and >= 6 layout .yaml files
#   7  share/man/man1/jigsaw-generate.1 is installed and describes the tool
#   8  (host has python3) ast.parse syntax check of entry + package modules
#   9  (host has python3+yaml) every packaged YAML parses (templates + examples)
#
# Runtime layer (--auto/--execute; host needs python3+yaml)
#  10  `jigsaw-generate -v` reports version 0.2.7
#  11  `jigsaw-generate --help` prints the usage (puzzlefile[.yaml])
#  12  generation over examples/puzzle-smallhexagon.yaml with --nomakepdf
#      (upstream gates the whole .tex pipeline on the makepdf option, so no
#      LaTeX is invoked): exit 0 and >= 1 .md output
#  13  full makepdf pipeline vs a stub pdflatex: exit 0, 3 .pdf artifacts,
#      intermediate .tex cleaned by upstream (clean defaults to true)
#
# HarmonyOS-specific consumer use case (--auto/--execute; needs python3+yaml)
#  14  end-to-end consumer run over a shipped example puzzle with
#      --nomakepdf: exit 0, >= 1 .md artifact that is non-empty (usable
#      output), i.e. a complete consumer workflow, not a bare assertion

set -e
set -o pipefail
# never let the test's own python invocations write bytecode into the package
export PYTHONDONTWRITEBYTECODE=1

MODE="${1:---auto}"

HAVE_PY=0
if command -v python3 >/dev/null 2>&1 && python3 -c "import yaml" 2>/dev/null; then
    HAVE_PY=1
fi

BIN="$(command -v jigsaw-generate || true)"
PKGROOT="$(dirname "$(dirname "$BIN")")"
DATA="$PKGROOT/lib/jigsaw-generator"

echo "== static layer (mode=$MODE, host python3+yaml: $HAVE_PY)"
test -n "$BIN"
test -f "$BIN"
test -x "$BIN"                                                    # [1]
echo "bin: $BIN"
head -1 "$BIN" | grep -q "python3"                                 # [2]
! grep -q "@pkgdatadir@\|@PACKAGE_VERSION@" "$BIN"                # [3]
BAKED="$(sed -n "s/^pkgdatadir = '\(.*\)'$/\1/p" "$BIN" | head -1)"
test -n "$BAKED"
test "$BAKED" = "$PKGROOT/lib/jigsaw-generator"                   # [4]
test -d "$BAKED"
test -f "$DATA/jigsaw/generate.py"                                # [5]
test -f "$DATA/jigsaw/__init__.py"
test -f "$DATA/jigsaw/appdirs.py"
# the package must not ship host-generated bytecode
PYC="$(find "$PKGROOT" -name '*.pyc' | wc -l)"
test "$PYC" -eq 0
test -f "$DATA/templates/default_config.ini"                      # [6]
LAYOUT_YAML="$(find "$DATA/templates" -maxdepth 1 -name '*-layout.yaml' | wc -l)"
test "$LAYOUT_YAML" -ge 6
test -f "$PKGROOT/share/man/man1/jigsaw-generate.1"               # [7]
test -s "$PKGROOT/share/man/man1/jigsaw-generate.1"
# The man page's NAME entry is "jigsaw-generator" (the tool name as the man
# page spells it; the installed binary is jigsaw-generate).
grep -qi "jigsaw-generator" "$PKGROOT/share/man/man1/jigsaw-generate.1"
echo "static layout: ok"

if [ "$HAVE_PY" -eq 1 ]; then
    # [8] syntax check via ast.parse (no __pycache__ written into the package)
    python3 - "$BIN" "$DATA/jigsaw/generate.py" "$DATA/jigsaw/appdirs.py" <<'EOF'
import ast, sys
for f in sys.argv[1:]:
    with open(f, encoding="utf-8") as fh:
        ast.parse(fh.read(), filename=f)
print("syntax ok: %d files" % (len(sys.argv) - 1))
EOF
    # [9] every packaged YAML must parse (templates + shipped examples)
    PKGROOT_EX="$PKGROOT" python3 - <<'EOF'
import glob, os, yaml
base = os.environ["PKGROOT_EX"]
files = sorted(glob.glob(os.path.join(base, "lib/jigsaw-generator/templates/*.yaml")))
files += sorted(glob.glob(os.path.join(
    base, "share/doc/jigsaw-generator/examples/*.yaml")))
assert files, "no packaged YAML files found"
for f in files:
    with open(f, encoding="utf-8") as fh:
        yaml.safe_load(fh)
print("yaml parse ok: %d files" % len(files))
EOF
fi

if [ "$MODE" = "--static-only" ]; then
    echo "PASS: jigsaw-generator consumer static verification; runtime layer skipped"
    exit 0
fi

if [ "$HAVE_PY" -ne 1 ]; then
    echo "no python3+yaml on this host; runtime layer deferred " \
         "(static assertions enforced)"
    exit 0
fi

echo
echo "== runtime layer"
OUTV="$(mktemp 2>/dev/null || echo ./jg_ver.txt)"
"$BIN" -v > "$OUTV" 2>&1
head -2 "$OUTV"
grep -q "version 0.2.7" "$OUTV"                                    # [10]
rm -f "$OUTV"

OUTH="$(mktemp 2>/dev/null || echo ./jg_help.txt)"
"$BIN" --help > "$OUTH" 2>&1
grep -q "puzzlefile" "$OUTH"                                       # [11]
rm -f "$OUTH"

# [12] real generation without LaTeX (--nomakepdf)
WORK="$(mktemp -d 2>/dev/null || mktemp -d ./jg_work.XXXXXX)"
set +e
( cd "$WORK" && "$BIN" -o out --nomakepdf \
    "$PKGROOT/share/doc/jigsaw-generator/examples/puzzle-smallhexagon.yaml" \
    > gen.log 2>&1 )
RC=$?
set -e
echo "nomakepdf run exit=$RC"
head -10 "$WORK/gen.log"
test "$RC" -eq 0
MD="$(find "$WORK" -name '*.md' | wc -l)"
test "$MD" -ge 1                                                   # [12]
echo "md files generated: $MD"

# [13] full makepdf pipeline against a stub pdflatex: proves the tex
# generation, the pdflatex invocation and the surviving artifacts.
# Upstream runlatex() removes the intermediate .tex files afterwards (its
# 'clean' option defaults to true; with a real pdflatex the .pdf is what
# survives), so the stub stands in for pdflatex by creating the .pdf.
cat > "$WORK/pdflatex" <<'EOF'
#!/bin/sh
for a in "$@"; do
  case "$a" in
    *.tex) touch "$a.pdf" ;;
  esac
done
exit 0
EOF
chmod +x "$WORK/pdflatex"
set +e
( cd "$WORK" && PATH="$WORK:$PATH" "$BIN" -o out2 \
    "$PKGROOT/share/doc/jigsaw-generator/examples/puzzle-smallhexagon.yaml" \
    > gen2.log 2>&1 )
RC2=$?
set -e
echo "makepdf(stub) run exit=$RC2"
head -10 "$WORK/gen2.log"
test "$RC2" -eq 0
PDF="$(find "$WORK" -name '*.pdf' | wc -l)"
test "$PDF" -ge 3                                                  # [13]
TEX="$(find "$WORK" -name '*.tex' | wc -l)"
test "$TEX" -eq 0   # upstream runlatex cleans intermediate .tex (clean defaults true)
echo "pdf artifacts: $PDF; intermediate .tex cleaned by upstream: $TEX remain"
rm -rf "$WORK"

# [14] HarmonyOS-specific consumer use case (end-to-end): a real run
# over a shipped example puzzle that verifies the produced .md artifact
# is a non-empty usable output, i.e. a complete consumer workflow rather
# than a bare existence assertion.
echo
echo "== harmony-specific consumer use case (end-to-end)"
WORK2="$(mktemp -d 2>/dev/null || mktemp -d ./jg_ohos.XXXXXX)"
set +e
( cd "$WORK2" && "$BIN" -o hout --nomakepdf \
    "$PKGROOT/share/doc/jigsaw-generator/examples/puzzle-smallhexagon.yaml" \
    > hgen.log 2>&1 )
RC3=$?
set -e
echo "harmony consumer run exit=$RC3"
head -8 "$WORK2/hgen.log"
test "$RC3" -eq 0
HMD="$(find "$WORK2" -name '*.md' | wc -l)"
test "$HMD" -ge 1
HMDSRC="$(find "$WORK2" -name '*.md' | head -1)"
test -s "$HMDSRC"   # generated artifact is non-empty, usable end-to-end output
echo "harmony consumer use case ok: $HMD md artifact(s), content non-empty"
rm -rf "$WORK2"

echo
echo "PASS: jigsaw-generator consumer verification (static + runtime + harmony-specific use case)"
