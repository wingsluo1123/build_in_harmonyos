#!/usr/bin/env python3
"""Conan recipe — lasem 0.6.0 (Meson)

SVG and MathML rendering library with a DOM-like API (pure C).
Upstream: LasemProject/lasem 0.6.0 (meson build, GNOME stack).

OHOS adaptation (meson, verified pattern from lasem-render 0.5.1):
- Dependencies come from Conan pkg-config only (wrap_mode=nodownload);
  introspection/documentation/viewer are disabled (need
  gobject-introspection/gi-docgen/gtk4, unavailable on OHOS).
- itex2mml (LaTeX to MathML) is generated by flex/bison tool_requires.
- po/ translations need xgettext: gettext tool_requires provides it.
- gnome.mkenums_simple needs glib-mkenums: exposed via the generated
  glib-2.0.pc variable (same approach as pango 1.56.4).
- conan MesonToolchain does not write ar/ranlib into the native file,
  so absolute llvm-ar/llvm-ranlib paths are injected (cairo precedent).
- OHOS XPM requires signed ELF binaries: build-tree test binaries and
  shared libs are signed before `meson test`, installed .so/bin after
  `meson install`.
- Upstream tests run in build(): `meson test` executes the 4 registered
  tests (dom/str/filter/suite); the marker below reports real numbers.
"""

import json
import os
import re
import shutil
import stat
import subprocess
import tempfile
import time

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout
from conan.tools.meson import Meson, MesonToolchain


class LasemConan(ConanFile):
    name = "lasem"
    version = "0.6.0"
    description = "SVG and MathML rendering library with DOM-like API"
    license = "LGPL-2.1-or-later"
    homepage = "https://github.com/LasemProject/lasem"
    url = "https://github.com/LasemProject/lasem"
    topics = ("svg", "mathml", "rendering", "cairo", "pango")
    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        # Pure C library: no C++ standard library involvement.
        self.settings.rm_safe("compiler.cppstd")
        self.settings.rm_safe("compiler.libcxx")
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "lasem supports Linux and OHOS, not %s" % self.settings.os
            )

    def requirements(self):
        # R37 non-X lineage (binary-available, no X11 chain):
        # pango/1.50.14.1.1 pins cairo/1.18.4 (xlib DISABLED) and
        # harfbuzz/14.2.0.1.1.1, both bound to glib shared=True so the
        # whole graph reuses registry binaries. pango/1.50.14.1.1.1 would
        # pin cairo/1.18.4.1 (xlib ENABLED) and conflict with our direct
        # cairo/1.18.4 pin ("Version conflict ... originates from pango").
        # cairo/1.18.4: lasem only renders to cairo image surfaces, never
        # cairo-xlib. 1.18.4.1 pulls libx11/6.4.0 + libxext/6.4.0 +
        # libxrender/0.9.12, whose autotools configure fails on OHOS
        # ("C compiler cannot create executables") with no prebuilt binary
        # available. Same-family lasem-render 0.5.1 proves 1.18.4.
        # transitive_headers=True: lasem public headers include
        # <cairo.h>, <pango/pangocairo.h>, <glib-object.h>; without the
        # trait Conan marks them headers=False for consumers.
        self.requires("glib/2.84.0.1", transitive_headers=True)
        self.requires("cairo/1.18.4", transitive_headers=True)
        self.requires("pango/1.50.14.1.1", transitive_headers=True)
        self.requires("harfbuzz/14.2.0.1.1.1", transitive_headers=True)
        self.requires("gdk-pixbuf/2.44.6.1.1", transitive_headers=True)
        self.requires("libxml2/2.15.3", transitive_headers=True)

    def build_requirements(self):
        self.tool_requires("meson/1.11.0")
        # itex2mml subdir generates the lexer/parser with flex/bison.
        # flex/2.6.4.2 (not .4): the workspace-internal flex/2.6.4 recipe
        # (archives/f/flex/2.6.4) publishes only OHOS binaries (yosys
        # 0.66 precedent: build-context tool_requires find OHOS/armv8
        # only with the default build profile), so the build-machine flex
        # never materialises and meson reports "Program flex found: NO".
        # .4.2 exists only in ConanCenter, guaranteeing a Linux
        # build-machine binary (zimpl 3.7.1 precedent).
        self.tool_requires("flex/2.6.4.2")
        self.tool_requires("bison/3.8.2")
        # flex 运行时 exec 其编译期写死的 m4 绝对路径 (本次真机:
        # /storage/.../.cache/conan2/p/m42d92622f4ed01/p/bin/m4), 该路径
        # 指向 flex 自身构建时的旧缓存, 在本机不存在, 故报
        # "flex: fatal internal error, exec of .../m4 failed" (code=141)。
        # flex 的 build_require(m4) 不会传递给下游, 必须在此直接声明
        # m4/1.4.19, 由其 buildenv(M4 变量)+ bindir 提供可用的 Linux
        # build 机 m4; flex 优先读 $M4 环境变量而非编译期硬编码路径。
        self.tool_requires("m4/1.4.19")
        # po/ i18n.gettext() runs xgettext at build time.
        self.tool_requires("gettext/0.22.5.1")
        # True-machine/CI workers have no system pkg-config on PATH (HMBS
        # only injects cmake/make/ninja/python3); meson glib-2.0 lookup
        # fails with "Pkg-config for machine host machine not found".
        # Pull pkgconf from the registry (libapk 3.0.6 same-fingerprint
        # precedent) and expose it under the canonical pkg-config name.
        self.tool_requires("pkgconf/3.0.5")

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # Parallelism cap: conan Meson helper appends -j<tools.build:jobs>,
        # which defaults to os.cpu_count() (CI worker 20 / cgroup affinity
        # much smaller => oversubscription, ninja dies with
        # "ninja: fatal: posix_spawn: Resource temporarily unavailable",
        # CI #93729). Cap-4 still hit EAGAIN in the compile phase
        # (CI #94032: `meson compile -j4` -> ninja posix_spawn), so
        # serialize to 1 for this small pure-C lib; HMBS true-machine
        # already injects 1 so it stays serial there.
        _jobs = self.conf.get("tools.build:jobs", default=None, check_type=int)
        _jobs = max(1, min(_jobs or (os.cpu_count() or 1), 1))
        self.conf.define("tools.build:jobs", _jobs)
        self.output.info("capped tools.build:jobs to %s" % _jobs)
        self._ensure_pkg_config_shim()
        PkgConfigDeps(self).generate()
        self._inject_pc_var()
        self._patch_glib_pc_lintl()
        tc = MesonToolchain(self)
        # Never fetch meson wraps: every dependency comes from Conan.
        tc.project_options["wrap_mode"] = "nodownload"
        tc.project_options["default_library"] = (
            "shared" if self.options.shared else "static"
        )
        # gobject-introspection / gi-docgen / gtk4 are unavailable on OHOS.
        tc.project_options["introspection"] = "disabled"
        tc.project_options["documentation"] = "disabled"
        tc.project_options["viewer"] = "disabled"
        tc.generate()
        self._inject_meson_ar()

    def _inject_pc_var(self):
        # conan PkgConfigDeps only writes standard .pc variables, but
        # meson gnome.mkenums_simple locates glib-mkenums through the
        # glib-2.0.pc `glib_mkenums` variable (pango 1.56.4 precedent).
        import os as _os

        for _pv in ["glib-2.0:glib_mkenums=${bindir}/glib-mkenums"]:
            _pc, _kv = _pv.split(":", 1)
            _path = _os.path.join(self.generators_folder, _pc + ".pc")
            if not _os.path.isfile(_path):
                self.output.warning("pc-var: %s.pc not found, skip %s" % (_pc, _kv))
                continue
            with open(_path, encoding="utf-8") as _f:
                _txt = _f.read()
            if _kv.split("=")[0] + "=" in _txt:
                continue
            _i = _txt.find("\nName:")
            _new = (_txt[:_i] + "\n" + _kv + _txt[_i:]) if _i >= 0 else (_kv + "\n" + _txt)
            with open(_path, "w", encoding="utf-8") as _f:
                _f.write(_new)

    def _patch_glib_pc_lintl(self):
        # glib's proxy-libintl exports the g_libintl_* symbols through the
        # glib package's libintl.so; PkgConfigDeps emits glib-2.0.pc without
        # -lintl, so the lasem-render-0.6 CLI link fails with undefined
        # g_libintl_bindtextdomain / bind_textdomain_codeset / textdomain /
        # gettext symbols (same failure + fix as lasem-render 0.5.1 and
        # gdk-pixbuf 2.44.6.1.1). Append -lintl to the Libs line so meson
        # links the proxy-intl lib coming from the glib package libdir
        # (already on the Libs -L path).
        glib_pc = os.path.join(self.generators_folder, "glib-2.0.pc")
        if not os.path.isfile(glib_pc):
            self.output.warning("glib-2.0.pc not found; skip -lintl patch")
            return
        with open(glib_pc, encoding="utf-8") as handle:
            content = handle.read()
        if re.search(r"^Libs:.*-lintl", content, flags=re.M):
            return
        if re.search(r"^Libs:", content, flags=re.M):
            content = re.sub(
                r"^Libs:.*$", lambda m: m.group(0) + " -lintl",
                content, count=1, flags=re.M)
        with open(glib_pc, "w", encoding="utf-8") as handle:
            handle.write(content)
        self.output.info("glib-2.0.pc: appended -lintl to Libs (proxy-libintl symbols)")

    def _find_usable_exe(self, candidates):
        # Return the first candidate that exists and is executable.
        # Bare names are resolved via PATH (which HMBS prepends with the
        # probed tool dirs); absolute paths are checked directly.
        for cand in candidates:
            if not cand:
                continue
            cand = cand.strip().strip("'\"")
            if not cand:
                continue
            if os.path.sep in cand or "/" in cand:
                if os.path.isfile(cand) and os.access(cand, os.X_OK):
                    return cand
                continue
            found = shutil.which(cand)
            if found and os.path.isfile(found):
                return found
        return ""

    def _resolve_compilers(self, conf):
        c_conf = (conf.get("c") or "").strip()
        cpp_conf = (conf.get("cpp") or "").strip()
        c_cands = [
            c_conf,
            os.environ.get("CC", ""),
            shutil.which("clang") or "",
            shutil.which("cc") or "",
            "/data/service/hnp/bin/clang",
        ]
        # HMBS-managed wrapper dir appears first on PATH (see preflight
        # HMBS_BUILD_TOOLS); also probe it explicitly in case PATH is thin.
        for _d in ("/storage/Users/currentUser/usr/local/bin",
                   os.path.expanduser("~/usr/local/bin")):
            c_cands.append(os.path.join(_d, "clang"))
        cpp_cands = [
            cpp_conf,
            os.environ.get("CXX", ""),
            shutil.which("clang++") or "",
            shutil.which("c++") or "",
            "/data/service/hnp/bin/clang++",
        ]
        for _d in ("/storage/Users/currentUser/usr/local/bin",
                   os.path.expanduser("~/usr/local/bin")):
            cpp_cands.append(os.path.join(_d, "clang++"))
        c_hit = self._find_usable_exe(c_cands)
        cpp_hit = self._find_usable_exe(cpp_cands)
        return c_conf, cpp_conf, c_hit, cpp_hit

    def _discover_build_program(self, names, build_dep=""):
        # Search PATH first, then every build-requirement bindir, then the
        # named build-requirement package folder, then well-known system
        # dirs. Returns absolute path or "".
        # Lesson from 3 failed preflight rounds: generate()-phase PATH does
        # NOT contain conan tool bindirs and the old code only checked the
        # single named dep, so flex stayed "not found" while bison happened
        # to resolve. The new code enumerates ALL build deps plus the true
        # machine's fixed tool dirs (/data/service/hnp/bin per boxes/2.3.1
        # and genders notes) instead of assuming PATH is complete.
        if isinstance(names, str):
            names = [names]
        for nm in names:
            hit = shutil.which(nm)
            if hit and os.path.isfile(hit):
                return hit
        try:
            for _bdep in self.dependencies.build.values():
                _pf = getattr(_bdep, "package_folder", None)
                if not _pf:
                    continue
                for nm in names:
                    for sub in ("bin/%s" % nm, "%s" % nm):
                        cand = os.path.join(str(_pf), sub)
                        if os.path.isfile(cand):
                            return cand
        except Exception:
            pass
        if build_dep:
            try:
                bdep = self.dependencies.build.get(build_dep)
                if bdep is not None and getattr(bdep, "package_folder", None):
                    for nm in names:
                        for sub in ("bin/%s" % nm, "%s" % nm):
                            cand = os.path.join(str(bdep.package_folder), sub)
                            if os.path.isfile(cand):
                                return cand
            except Exception:
                pass
        for _d in ("/data/service/hnp/bin",
                   "/storage/Users/currentUser/.harmonybrew/bin",
                   os.path.expanduser("~/.harmonybrew/bin"),
                   "/storage/Users/currentUser/usr/local/bin",
                   os.path.expanduser("~/usr/local/bin"),
                   "/usr/local/bin", "/usr/bin"):
            for nm in names:
                cand = os.path.join(_d, nm)
                if os.path.isfile(cand):
                    return cand
        return ""

    def _export_build_tools_path(self):
        # Meson child (via self.run) inherits conan buildenv, but our own
        # shutil.which probes and meson's native-file fallback both depend
        # on the Python-process PATH. Prepend every build-dep bindir plus
        # the true-machine fixed tool dirs so bare find_program('flex')
        # succeeds via PATH even without ini injection.
        dirs = []
        try:
            for _bdep in self.dependencies.build.values():
                _pf = getattr(_bdep, "package_folder", None)
                if not _pf:
                    continue
                _b = os.path.join(str(_pf), "bin")
                if os.path.isdir(_b) and _b not in dirs:
                    dirs.append(_b)
        except Exception as e:
            self.output.warning("enumerate build bindirs failed: %s" % e)
        for _d in ("/data/service/hnp/bin",
                   "/storage/Users/currentUser/.harmonybrew/bin",
                   os.path.expanduser("~/.harmonybrew/bin"),
                   "/storage/Users/currentUser/usr/local/bin"):
            if os.path.isdir(_d) and _d not in dirs:
                dirs.append(_d)
        cur = os.environ.get("PATH", "")
        parts = [p for p in cur.split(os.pathsep) if p] if cur else []
        added = [d for d in dirs if d not in parts]
        if added:
            os.environ["PATH"] = os.pathsep.join(added + parts)
            self.output.info("prepended %d build-tool dirs to PATH" % len(added))
        for _prog in ("flex", "bison", "xgettext", "pkg-config", "pkgconf", "m4"):
            self.output.info("which %s -> %s" % (_prog, shutil.which(_prog) or "NOT-FOUND"))
        self._ensure_m4_env()

    def _ensure_m4_env(self):
        # flex 在运行时 exec 编译期硬编码的 m4 绝对路径; 该路径在真机
        # 不存在时报 "fatal internal error, exec of .../m4 failed"。
        # flex 优先使用 $M4 环境变量, 故在此将其指向本包 build 上下文
        # 的真实 m4 (m4/1.4.19 tool_requires, 否则只有 flex 构建期的旧
        # 缓存路径可用)。bison 同样在运行时调用 m4, 一并受益。
        # bison 编译内置 pkgdatadir 为 /share/bison (--prefix= 导致),
        # 实际数据在包内 share/bison, 必须重定向 BISON_PKGDATADIR
        # (ball/zimpl/canl-c/bison 自身 test_package 同款做法)。
        # 顺序: 已有可用 $M4 > build 依赖 m4 包 > PATH 上的 m4。
        cur = (os.environ.get("M4") or "").strip()
        if cur and os.path.isfile(cur):
            self.output.info("M4 already set: %s" % cur)
        else:
            hit = self._discover_build_program(["m4", "gm4"], "m4")
            if not hit:
                try:
                    mdep = self.dependencies.build.get("m4/1.4.19")
                    if mdep is None:
                        mdep = self.dependencies.build.get("m4")
                    if mdep is not None and getattr(mdep, "package_folder", None):
                        for cand in (os.path.join(str(mdep.package_folder), "bin", "m4"),
                                     os.path.join(str(mdep.package_folder), "bin", "gm4")):
                            if os.path.isfile(cand):
                                hit = cand
                                break
                except Exception as e:
                    self.output.warning("lookup m4 build dep failed: %s" % e)
            if hit:
                os.environ["M4"] = hit
                self.output.info("exported M4=%s for flex/bison" % hit)
            else:
                self.output.warning("m4 binary not found; flex may fail with exec m4 error")
        # BISON_PKGDATADIR: 每次都按当前 build 依赖重算, 覆盖旧值。
        try:
            bdep = self.dependencies.build.get("bison/3.8.2")
            if bdep is None:
                bdep = self.dependencies.build.get("bison")
            if bdep is not None and getattr(bdep, "package_folder", None):
                for sub in ("share/bison", "usr/share/bison", "res/share/bison"):
                    cand = os.path.join(str(bdep.package_folder), *sub.split("/"))
                    probe = os.path.join(cand, "m4sugar", "m4sugar.m4")
                    if os.path.isfile(probe):
                        os.environ["BISON_PKGDATADIR"] = cand
                        self.output.info("exported BISON_PKGDATADIR=%s" % cand)
                        return os.environ.get("M4", "")
                # 包目录存在但未找到 m4sugar.m4: 记录实际布局供诊断。
                try:
                    listed = os.listdir(str(bdep.package_folder))
                except OSError:
                    listed = []
                self.output.warning("bison pkgdatadir probe missed m4sugar.m4; pkg root=%s content=%s"
                                    % (bdep.package_folder, listed))
        except Exception as e:
            self.output.warning("lookup bison build dep failed: %s" % e)
        return os.environ.get("M4", "")

    def _pkg_config_binary(self):
        # Prefer the hmbs-shims/pkg-config shim (canonical name meson
        # probes), fall back to PATH pkg-config/pkgconf, then to the
        # pkgconf build-requirement package folder (generate() may run
        # before the tool package is downloaded, so all are best-effort).
        for cand in (os.path.join(getattr(self, "build_folder", "") or "",
                                  "hmbs-shims", "pkg-config"),
                     shutil.which("pkg-config") or "",
                     shutil.which("pkgconf") or ""):
            if cand and os.path.isfile(cand) and os.access(cand, os.X_OK):
                return cand
        try:
            bdep = self.dependencies.build.get("pkgconf")
            if bdep is not None and getattr(bdep, "package_folder", None):
                cand = os.path.join(str(bdep.package_folder), "bin", "pkgconf")
                if os.path.isfile(cand):
                    return cand
        except Exception:
            pass
        return ""

    def _ensure_pkg_config_shim(self):
        # pkgconf/3.0.5 ships bin/pkgconf WITHOUT a bin/pkg-config alias,
        # while meson probes the `pkg-config` name. Provide a hmbs-shims
        # dir with pkg-config -> pkgconf (symlink first, HMBS symlink cap=1;
        # copyfile fallback for chmod=0/HMDFS) and export it on PATH plus
        # PKG_CONFIG/PKG_CONFIG_PATH so both meson and child processes
        # find it (libapk 3.0.6 same-fingerprint precedent, adapted to
        # lasem's build_folder layout).
        base = getattr(self, "build_folder", None) or os.environ.get("TMPDIR") or "/tmp"
        shim_dir = os.path.join(base, "hmbs-shims")
        try:
            os.makedirs(shim_dir, exist_ok=True)
        except OSError:
            return ""
        pkgconf_bin = ""
        try:
            bdep = self.dependencies.build.get("pkgconf")
            if bdep is not None and getattr(bdep, "package_folder", None):
                cand = os.path.join(str(bdep.package_folder), "bin", "pkgconf")
                if os.path.isfile(cand):
                    pkgconf_bin = cand
        except Exception:
            pass
        if not pkgconf_bin:
            pkgconf_bin = shutil.which("pkgconf") or shutil.which("pkg-config") or ""
        if not pkgconf_bin or not os.path.isfile(pkgconf_bin):
            # generate() can run before the tool package lands; export the
            # generators dir for PKG_CONFIG_PATH and let build() create
            # the real shim once pkgconf is on disk.
            try:
                gf = getattr(self, "generators_folder", "")
                if gf:
                    prev = os.environ.get("PKG_CONFIG_PATH", "")
                    if gf not in prev.split(os.pathsep):
                        os.environ["PKG_CONFIG_PATH"] = gf + (os.pathsep + prev if prev else "")
            except Exception:
                pass
            return shim_dir
        link = os.path.join(shim_dir, "pkg-config")
        try:
            if os.path.islink(link) or os.path.isfile(link):
                try:
                    os.remove(link)
                except OSError:
                    pass
            try:
                os.symlink(pkgconf_bin, link)
            except (OSError, NotImplementedError):
                shutil.copyfile(pkgconf_bin, link)
            self.output.info("pkg-config shim: %s -> %s" % (link, pkgconf_bin))
        except Exception as exc:
            self.output.warning("pkg-config shim failed: %s" % exc)
            return ""
        try:
            if shim_dir not in os.environ.get("PATH", "").split(os.pathsep):
                os.environ["PATH"] = shim_dir + os.pathsep + os.environ.get("PATH", "")
            os.environ["PKG_CONFIG"] = link
            gf = getattr(self, "generators_folder", "")
            if gf:
                prev = os.environ.get("PKG_CONFIG_PATH", "")
                parts = [p for p in prev.split(os.pathsep) if p] if prev else []
                if gf not in parts:
                    parts.insert(0, gf)
                os.environ["PKG_CONFIG_PATH"] = os.pathsep.join(parts)
        except Exception:
            pass
        return shim_dir

    def _inject_meson_ar(self):
        # conan MesonToolchain does not write tools.build ar/ranlib into
        # the native file, so meson probes bare "llvm-ar" which is not on
        # PATH (clang lives in /data/service/hnp/bin). Inject absolute
        # paths (cairo 1.18.4 precedent).
        # 2026-10-11 robustness fix: the CI profile pins
        # /data/service/hnp/bin/clang(+clang++), but preflight proved that
        # path can be absent on the real machine
        # (meson: "No such file or directory: '/data/service/hnp/bin/clang'").
        # When the pinned compiler is missing, discover a usable clang via
        # conf -> CC/CXX -> PATH -> well-known locations and rewrite the
        # c/cpp entries in BOTH native and cross files instead of letting
        # meson fail. ar/ranlib get the same treatment (conf -> which ->
        # compiler bindir).
        conf = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
        c_conf, cpp_conf, c_hit, cpp_hit = self._resolve_compilers(conf)
        self.output.info("meson compilers: conf c=%s cpp=%s -> resolved c=%s cpp=%s"
                         % (c_conf, cpp_conf, c_hit, cpp_hit))
        ar = conf.get("ar") or ""
        ranlib = conf.get("ranlib") or ""
        if ar and not (os.path.isfile(ar) and os.access(ar, os.X_OK)):
            self.output.warning("conf ar missing (%s); will re-discover" % ar)
            ar = ""
        if ranlib and not (os.path.isfile(ranlib) and os.access(ranlib, os.X_OK)):
            self.output.warning("conf ranlib missing (%s); will re-discover" % ranlib)
            ranlib = ""
        if not ar:
            ar = (self._find_usable_exe([shutil.which("llvm-ar") or ""])
                  or self._find_usable_exe([shutil.which("ar") or ""]))
        if not ranlib:
            ranlib = (self._find_usable_exe([shutil.which("llvm-ranlib") or ""])
                      or self._find_usable_exe([shutil.which("ranlib") or ""]))
        for _bindir in [os.path.dirname(c_hit) if c_hit else "",
                        os.path.dirname(conf.get("c") or "")]:
            if not _bindir:
                continue
            if not ar:
                _cand = os.path.join(_bindir, "llvm-ar")
                if os.path.isfile(_cand) and os.access(_cand, os.X_OK):
                    ar = _cand
            if not ranlib:
                _cand = os.path.join(_bindir, "llvm-ranlib")
                if os.path.isfile(_cand) and os.access(_cand, os.X_OK):
                    ranlib = _cand
        for nf_name in ("conan_meson_native.ini", "conan_meson_cross.ini"):
            nf = os.path.join(self.generators_folder, nf_name)
            if not os.path.isfile(nf):
                continue
            with open(nf, encoding="utf-8") as f:
                content = f.read()
            orig = content
            # Repair missing compilers: only rewrite an entry whose pinned
            # path does not exist; never override a working toolchain.
            if c_hit:
                m = re.search(r"(?m)^c\s*=\s*['\"]([^'\"]+)['\"]", content)
                if m and not os.path.isfile(m.group(1)):
                    content = re.sub(r"(?m)^c\s*=.*$",
                                     "c = '%s'" % c_hit, content, count=1)
                    self.output.warning("%s: c %s missing -> %s"
                                        % (nf_name, m.group(1), c_hit))
                elif not m and "[binaries]" in content:
                    content = content.replace(
                        "[binaries]\n",
                        "[binaries]\nc = '%s'\n" % c_hit, 1)
            if cpp_hit:
                m = re.search(r"(?m)^cpp\s*=\s*['\"]([^'\"]+)['\"]", content)
                if m and not os.path.isfile(m.group(1)):
                    content = re.sub(r"(?m)^cpp\s*=.*$",
                                     "cpp = '%s'" % cpp_hit, content, count=1)
                    self.output.warning("%s: cpp %s missing -> %s"
                                        % (nf_name, m.group(1), cpp_hit))
                elif not m and "[binaries]" in content:
                    content = content.replace(
                        "[binaries]\n",
                        "[binaries]\ncpp = '%s'\n" % cpp_hit, 1)
            if ar and "\nar =" not in content and "[binaries]" in content:
                insert = "[binaries]\nar = '%s'\n" % ar
                if ranlib:
                    insert += "ranlib = '%s'\n" % ranlib
                content = content.replace("[binaries]\n", insert, 1)
            elif ranlib and "\nranlib =" not in content and "[binaries]" in content \
                    and "\nar =" in content:
                content = content.replace(
                    "\nar =", "\nranlib = '%s'\nar =" % ranlib, 1)
            _pc = self._pkg_config_binary()
            if _pc and "\npkgconfig =" not in content and "[binaries]" in content:
                content = content.replace(
                    "[binaries]\n",
                    "[binaries]\npkgconfig = '%s'\n" % _pc.replace("'", "''"), 1)
                self.output.info("%s: injected pkgconfig %s" % (nf_name, _pc))
            # itex2mml uses generator(flex)/generator(bison); meson probes
            # them via find_program. Preflight proved bison resolves via
            # PATH but flex reports not-found, aborting at
            # itex2mml/meson.build:13 generator(). Pin both (plus xgettext
            # for po/) into [binaries] so the probe is deterministic and
            # logged, instead of relying on bare-name PATH lookup alone.
            for _prog, _dep in (("flex", "flex"), ("bison", "bison"),
                                ("xgettext", "gettext")):
                if ("\n%s =" % _prog) in content:
                    continue
                _hit = self._discover_build_program(_prog, _dep)
                if _hit and "[binaries]" in content:
                    content = content.replace(
                        "[binaries]\n",
                        "[binaries]\n%s = '%s'\n" % (_prog, _hit.replace("'", "''")), 1)
                    self.output.info("%s: injected %s %s" % (nf_name, _prog, _hit))
                elif not _hit:
                    self.output.warning("%s: build program %s not found (dep %s)"
                                        % (nf_name, _prog, _dep))
            if content != orig:
                with open(nf, "w", encoding="utf-8") as f:
                    f.write(content)
                self.output.info("%s: repaired binaries (c=%s ar=%s)"
                                 % (nf_name, c_hit, ar))

    @staticmethod
    def _meson_configure_transient_markers():
        return ("Resource temporarily unavailable", "posix_spawn failed")

    def _meson_configure_failed_transient(self):
        # configure-phase EAGAIN leaves its fingerprint in meson-log.txt,
        # while ConanException itself only says "Error 1 while executing".
        # Scan the log tail for the transient markers; anything else (real
        # compiler/platform errors) must re-raise immediately without retry.
        markers = self._meson_configure_transient_markers()
        candidates = (
            os.path.join(self.build_folder, "build-release",
                         "meson-logs", "meson-log.txt"),
            os.path.join(self.build_folder, "meson-logs", "meson-log.txt"),
        )
        for path in candidates:
            try:
                with open(path, encoding="utf-8", errors="replace") as handle:
                    tail = handle.read()[-200000:]
            except OSError:
                continue
            if any(m in tail for m in markers):
                return True
        return False

    def _meson_configure_with_transient_retry(self, meson, attempts=3):
        # CI #93888 failed BEFORE any compilation, at meson compiler sanity
        # check: `clang -Wl,--version` -> "posix_spawn failed: Resource
        # temporarily unavailable" (EAGAIN). This is transient worker
        # process/resource pressure, not a source/toolchain defect, and it is
        # strictly earlier than the ninja-phase oversubscription that the
        # tools.build:jobs cap (CI #93729) addresses. Bounded retry keeps
        # the exact same configure command/toolchain/sources/tests and only
        # tolerates EAGAIN: non-transient failures re-raise at once, and the
        # stale build dir is wiped so the retry reconfigures cleanly.
        last_exc = None
        for attempt in range(1, attempts + 1):
            try:
                meson.configure()
                return
            except ConanException as exc:
                last_exc = exc
                if attempt >= attempts or not self._meson_configure_failed_transient():
                    raise
                self.output.warning(
                    "meson configure hit transient resource exhaustion "
                    "(attempt %d/%d); wiping build dir and retrying" % (attempt, attempts))
                build_dir = self._meson_build_dir()
                try:
                    shutil.rmtree(build_dir, ignore_errors=True)
                except OSError as rmtree_exc:
                    self.output.warning("wipe build dir failed: %s" % rmtree_exc)
                time.sleep(20 * attempt)
        if last_exc is not None:
            raise last_exc

    def _meson_build_with_transient_retry(self, meson, attempts=3):
        # CI #94032: `meson compile -j4` died in ninja with
        # "ninja: fatal: posix_spawn: Resource temporarily unavailable"
        # (EAGAIN under worker process pressure), after configure had
        # already passed. Unlike configure, meson.build() leaves no
        # meson-log.txt fingerprint (ninja output goes to conan stdout
        # while ConanException only says "Error 1 while executing"), so
        # the retry cannot fingerprint and instead retries any build()
        # failure boundedly: real compile errors fail deterministically
        # on every attempt and still surface unchanged, while transient
        # EAGAIN succeeds once pressure subsides. No build-dir wipe:
        # ninja resumes incrementally, unlike configure which needs a
        # clean reconfigure. Serial jobs=1 (see generate()) is the
        # primary fix; this retry is belt-and-suspenders for residual
        # single-spawn EAGAIN (configure #93888 proved even one clang
        # spawn can hit it).
        last_exc = None
        for attempt in range(1, attempts + 1):
            try:
                meson.build()
                return
            except ConanException as exc:
                last_exc = exc
                if attempt >= attempts:
                    raise
                self.output.warning(
                    "meson build failed (attempt %d/%d); "
                    "sleeping and retrying (transient EAGAIN suspected, "
                    "cf. CI #94032)" % (attempt, attempts))
                time.sleep(20 * attempt)
        if last_exc is not None:
            raise last_exc

    def _meson_build_dir(self):
        # basic_layout(src_folder=".") puts the meson build tree directly
        # in self.build_folder (true-machine: .../b/build-release, which
        # already contains build.ninja/meson-info). An extra
        # "build-release" suffix points at a non-existent nested dir and
        # `meson install -C` dies with "Install data not found".
        # Resolve robustly: prefer self.build_folder when it already is
        # the meson tree, else fall back to the legacy subdir.
        base = self.build_folder or ""
        for cand in (base, os.path.join(base, "build-release")):
            try:
                if (os.path.isfile(os.path.join(cand, "build.ninja"))
                        or os.path.isdir(os.path.join(cand, "meson-info"))):
                    return cand
            except Exception:
                continue
        return base

    def _meson_install_with_transient_retry(self, meson, attempts=3):
        # CI #94809: 3 install retries ALL died at the same ninja rebuild
        # ([1/8] Linking, [2/8] symbols -> posix_spawn EAGAIN, Error 255),
        # proving retry alone cannot fix it. Root cause refined: Conan 2
        # Meson.install() runs `meson install -C <build> --destdir <pkg>`
        # WITHOUT --no-rebuild, so meson always spawns a ninja rebuild
        # check first -- and that implicit ninja run uses ninja's default
        # parallelism, IGNORING the tools.build:jobs=1 cap (which only
        # caps `meson compile -j`). Every retry re-spawns the same
        # parallel ninja, so EAGAIN persists deterministically under
        # worker pressure. Fix: pass --no-rebuild (upstream meson flag
        # since 0.57, `meson install --help` lists it): build() already
        # ran `meson compile` for all targets and 4/4 meson tests passed
        # on those exact artifacts, so the redundant pre-install rebuild
        # is pure risk with zero value -- skipping it installs the
        # validated binaries as-is. Real install errors still fail on
        # every attempt and surface unchanged. No dir wipe.
        # 2026-10-16 preflight fix: build dir is self.build_folder itself
        # (see _meson_build_dir); the old extra "build-release" suffix
        # produced .../build-release/build-release -> "Install data not
        # found. Run this command in build directory root."
        # CI #94891 2nd round (different strategy): resolve meson
        # deterministically from the meson tool_requires package folder
        # FIRST (same explicit scan as _run_upstream_tests), PATH only as
        # fallback. _discover_build_program checks PATH first, so a stale
        # system meson (< 0.57, no --no-rebuild flag) could shadow conan's
        # meson/1.11.0 and turn the flag below into "unrecognized
        # arguments". Pinning the tool package binary removes that class.
        build_dir = self._meson_build_dir()
        _exe = ""
        try:
            for _key in ("meson/1.11.0", "meson"):
                _bd = self.dependencies.build.get(_key)
                _pf = getattr(_bd, "package_folder", None) if _bd is not None else None
                if not _pf:
                    continue
                for _nm in ("meson", "meson.py"):
                    _c = os.path.join(str(_pf), "bin", _nm)
                    if os.path.isfile(_c):
                        _exe = _c
                        break
                if _exe:
                    break
        except Exception as _e:
            self.output.warning("meson build-dep scan failed: %s" % _e)
        if not _exe:
            try:
                _exe = self._discover_build_program(["meson"], "meson")
            except Exception:
                _exe = ""
        if not _exe:
            _exe = shutil.which("meson") or "meson"
        self.output.info("meson install exe resolved: %s" % _exe)
        last_exc = None
        for attempt in range(1, attempts + 1):
            try:
                self.run('"%s" install -C "%s" --no-rebuild --destdir "%s"'
                         % (_exe, build_dir, self.package_folder))
                return
            except ConanException as exc:
                last_exc = exc
                if attempt >= attempts:
                    raise
                self.output.warning(
                    "meson install --no-rebuild failed (attempt %d/%d); "
                    "sleeping and retrying (cf. CI #94809)" % (attempt, attempts))
                time.sleep(20 * attempt)
        if last_exc is not None:
            raise last_exc

    def build(self):
        self._ensure_pkg_config_shim()
        apply_conandata_patches(self)
        # Build-dep bindirs land on disk only by build() time; export them
        # to PATH first so meson find_program('flex') succeeds via PATH,
        # then re-inject ini entries (now with full discovery) before probe.
        try:
            self._export_build_tools_path()
        except Exception as e:
            self.output.warning("export build tools PATH failed: %s" % e)
        try:
            self._inject_meson_ar()
        except Exception as e:
            self.output.warning("re-inject meson programs failed: %s" % e)
        try:
            self._patch_glib_pc_lintl()
        except Exception as e:
            self.output.warning("re-patch glib-2.0.pc -lintl failed: %s" % e)
        meson = Meson(self)
        self._meson_configure_with_transient_retry(meson)
        self._meson_build_with_transient_retry(meson)
        tmp = self._writable_test_tmp()
        for _k in ("TMPDIR", "TMP", "TEMP"):
            os.environ[_k] = tmp
        self._sign_build_tests()
        self._run_upstream_tests()

    def _writable_test_tmp(self):
        # OHOS /tmp is read-only: point temp roots at task-private
        # writable storage (HMBS injects per-task TMPDIR).
        for var in ("HMBS_TMPDIR", "TMPDIR", "TMP", "TEMP"):
            d = os.environ.get(var)
            if d and os.path.isdir(d):
                try:
                    fd, p = tempfile.mkstemp(dir=d)
                    os.close(fd)
                    os.unlink(p)
                    return d
                except Exception:
                    continue
        d = os.path.join(self.build_folder, "hmbs-test-tmp")
        os.makedirs(d, exist_ok=True)
        return d

    @staticmethod
    def _is_elf(path):
        try:
            with open(path, "rb") as f:
                return f.read(4) == b"\x7fELF"
        except OSError:
            return False

    def _sign_one(self, objcopy, signer, path):
        try:
            subprocess.run(
                [objcopy, "--remove-section", ".codesign", path],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
            subprocess.run(
                [signer, "sign", "-inFile", path, "-outFile", path, "-selfSign", "1"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                timeout=60, check=True)
            return True
        except (OSError, subprocess.SubprocessError) as e:
            self.output.warning("sign %s failed: %s" % (path, e))
            return False

    def _sign_build_tests(self):
        # OHOS XPM kills unsigned exec/mmap with SIGKILL. Test binaries
        # mmap the build-tree liblasem shared lib, so sign both
        # executables AND build-tree .so files before `meson test`
        # (cairo 1.18.4 precedent).
        if str(self.settings.os) != "OHOS":
            return
        objcopy = shutil.which("llvm-objcopy") or "/data/service/hnp/bin/llvm-objcopy"
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(objcopy) or not os.path.isfile(signer):
            self.output.warning("OHOS signing tools missing; skip build-tree signing")
            return
        signed = 0
        for root, _dirs, files in os.walk(self.build_folder):
            if "meson-info" in root or "meson-private" in root:
                continue
            for name in files:
                path = os.path.join(root, name)
                if name.endswith((".c", ".h", ".o", ".a", ".log", ".json", ".ini",
                                   ".dat", ".build", ".ninja", ".pc", ".txt",
                                   ".xml", ".svg", ".mml", ".png", ".1")):
                    continue
                is_lib = ".so" in name
                if not is_lib:
                    try:
                        st = os.stat(path)
                    except OSError:
                        continue
                    if not (st.st_mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)):
                        continue
                    if os.path.islink(path):
                        continue
                    if not self._is_elf(path):
                        continue
                else:
                    if os.path.islink(path) or not self._is_elf(path):
                        continue
                if self._sign_one(objcopy, signer, path):
                    signed += 1
        self.output.info("signed %d build-tree binaries/libs for meson test" % signed)

    def _host_libdirs_for_tests(self):
        # Upstream test binaries link shared conan deps; the dynamic loader
        # finds them via LD_LIBRARY_PATH. glib/2.84.0.1 ships the real
        # proxy-libintl libintl.so exporting g_libintl_* (gdk-pixbuf
        # 2.44.6.1.1 / lasem-render 0.5.1 precedent); the gettext
        # tool_requires' GNU libintl.so lacks those symbols. LD order must
        # put the glib package libdir FIRST so its libintl.so shadows the
        # gettext one, otherwise every test dies with
        # "Error relocating libglib-2.0.so.0: g_libintl_* symbol not found"
        # (exit 127). Same approach as lasem-render 0.5.1 _dependency_libdirs.
        dirs = []
        try:
            host_deps = self.dependencies.host.values()
        except Exception:
            host_deps = []
        glib_first = []
        rest = []
        for dep in host_deps:
            try:
                pf = getattr(dep, "package_folder", None)
                libdirs = getattr(getattr(dep, "cpp_info", None), "libdirs", [])
            except Exception:
                continue
            if not pf:
                continue
            for libdir in libdirs or []:
                d = libdir if os.path.isabs(str(libdir)) else os.path.join(str(pf), str(libdir))
                if not os.path.isdir(d):
                    continue
                if d not in dirs:
                    dirs.append(d)
                try:
                    ref = getattr(dep, "ref", None)
                    is_glib = (ref is not None and getattr(ref, "name", "") == "glib")
                except Exception:
                    is_glib = False
                if is_glib:
                    if d not in glib_first:
                        glib_first.append(d)
                else:
                    if d not in rest:
                        rest.append(d)
        ordered = glib_first + [d for d in rest if d not in glib_first]
        # Fallback: direct glib lookup in case host iteration missed it.
        if not glib_first:
            try:
                gdep = self.dependencies.host.get("glib")
                pf = getattr(gdep, "package_folder", None) if gdep is not None else None
                if pf:
                    for libdir in getattr(getattr(gdep, "cpp_info", None), "libdirs", []) or []:
                        d = libdir if os.path.isabs(str(libdir)) else os.path.join(str(pf), str(libdir))
                        if os.path.isdir(d) and d not in ordered:
                            ordered.insert(0, d)
            except Exception as e:
                self.output.warning("glib libdir fallback lookup failed: %s" % e)
        for d in ordered:
            probe = os.path.join(d, "libintl.so")
            if os.path.lexists(probe):
                self.output.info("test LD probe: libintl.so present in %s" % d)
        if ordered:
            self.output.info("test LD libdirs (glib first): %s" % ":".join(ordered))
        else:
            self.output.warning("test LD libdirs empty; loader may miss shared deps")
        return ordered

    def _wrap_test_binaries(self, ld_dirs):
        # See isolation comment in _run_upstream_tests: rename each tests/*
        # ELF to *.hmbs-real and drop a /bin/sh wrapper that prepends the
        # glib-first host libdirs, then execs the real binary. Idempotent
        # (already-wrapped binaries are skipped via the .hmbs-real probe).
        # Only wraps regular ELF files with an exec bit; scripts/.so/data
        # files are left alone. Returns the wrapped count.
        if not ld_dirs:
            self.output.warning("wrap tests: empty ld_dirs, skip wrapping")
            return 0
        tests_dir = os.path.join(self.build_folder, "tests")
        if not os.path.isdir(tests_dir):
            self.output.warning("wrap tests: no tests dir at %s" % tests_dir)
            return 0
        ld_prefix = ":".join(ld_dirs)
        wrapped = 0
        try:
            names = sorted(os.listdir(tests_dir))
        except OSError as e:
            self.output.warning("wrap tests: listdir failed: %s" % e)
            return 0
        for name in names:
            path = os.path.join(tests_dir, name)
            try:
                if os.path.islink(path) or not os.path.isfile(path):
                    continue
                if name.endswith(".hmbs-real"):
                    continue
                real = path + ".hmbs-real"
                if os.path.lexists(real):
                    continue  # already wrapped in a previous attempt
                with open(path, "rb") as f:
                    if f.read(4) != b"\x7fELF":
                        continue
                try:
                    st = os.stat(path)
                except OSError:
                    continue
                if not (st.st_mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)):
                    continue
                os.replace(path, real)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write("#!/bin/sh\n")
                    f.write("export LD_LIBRARY_PATH=\"%s:$LD_LIBRARY_PATH\"\n"
                            % ld_prefix.replace("\"", "\\\""))
                    f.write("exec \"%s\" \"$@\"\n" % real.replace("\"", "\\\""))
                try:
                    os.chmod(path, 0o755)
                except OSError as e:
                    self.output.warning("wrap tests: chmod %s failed: %s" % (path, e))
                wrapped += 1
                self.output.info("wrapped test binary: %s" % path)
            except OSError as e:
                self.output.warning("wrap tests: %s failed: %s" % (path, e))
        if wrapped == 0:
            self.output.warning("wrap tests: no ELF test binaries wrapped under %s" % tests_dir)
        else:
            self.output.info("wrapped %d test binaries with glib-first LD" % wrapped)
        return wrapped

    def _unwrap_test_binaries(self):
        # Post-test hygiene (CI #94891 2nd round, different strategy):
        # _wrap_test_binaries replaces ninja-tracked tests/* outputs with
        # sh scripts. Any later ninja tree inspection (meson install
        # without --no-rebuild on an older-pushed tree, a re-invoked
        # compile, or Meson-helper internals) then sees outputs that no
        # longer match build.ninja's expectations. Restore the pristine
        # signed ELFs (the *.hmbs-real files) so package() starts from
        # the exact tree `meson compile` produced. Runs after the marker
        # + hmbs_upstream.json are written, so test evidence is untouched;
        # best-effort only, never masks the real test result.
        tests_dir = os.path.join(self.build_folder, "tests")
        if not os.path.isdir(tests_dir):
            return 0
        try:
            names = sorted(os.listdir(tests_dir))
        except OSError as e:
            self.output.warning("unwrap tests: listdir failed: %s" % e)
            return 0
        restored = 0
        for name in names:
            if not name.endswith(".hmbs-real"):
                continue
            real = os.path.join(tests_dir, name)
            orig = real[: -len(".hmbs-real")]
            try:
                if not os.path.isfile(real) or os.path.islink(real):
                    continue
                os.replace(real, orig)
                restored += 1
            except OSError as e:
                self.output.warning("unwrap tests: %s failed: %s" % (real, e))
        if restored:
            self.output.info("restored %d wrapped test binaries to pristine ELFs" % restored)
        return restored

    def _run_upstream_tests(self):
        """Run `meson test` and emit HMBS_UPSTREAM_TEST_RESULT.

        Upstream 0.6.0 registers 4 meson tests (tests/meson.build):
        dom, str, filter (GLib gtest unit tests) and suite (data-driven
        render regression: every tests/data/**/*.svg|*.mml file becomes
        a /render/<path> sub-case rendered to a cairo surface, failing
        only on cairo_status != SUCCESS). The single deterministic count
        source is the summary block (Ok:/Fail: always present, other
        categories only when nonzero per meson mtest.py summary()) from
        meson-written
        meson-logs/testlog.txt when present, else from our teed copy of
        meson's formal stdout (same block, PIPE without shell); no
        per-word stdout counting, no arithmetic patch-ups, no
        returncode-based count overrides. Both missing ->
        honest failure marker with searched paths, never fabricated.
        """
        tmp = self._writable_test_tmp()
        home_dir = os.path.join(tmp, "lasem-home")
        for _d in (tmp, home_dir):
            try:
                os.makedirs(_d, exist_ok=True)
            except OSError:
                pass
        env = Environment()
        env.define("TMPDIR", tmp)
        env.define("TMP", tmp)
        env.define("TEMP", tmp)
        env.define("HOME", home_dir)
        env.define("XDG_CACHE_HOME", tmp)
        env.define("XDG_RUNTIME_DIR", tmp)
        env.define("MESON_TESTTHREADS", "1")
        try:
            _ld_dirs = self._host_libdirs_for_tests()
        except Exception as e:
            self.output.warning("host libdirs probe failed: %s" % e)
            _ld_dirs = []
        # Parent LD stays clean on purpose (see wrapper isolation below).
        try:
            _wrapped = self._wrap_test_binaries(_ld_dirs)
        except Exception as e:
            self.output.warning("wrap test binaries failed: %s" % e)
        for _k in ("HMBS_AUTOCONF_MKTEMP_FALLBACK", "HMBS_CAP_LOCAL_MKTEMP",
                   "HMBS_TMPDIR", "HMBS_CAP_HARDLINK", "HMBS_CAP_CHMOD",
                   "HMBS_CAP_SYMLINK"):
            _v = os.environ.get(_k)
            if _v:
                env.define(_k, _v)
        with env.vars(self).apply():
            # libintl SONAME conflict isolation (3rd fix round):
            # glib/2.84.0.1's libintl.so exports g_libintl_* (needed by the
            # C test binaries via libglib/libgio/gdk-pixbuf) while the
            # system/gettext libintl.so exports plain libintl_* (needed by
            # meson itself = libpython3.14). Same basename, so a single
            # global LD_LIBRARY_PATH cannot satisfy both: glib-first broke
            # meson/python, gettext-first broke the C tests. meson 1.11.0
            # has NO `meson test --env` flag (2nd round failed with
            # "unrecognized arguments: --env"), so isolation is done with
            # per-binary sh wrappers (no meson flag): the parent meson keeps
            # a build-dep-only LD (plain libintl for libpython), each
            # tests/* ELF is renamed to *.hmbs-real and replaced by a
            # script that prepends the glib-first host libdirs then execs
            # the real binary. Meson still prepends its build-tree dirs at
            # test runtime, so the build-tree liblasem .so keeps working.
            # --verbose streams progress so a multi-minute suite never
            # looks like a dead session on jobs=1 hardware.
            # ignore_errors semantics: the marker below carries pass/fail;
            # a failing suite must report numbers, not a bare traceback.
            # Execution + evidence (5th fix round): `meson test` runs here
            # via an in-process-resolved meson binary with stdout teed
            # through a PIPE (no shell, no /tmp temp files) into
            # meson_test_stdout.log. The previous round proved the suite
            # itself passes (stdout summary Fail: 0, End of render tests)
            # but no parseable evidence reached the marker (discovered=0):
            # the teed run either never started (meson unresolvable in the
            # raw process env) or started without conan buildenv parity
            # (build-tool PATH, plain-libintl LD for libpython). This
            # round resolves meson explicitly, rebuilds the parent env
            # from build-dep bindirs/libdirs + HMBS tool dirs, and only
            # falls back to self.run when the teed output holds no
            # parseable summary. testlog.txt stays the preferred source.
            _cmd = ("meson test --no-rebuild --print-errorlogs "
                    "--num-processes 1 --verbose --timeout-multiplier 0")
            self.output.info("meson parent LD_LIBRARY_PATH: %s"
                             % (os.environ.get("LD_LIBRARY_PATH", "") or "(empty)"))
            self.output.info("meson PATH probe: which=%s"
                             % (shutil.which("meson") or "NOT-FOUND"))
            try:
                _mlogs = os.path.join(self.build_folder, "meson-logs")
                self.output.info("meson-logs dir: %s exists=%s content=%s"
                                 % (_mlogs, os.path.isdir(_mlogs),
                                    sorted(os.listdir(_mlogs))[:10] if os.path.isdir(_mlogs) else []))
            except Exception as _e:
                self.output.warning("meson-logs probe failed: %s" % _e)
            _meson_exe = self._discover_build_program(["meson"], "meson")
            if not _meson_exe:
                # Explicit build-dep package scan (meson/1.11.0): the
                # in-process PATH may miss the tool package bindir even
                # after _export_build_tools_path.
                try:
                    for _key in ("meson/1.11.0", "meson"):
                        _bd = self.dependencies.build.get(_key)
                        _pf = getattr(_bd, "package_folder", None) if _bd is not None else None
                        if not _pf:
                            continue
                        for _nm in ("meson", "meson.py"):
                            _c = os.path.join(str(_pf), "bin", _nm)
                            if os.path.isfile(_c):
                                _meson_exe = _c
                                break
                        if _meson_exe:
                            break
                except Exception as _e:
                    self.output.warning("meson build-dep scan failed: %s" % _e)
            self.output.info("meson exe resolved: %s" % (_meson_exe or "NOT-FOUND"))
            _stdout_log = os.path.join(self.build_folder, "meson_test_stdout.log")
            _teed = ""
            _teed_usable = False
            if _meson_exe:
                # Parent env parity with self.run's conan buildenv: build-dep
                # bindirs on PATH (meson shebang needs python3: HMBS tool
                # dirs first), build-dep libdirs on LD (plain libintl for
                # libpython). Host glib-first dirs stay OUT of the parent LD;
                # test children get them via the sh wrappers.
                _penv = dict(os.environ)
                _pdirs = []
                try:
                    for _bdep in self.dependencies.build.values():
                        _pf = getattr(_bdep, "package_folder", None)
                        if not _pf:
                            continue
                        _b = os.path.join(str(_pf), "bin")
                        if os.path.isdir(_b) and _b not in _pdirs:
                            _pdirs.append(_b)
                except Exception as _e:
                    self.output.warning("parent PATH scan failed: %s" % _e)
                for _hk in ("HMBS_PYTHON3", "HMBS_CMAKE", "HMBS_MAKE", "HMBS_NINJA"):
                    _hv = os.environ.get(_hk, "")
                    if _hv:
                        _hd = os.path.dirname(_hv)
                        if _hd and _hd not in _pdirs:
                            _pdirs.append(_hd)
                if _pdirs:
                    _penv["PATH"] = os.pathsep.join(_pdirs + [_penv.get("PATH", "")])
                _bld = []
                try:
                    for _bdep in self.dependencies.build.values():
                        _pf = getattr(_bdep, "package_folder", None)
                        if not _pf:
                            continue
                        try:
                            _libdirs = getattr(getattr(_bdep, "cpp_info", None), "libdirs", []) or []
                        except Exception:
                            _libdirs = []
                        for _ldn in ["lib"] + [str(x) for x in _libdirs]:
                            _d = _ldn if os.path.isabs(_ldn) else os.path.join(str(_pf), _ldn)
                            if os.path.isdir(_d) and _d not in _bld:
                                _bld.append(_d)
                except Exception as _e:
                    self.output.warning("parent LD scan failed: %s" % _e)
                _old_ld = _penv.get("LD_LIBRARY_PATH", "")
                _penv["LD_LIBRARY_PATH"] = os.pathsep.join(_bld + ([_old_ld] if _old_ld else []))
                self.output.info("parent PATH prepended %d dirs, parent LD %d build libdirs"
                                 % (len(_pdirs), len(_bld)))
                try:
                    _proc = subprocess.Popen(
                        [_meson_exe, "test", "--no-rebuild", "--print-errorlogs",
                         "--num-processes", "1", "--verbose", "--timeout-multiplier", "0"],
                        cwd=self.build_folder,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                        env=_penv, text=True, errors="replace", bufsize=1)
                    with open(_stdout_log, "w", encoding="utf-8", errors="replace") as _lf:
                        for _ln in _proc.stdout:
                            _lf.write(_ln)
                            _lf.flush()
                            self.output.info(_ln.rstrip("\n"))
                            _teed += _ln
                    _proc.stdout.close()
                    _proc.wait()
                    self.output.info("meson test returncode: %s" % _proc.returncode)
                except Exception as _e:
                    self.output.warning("teed meson run failed (%s)" % _e)
                    _teed = ""
                if _teed.strip():
                    _probe = self._parse_meson_summary(_teed, _stdout_log, (_stdout_log,))
                    _teed_usable = _probe.get("discovered", 0) > 0
                    self.output.info("teed summary usable=%s (discovered=%s)"
                                     % (_teed_usable, _probe.get("discovered")))
                else:
                    self.output.warning("teed meson produced no output")
            if not _teed_usable:
                # Fallback keeps the proven self.run execution env (conan
                # buildenv PATH applies even when the meson binary is not
                # resolvable in-process). Runs only when tee gave no
                # parseable summary, so the suite normally executes once.
                self.output.info("fallback to self.run (tee unusable)")
                self.run(_cmd, cwd=self.build_folder, ignore_errors=True)
        log_cands = [os.path.join(self.build_folder, "meson-logs", "testlog.txt"),
                     os.path.join(self.build_folder, "meson_test.log"),
                     os.path.join(self.build_folder, "build-release", "meson-logs", "testlog.txt")]
        # Meson helper may nest the build dir one level deeper; fall back to
        # a bounded recursive search so the single deterministic source
        # (meson-written testlog.txt) is still found. No stdout counting.
        try:
            import glob as _glob
            for _hit in sorted(_glob.glob(os.path.join(self.build_folder, "**", "meson-logs",
                                                        "testlog.txt"), recursive=True)):
                if _hit not in log_cands:
                    log_cands.append(_hit)
        except Exception:
            pass
        log_cands = tuple(log_cands)
        _tee_report = os.path.join(self.build_folder, "meson_test_stdout.log")
        _report_cands = log_cands + ((_tee_report,) if _tee_report not in log_cands else ())
        output = ""
        used_log = ""
        for _cand in log_cands:
            if os.path.isfile(_cand):
                try:
                    with open(_cand, encoding="utf-8", errors="replace") as f:
                        output = f.read()
                    used_log = _cand
                    break
                except OSError:
                    continue
        if not output.strip():
            # Secondary deterministic source: our own teed copy of meson's
            # formal stdout (same Ok:/Fail: summary block, written through
            # a PIPE without shell). Preferred testlog.txt stays first;
            # this only fills the gap proven by the previous round
            # (suite passed with Fail: 0 yet testlog.txt absent).
            try:
                _tee = os.path.join(self.build_folder, "meson_test_stdout.log")
                if os.path.isfile(_tee):
                    with open(_tee, encoding="utf-8", errors="replace") as f:
                        _t = f.read()
                    if _t.strip():
                        output = _t
                        used_log = _tee
                        self.output.info("using teed meson stdout as summary source")
            except OSError:
                pass
        self.output.info("=== upstream meson test (tail) ===")
        for line in (output.splitlines() or [])[-25:]:
            self.output.info(line)
        marker = self._parse_meson_summary(output, used_log, _report_cands)
        # If the file source yielded no tests but the in-memory teed
        # console output holds a valid Ok:/Fail: summary (verbose mode
        # prints no "1/4" progress lines to console, only to the file),
        # prefer the teed evidence over an honest-failure marker. Single
        # deterministic source still: one block, no cross-source mixing.
        try:
            if marker.get("discovered", 0) == 0 and (_teed or "").strip():
                _alt = self._parse_meson_summary(_teed, _stdout_log, (_stdout_log,))
                if _alt.get("discovered", 0) > 0:
                    self.output.info("using in-memory teed summary (file source empty/unparseable)")
                    marker = _alt
                    used_log = _stdout_log
        except Exception:
            pass
        try:
            marker["command"] = _cmd
        except Exception:
            pass
        # Falsification guard (toybox-tar lesson): a green summary is
        # only trusted if the fixtures and binaries are real non-empty
        # files. Suite renders tests/data/**/*.{svg,mml}; an empty data
        # dir would pass vacuously.
        self._guard_nonempty_fixtures(marker)
        line = "HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(marker, ensure_ascii=False)
        print(line, flush=True)
        self.output.info(line)
        try:
            with open(os.path.join(self.build_folder, "hmbs_upstream.json"), "w",
                      encoding="utf-8") as f:
                json.dump(marker, f, ensure_ascii=False)
        except OSError:
            pass
        try:
            self._unwrap_test_binaries()
        except Exception as e:
            self.output.warning("unwrap test binaries failed: %s" % e)
        if marker["status"] != "passed":
            raise ConanException("upstream meson test failed: %s" % marker)

    def _parse_meson_summary(self, output, used_log, log_cands):
        command = ("meson test --no-rebuild --print-errorlogs "
                   "--num-processes 1 --verbose --timeout-multiplier 0")
        # Meson mtest.py summary() prints Ok:/Fail: always, every other
        # category only when its count is > 0 (e.g. a 4/4 green run prints
        # just "Ok: 4" + "Fail: 0"). Requiring all six/seven fields is
        # therefore wrong (lasem 0.6.0 preflight: suite green with Fail: 0
        # yet marker failed with discovered=0). Strip ANSI first, allow
        # leading spaces, treat absent categories as 0; Ok+Fail present
        # is sufficient for a deterministic summary.
        try:
            output = re.sub(r"\x1b\[[0-9;]*m", "", output)
        except Exception:
            pass

        def _field(name):
            m = re.search(r"^\s*%s:\s*(\d+)" % re.escape(name), output, flags=re.M)
            return int(m.group(1)) if m else None

        ok = _field("Ok")
        fail = _field("Fail")
        if ok is not None and fail is not None:
            exp_fail = _field("Expected Fail") or 0
            unexp = _field("Unexpected Pass") or 0
            skipped = _field("Skipped") or 0
            ignored = _field("Ignored") or 0
            timeout = _field("Timeout") or 0
            passed = ok + exp_fail
            failed = fail + unexp + timeout
            skipped_total = skipped + ignored
            discovered = passed + failed + skipped_total
            executed = passed + failed
            result = {
                "status": "passed" if (failed == 0 and discovered > 0) else "failed",
                "framework": "meson",
                "command": command,
                "discovered": discovered,
                "executed": executed,
                "passed": passed,
                "failed": failed,
                "skipped": skipped_total,
            }
            if result["status"] == "failed" and discovered == 0:
                result["reason"] = "meson summary present but zero tests"
            return result
        # Fallback: line-by-line parse of per-test result lines
        # ("1/4 dom OK ..."), one source, no cross-source overrides.
        # Meson file logger uses OK/FAIL/SKIP/TIMEOUT/INTERRUPT/ERROR plus
        # EXPECTEDFAIL (pass) / UNEXPECTEDPASS (fail); TAP "ok N" lines
        # (lowercase, suite sub-cases) must NOT match here.
        p_ok = p_fail = p_skip = p_timeout = 0
        for _line in output.splitlines():
            m = re.match(r"^\s*\d+/\d+\s+\S.*?\b(OK|EXPECTEDFAIL|UNEXPECTEDPASS|FAIL|FAILED|SKIP|SKIPPED|TIMEOUT|INTERRUPT|ERROR)\b",
                         _line)
            if not m:
                continue
            w = m.group(1)
            if w in ("OK", "EXPECTEDFAIL"):
                p_ok += 1
            elif w in ("SKIP", "SKIPPED"):
                p_skip += 1
            elif w == "TIMEOUT":
                p_timeout += 1
            else:
                p_fail += 1
        if p_ok + p_fail + p_skip + p_timeout > 0:
            passed = p_ok
            failed = p_fail + p_timeout
            discovered = passed + failed + p_skip
            return {
                "status": "passed" if (failed == 0 and discovered > 0) else "failed",
                "framework": "meson",
                "command": command,
                "discovered": discovered,
                "executed": passed + failed,
                "passed": passed,
                "failed": failed,
                "skipped": p_skip,
            }
        return {
            "status": "failed",
            "framework": "meson",
            "command": command,
            "discovered": 0,
            "executed": 0,
            "passed": 0,
            "failed": 0,
            "skipped": 0,
            "reason": "no meson summary or result lines; searched: %s" % ", ".join(log_cands),
        }

    def _guard_nonempty_fixtures(self, marker):
        # Prove the green run compared real files: test binaries and the
        # suite data dir must exist and be non-empty. Log only; a failed
        # marker already fails the build, a passed marker with empty
        # fixtures is distrusted and fails here instead of silently.
        try:
            data_dir = os.path.join(self.source_folder, "tests", "data")
            n_data = 0
            if os.path.isdir(data_dir):
                for _root, _ds, _fs in os.walk(data_dir):
                    n_data += sum(1 for _f in _fs
                                  if _f.endswith((".svg", ".mml")))
            self.output.info("suite fixture files (.svg/.mml under tests/data): %d" % n_data)
            if marker.get("status") == "passed" and n_data <= 0:
                raise ConanException(
                    "upstream suite passed with empty tests/data "
                    "(vacuous green, toybox-tar lesson)")
        except ConanException:
            raise
        except Exception as e:
            self.output.warning("fixture guard probe skipped: %s" % e)

    def package(self):
        self._meson_install_with_transient_retry(Meson(self))
        self._copy_upstream_evidence()
        self._sign_installed()

    def _copy_upstream_evidence(self):
        # Persist the upstream marker so test_package can re-emit it on
        # cache-hit rounds (laz-perf 3.4.0 precedent).
        src = os.path.join(self.build_folder, "hmbs_upstream.json")
        if not os.path.isfile(src):
            self.output.warning("hmbs_upstream.json absent from build; skip evidence copy")
            return
        dst_dir = os.path.join(self.package_folder, "res")
        try:
            os.makedirs(dst_dir, exist_ok=True)
            shutil.copy2(src, os.path.join(dst_dir, "hmbs_upstream.json"))
        except OSError as e:
            self.output.warning("cannot copy hmbs_upstream.json: %s" % e)

    def _sign_installed(self):
        # OHOS XPM: installed .so and the lasem-render CLI must be signed
        # (pango 1.56.4 precedent).
        if str(self.settings.os) != "OHOS":
            return
        import glob as _glob

        targets = _glob.glob(os.path.join(self.package_folder, "lib", "**", "*.so"), recursive=True)
        targets += _glob.glob(os.path.join(self.package_folder, "lib", "**", "*.so.*"), recursive=True)
        bindir = os.path.join(self.package_folder, "bin")
        if os.path.isdir(bindir):
            for name in os.listdir(bindir):
                p = os.path.join(bindir, name)
                if os.path.isfile(p) and not os.path.islink(p) and self._is_elf(p):
                    targets.append(p)
        objcopy = shutil.which("llvm-objcopy") or ""
        if not objcopy or not os.path.isfile(objcopy):
            ce = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
            _cc = ce.get("c") or ""
            if _cc and os.path.sep in _cc:
                _cand = os.path.join(os.path.dirname(_cc), "llvm-objcopy")
                if os.path.isfile(_cand):
                    objcopy = _cand
        if not objcopy or not os.path.isfile(objcopy):
            objcopy = "/data/service/hnp/bin/llvm-objcopy"
        signer = shutil.which("binary-sign-tool") or ""
        if not signer or not os.path.isfile(signer):
            signer = "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(objcopy) or not os.path.isfile(signer):
            self.output.warning("OHOS signing tools missing (%s, %s); skip installed signing"
                                % (objcopy, signer))
            return
        for f in targets:
            if os.path.islink(f):
                continue
            self.run('"%s" --remove-section .codesign "%s" 2>/dev/null || true' % (objcopy, f))
            self.run('"%s" sign -inFile "%s" -outFile "%s" -selfSign 1' % (signer, f, f))

    def package_info(self):
        self.cpp_info.libs = ["lasem-0.6"]
        self.cpp_info.includedirs = self._detect_include_dirs()
        self.cpp_info.bindirs = ["bin"]
        # lasem's public headers include <glib-object.h> / <gio/gio.h> /
        # <cairo.h> / <pango/pangocairo.h> — propagate consumer requirements.
        # Component names must match each dep's package_info: glib exposes
        # glib-2.0/gobject-2.0/gio-2.0 components (no aggregate "glib"),
        # pango's rendering path needs the pangocairo component (which itself
        # requires pango/pangoft2/cairo::cairo). Same set as the verified
        # same-family lasem-render/0.5.1 recipe; "glib::glib" / "pango::pango"
        # left lld without g_type/g_object/cairo symbols at test link time.
        self.cpp_info.requires = [
            "glib::glib-2.0",
            "glib::gobject-2.0",
            "glib::gio-2.0",
            "cairo::cairo",
            "pango::pangocairo",
            "harfbuzz::harfbuzz",
            "gdk-pixbuf::gdk-pixbuf",
            "libxml2::libxml2",
        ]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["m"]
        self.cpp_info.set_property("cmake_file_name", "lasem")
        self.cpp_info.set_property("cmake_target_name", "lasem::lasem")
        self.cpp_info.set_property("pkg_config_name", "lasem-0.6")

    def _detect_include_dirs(self):
        """Scan include/ for header-bearing subdirs (pango precedent).

        lasem installs public headers under include/lasem-0.6/; consumers
        include <lsm.h> via that subdir. Declaring only "include" breaks
        downstream builds only (invisible at package time).
        """
        import os as _os

        base = _os.path.join(self.package_folder, "include")
        dirs = ["include"]
        if not _os.path.isdir(base):
            return dirs
        for name in sorted(_os.listdir(base)):
            sub = _os.path.join(base, name)
            if not _os.path.isdir(sub):
                continue
            for _root, _d, files in _os.walk(sub):
                if any(f.endswith((".h", ".hpp", ".hh", ".hxx")) for f in files):
                    dirs.append("include/" + name)
                    break
        return dirs
