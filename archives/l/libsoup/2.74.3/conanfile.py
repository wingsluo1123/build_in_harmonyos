#!/usr/bin/env python3
"""Conan recipe for libsoup 2.74.3 on HarmonyOS PC (arm64).

Build system: meson
Dependencies: glib, libpsl, libxml2, sqlite3, brotli

The old historical adaptation stubbed out gnome.compile_resources() because
the HNP system's glib-compile-resources was broken (missing libffi.so.8).
With Conan-managed glib, the working glib-compile-resources from the Conan
glib package is used, so no stub patch is needed.
"""

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.meson import Meson, MesonToolchain
from conan.tools.gnu import PkgConfigDeps


class LibsoupConan(ConanFile):
    name = "libsoup"
    version = "2.74.3"
    description = "HTTP client/server library for GNOME"
    license = "LGPL-2.0-or-later"
    homepage = "https://gitlab.gnome.org/GNOME/libsoup"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("glib/2.84.0")
        self.requires("libpsl/0.21.5")
        self.requires("libxml2/2.15.3")
        self.requires("sqlite3/3.49.1")
        self.requires("brotli/1.2.0")

    def layout(self):
        self.folders.source = "src"
        self.folders.build = "build"
        self.folders.generators = "build"

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = MesonToolchain(self)
        # Disable TLS check: glib-networking not available at compile time
        tc.project_options["tls_check"] = "false"
        # Disable sysprof: not needed on OHOS
        tc.project_options["sysprof"] = "disabled"
        # Disable tests: separate test_package handles testing
        tc.project_options["tests"] = "false"
        # Disable GNOME-specific features (po subdirectory)
        tc.project_options["gnome"] = "false"
        # Disable GObject introspection
        tc.project_options["introspection"] = "disabled"
        # Disable Vala bindings
        tc.project_options["vapi"] = "disabled"
        # Disable GTK doc generation
        tc.project_options["gtk_doc"] = "false"
        tc.generate()
        pkg = PkgConfigDeps(self)
        pkg.generate()
        # Generate pkg-config files for glib components that meson looks for
        # separately (gmodule-2.0, gobject-2.0, gio-2.0, gthread-2.0).
        # The glib Conan package puts all libs in a single glib-2.0.pc,
        # but meson's dependency() checks for each component separately.
        # Also add pkg-config variables (glib_compile_resources, etc.) that
        # the meson gnome module needs to find glib build tools.
        import os
        glib_root = self.dependencies["glib"].package_folder
        glib_bin = os.path.join(glib_root, "bin")
        pc_dir = self.generators_folder
        glib_vars = {
            "glib_compile_resources": f"{glib_bin}/glib-compile-resources",
            "glib_genmarshal": f"{glib_bin}/glib-genmarshal",
            "glib_mkenums": f"{glib_bin}/glib-mkenums",
            "glib_querymodulesdir": f"{glib_root}/lib/gio/modules",
        }
        var_lines = "\n".join(f"{k}={v}" for k, v in glib_vars.items())
        # Append glib tool variables to the main glib-2.0.pc (generated by PkgConfigDeps)
        glib_pc = os.path.join(pc_dir, "glib-2.0.pc")
        if os.path.exists(glib_pc):
            with open(glib_pc, "r") as f:
                existing = f.read()
            if "glib_compile_resources" not in existing:
                with open(glib_pc, "w") as f:
                    f.write(existing.rstrip() + "\n" + var_lines + "\n")
        for comp in ["gmodule-2.0", "gobject-2.0", "gio-2.0", "gthread-2.0"]:
            pc_path = os.path.join(pc_dir, f"{comp}.pc")
            if not os.path.exists(pc_path):
                content = (
                    f"Name: {comp}\n"
                    f"Description: {comp} (via glib conan package)\n"
                    f"Version: 2.84.0\n"
                    f"Requires: glib-2.0\n"
                    f"{var_lines}\n"
                )
                with open(pc_path, "w") as f:
                    f.write(content)
        # Generate pkg-config wrappers for brotli components
        # (brotli Conan package may only generate libbrotlicommon.pc)
        brotli_root = self.dependencies["brotli"].package_folder
        for comp in ["libbrotlidec", "libbrotlienc"]:
            pc_path = os.path.join(pc_dir, f"{comp}.pc")
            if not os.path.exists(pc_path):
                content = (
                    f"Name: {comp}\n"
                    f"Description: {comp} (via brotli conan package)\n"
                    f"Version: 1.2.0\n"
                    f"Requires: libbrotlicommon\n"
                    f"Libs: -L{brotli_root}/lib -l{comp.replace('lib', '')}\n"
                )
                with open(pc_path, "w") as f:
                    f.write(content)

    def build(self):
        import os
        # Fix: meson auto-detects llvm-ar as archiver for clang but can't find it
        os.environ["AR"] = "/data/service/hnp/bin/llvm-ar"
        os.environ["RANLIB"] = "/data/service/hnp/bin/llvm-ranlib"
        apply_conandata_patches(self)
        meson = Meson(self)
        meson.configure()
        meson.build()

    def package(self):
        meson = Meson(self)
        meson.install()

    def package_info(self):
        self.cpp_info.libs = ["soup-2.4"]
        self.cpp_info.set_property("pkg_config_name", "libsoup-2.4")
        # Headers installed to include/libsoup-2.4/libsoup/ by meson
        self.cpp_info.includedirs = ["include/libsoup-2.4"]
