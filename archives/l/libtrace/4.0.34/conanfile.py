#!/usr/bin/env python3
"""Conan recipe for libtrace 4.0.34 -- the WAND network trace processing library.

The GitHub tag archive of libtrace is *not* a buildable source release: it has
no generated ``configure`` and no generated ``lib/libtrace.h`` (only
``libtrace.h.in``, which upstream's configure substitutes).  Bootstrapping is
not an option on the HarmonyOS build hosts either, because only autoconf/m4 are
installed -- automake, aclocal and libtoolize are absent, and the GitHub archive
has no ``Makefile.in`` at all.

This recipe therefore does what the wandio/4.2.7 recipe in this same repository
does: it reproduces the two things configure would have produced (``config.h``
and ``libtrace.h`` from ``libtrace.h.in``) and compiles the library sources
directly with the Conan C compiler, mirroring ``lib/Makefile.am`` with every
optional backend (DAG / DPDK / pfring / XDP+eBPF / LLVM JIT / wandder-ETSI /
libnuma) switched off.  libpcap and libwandio come from the ohpcd remote and are
the only two dependencies upstream makes mandatory.
"""
import glob
import io
import os
import re
import shutil

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import (apply_conandata_patches, copy,
                               export_conandata_patches, get)
from conan.tools.layout import basic_layout

# lib/Makefile.am: libtrace_la_SOURCES with $(XDP_SOURCES) $(DAGSOURCE)
# $(BPFJITSOURCE) $(ETSISOURCES) $(LINUX_SOURCES) empty, i.e. upstream configure
# run with --without-dag --without-dpdk --without-pfring --without-libbpf
# --without-llvm --without-wandder.  NATIVEFORMATS and BPFFORMATS are the
# unconditional base values from the same file.
_LIB_SOURCES = [
    "trace.c", "trace_parallel.c",
    "format_pktmeta.c", "format_erf.c", "format_pcap.c", "format_legacy.c",
    "format_rt.c", "format_helper.c", "format_pcapfile.c", "format_duck.c",
    "format_tsh.c", "format_atmhdr.c", "format_pcapng.c", "format_tzsplive.c",
    "format_bpf.c",
    "format_linux_common.c", "format_linux_ring.c", "format_linux_int.c",
    "format_ndag.c", "format_linux_helpers.c",
    "linktypes.c", "link_wireless.c", "byteswap.c", "checksum.c",
    "protocols_pktmeta.c", "protocols_l2.c", "protocols_l3.c",
    "protocols_transport.c", "protocols_ospf.c", "protocols_application.c",
    "protocols_radius.c", "hash_toeplitz.c",
    "combiner_ordered.c", "combiner_sorted.c", "combiner_unordered.c",
    "pthread_spinlock.c", "strndup.c",
    "data-struct/ring_buffer.c", "data-struct/vector.c",
    "data-struct/message_queue.c", "data-struct/deque.c",
    "data-struct/sliding_window.c", "data-struct/object_cache.c",
    "data-struct/linked_list.c", "data-struct/buckets.c",
    "data-struct/simple_circular_buffer.c",
]

# Public headers installed by upstream (lib/Makefile.am include_HEADERS +
# pkginclude_HEADERS).  libtrace.h itself is generated from libtrace.h.in.
_PUBLIC_HEADERS = [
    "libtrace.h", "libtrace_parallel.h", "dagformat.h", "lt_inttypes.h",
    "daglegacy.h", "rt_protocol.h", "erftypes.h", "pthread_spinlock.h",
    "format_ndag.h", "hash_toeplitz.h", "libtrace_radius.h",
    "data-struct/ring_buffer.h", "data-struct/object_cache.h",
    "data-struct/vector.h", "data-struct/deque.h", "data-struct/linked_list.h",
    "data-struct/buckets.h", "data-struct/sliding_window.h",
    "data-struct/message_queue.h", "data-struct/simple_circular_buffer.h",
]

# Substitutions that upstream's configure makes in libtrace.h.in.
_HEADER_SUBST = {
    "LIBTRACE_MAJOR": "4",
    "LIBTRACE_MID": "0",
    "LIBTRACE_MINOR": "34",
    "DAG_VERSION_NUM": "4.0",
    "HAVE_ATTRIBUTE_PACKED": "1",
    "HAVE_ATTRIBUTE_ALIGNED": "1",
    "HAVE_ATTRIBUTE_UNUSED": "1",
    "HAVE_ATTRIBUTE_DEPRECATED": "1",
    "HAVE_ATTRIBUTE_PURE": "1",
    "HAVE_ATTRIBUTE_FORMAT": "1",
    "HAVE_VISIBILITY": "1",
}

_CONFIG_H = """\
/* Generated by the libtrace/4.0.34 recipe (direct build, no autotools).
 * Equivalent to upstream configure run with libpcap + libwandio enabled and
 * every optional capture backend disabled.
 */
#ifndef LIBTRACE_CONFIG_H
#define LIBTRACE_CONFIG_H 1

#define PACKAGE "libtrace"
#define PACKAGE_NAME "libtrace"
#define PACKAGE_STRING "libtrace 4.0.34"
#define PACKAGE_VERSION "4.0.34"
#define VERSION "4.0.34"

#define STDC_HEADERS 1
#define HAVE_INTTYPES_H 1
#define HAVE_LIMITS_H 1
#define HAVE_STDDEF_H 1
#define HAVE_SYS_TIME_H 1
#define HAVE_SYS_PRCTL_H 1
#define HAVE_NET_IF_H 1
#define HAVE_NETINET_IN_H 1
#define HAVE_NET_ETHERNET_H 1
#define HAVE_NETINET_IF_ETHER_H 1
#define HAVE_NET_IF_ARP_H 1
#define HAVE_NETPACKET_PACKET_H 1
#define HAVE_LINUX_ETHTOOL_H 1

#define HAVE_LIBPCAP 1
#define HAVE_PCAP_H 1
#define HAVE_PCAP_BPF_H 1
#define HAVE_PCAP_CREATE 1
#define HAVE_PCAP_IMMEDIATE 1

#define HAVE_DECL_STRNDUP 1
#define HAVE_DECL_STRDUP 1
#define HAVE_DECL_STRCASECMP 1
#define HAVE_DECL_STRNCASECMP 1
#define HAVE_DECL_SNPRINTF 1
#define HAVE_DECL_VSNPRINTF 1
#define HAVE_DECL_POSIX_MEMALIGN 1

#endif /* LIBTRACE_CONFIG_H */
"""


class LibtraceConan(ConanFile):
    name = "libtrace"
    version = "4.0.34"
    package_type = "library"
    description = ("Library for reading, writing and processing network packet "
                   "traces (ERF, PCAP, PCAP-NG, TSH, DUCK, NDAG)")
    license = "LGPL-3.0-or-later"
    homepage = "https://github.com/LibtraceTeam/libtrace"
    url = "https://atomgit.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def requirements(self):
        # Both are mandatory for libtrace 4.x (configure errors out otherwise).
        self.requires("libpcap/1.10.6")
        self.requires("wandio/4.2.7")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("libtrace is supported only on Linux/OHOS")

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"][self.version], strip_root=True)

    # ---------------------------------------------------------------- toolchain
    def _compiler_candidates(self):
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        cands = []
        for key in ("c", "cc"):
            if execs.get(key):
                cands.append(execs[key])
        if os.environ.get("CC"):
            cands.append(os.environ["CC"])
        for bare in ("clang", "cc"):
            if shutil.which(bare):
                cands.append(shutil.which(bare))
        cands.extend(glob.glob("/data/service/hnp/ohos-sdk*/ohos/native/llvm/bin/clang"))
        seen, ordered = set(), []
        for c in cands:
            if c and c not in seen:
                seen.add(c)
                ordered.append(c)
        return ordered or ["clang"]

    def _tool_works(self, tool):
        if os.path.isabs(tool) and not os.path.isfile(tool):
            return False
        try:
            self.run('"%s" --version' % tool, env="conanbuild")
            return True
        except Exception:
            return False

    def _resolve(self, kind):
        if kind == "cc":
            for cand in self._compiler_candidates():
                if self._tool_works(cand):
                    self.output.info("libtrace: using C compiler %s" % cand)
                    return cand
            return "clang"
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        cands = [execs.get("ar"), os.environ.get("AR"),
                 shutil.which("llvm-ar"), shutil.which("ar"), "ar"]
        cands += glob.glob("/data/service/hnp/ohos-sdk*/ohos/native/llvm/bin/llvm-ar")
        for cand in cands:
            if cand and self._tool_works(cand):
                self.output.info("libtrace: using archiver %s" % cand)
                return cand
        return "ar"

    def _dep_flags(self):
        inc, libdirs, libs = [], [], []
        for dep in ("libpcap", "wandio"):
            cpp = self.dependencies[dep].cpp_info
            inc.extend(cpp.includedirs or [])
            libdirs.extend(cpp.libdirs or [])
            libs.extend(cpp.libs or [])
        return (" ".join('-I"%s"' % d for d in inc),
                " ".join('-L"%s"' % d for d in libdirs),
                " ".join("-l%s" % l for l in libs))

    def generate(self):
        # config.h + the configure-generated public header are written in
        # build(); nothing else to generate here.
        pass

    def build(self):
        apply_conandata_patches(self)
        src_lib = os.path.join(self.source_folder, "lib")
        cfg_dir = os.path.join(self.build_folder, "cfg")
        obj_dir = os.path.join(self.build_folder, "obj")
        os.makedirs(cfg_dir, exist_ok=True)
        os.makedirs(obj_dir, exist_ok=True)
        with open(os.path.join(cfg_dir, "config.h"), "w", encoding="utf-8") as fh:
            fh.write(_CONFIG_H)
        # test/test-errors.c includes "../config.h", i.e. relative to test/
        with open(os.path.join(self.source_folder, "config.h"), "w",
                  encoding="utf-8") as fh:
            fh.write(_CONFIG_H)

        # libtrace.h is generated by upstream configure from libtrace.h.in
        with open(os.path.join(src_lib, "libtrace.h.in"), encoding="utf-8") as fh:
            header = fh.read()
        # upstream configure uses AC_SUBST; some placeholders are written with a
        # space before the closing @ (e.g. "@LIBTRACE_MAJOR @"), so match both
        header = re.sub(r"@([A-Z_]+) ?@",
                        lambda m: _HEADER_SUBST.get(m.group(1), m.group(0)),
                        header)
        leftovers = sorted(set(re.findall(r"@[A-Z_]+ ?@", header)))
        if leftovers:
            raise ConanException(
                "unsubstituted libtrace.h.in placeholders: %s" % leftovers)
        with open(os.path.join(src_lib, "libtrace.h"), "w", encoding="utf-8") as fh:
            fh.write(header)

        cc = self._resolve("cc")
        dep_inc, dep_libdir, dep_libs = self._dep_flags()
        # -I on the source root as well: several sources use path-qualified
        # includes such as "lib/format_ndag.h" (upstream builds in-tree).
        inc = '-I"%s" -I"%s" -I"%s" -I"%s" %s' % (
            self.source_folder, src_lib, cfg_dir,
            os.path.join(src_lib, "data-struct"), dep_inc)
        cflags = "-O2 -fPIC -pthread -std=gnu99 -Wall"
        objs = []
        for src in _LIB_SOURCES:
            obj = os.path.join(obj_dir, src.replace("/", "_") + ".o")
            self.run('"%s" %s %s -c "%s" -o "%s"'
                     % (cc, cflags, inc, os.path.join(src_lib, src), obj),
                     env="conanbuild")
            objs.append('"%s"' % obj)
        obj_list = " ".join(objs)
        if self.options.shared:
            self.run('"%s" -shared %s %s %s -o "%s"'
                     % (cc, cflags, obj_list, dep_libdir + " " + dep_libs,
                        os.path.join(self.build_folder, "libtrace.so")),
                     env="conanbuild")
        else:
            ar = self._resolve("ar")
            self.run('"%s" rcs "%s" %s'
                     % (ar, os.path.join(self.build_folder, "libtrace.a"), obj_list),
                     env="conanbuild")
        self._audit_upstream_tests()
        self._run_upstream_tests(cc, inc, dep_libdir, dep_libs, obj_list)

    def _audit_upstream_tests(self):
        """R51: the 4.x tree ships test programs and trace fixtures, but the
        autotools build no longer builds them (test/ has no Makefile.am and
        `test` is not in the top-level SUBDIRS), so the count and the actual
        execution are recorded here for the pull request."""
        test_dir = os.path.join(self.source_folder, "test")
        self.run('ls "%s"/*.c | wc -l' % test_dir, env="conanbuild")
        self.run('ls "%s"/traces | wc -l' % test_dir, env="conanbuild")
        self.run('ls "%s"/Makefile.am "%s"/Makefile.in 2>&1 || true'
                 % (test_dir, test_dir), env="conanbuild")
        # The tag archive has no submodule content: libwandder (the ETSI
        # decode backend) and wandio are empty directories, so the ETSI
        # formats cannot be built from this archive at all.
        self.run('echo -n "libwandder entries: "; ls "%s/libwandder" | wc -l'
                 % self.source_folder, env="conanbuild")
        self.run('echo -n "wandio entries: "; ls "%s/wandio" | wc -l'
                 % self.source_folder, env="conanbuild")

    # Three upstream programs print packet contents through libpacketdump
    # (upstream's test/Makefile links every test with -ltrace -lpacketdump).
    _PACKETDUMP_TESTS = {"test-decode", "test-convert2", "test-dir"}

    # Test programs that upstream's own do-*.sh drivers never invoke, but
    # which still need arguments to run: test-convert2 wants two trace formats
    # (test/test-convert2.c exits when argc < 3).
    # Unlike test-convert, test-convert2 takes plain URIs and reads the output
    # back, so both arguments must name real files in traces/.
    _TEST_ARG_OVERRIDES = {
        "test-convert2": "erf:traces/100_packets.erf "
                         "erf:traces/100_packets.c2.out.erf",
    }

    def _resolve_tool(self, names, env_keys=()):
        for key in env_keys:
            if os.environ.get(key):
                return os.environ[key]
        for name in names:
            found = shutil.which(name)
            if found:
                return found
        return None

    def _build_packetdump(self, base_inc):
        """Build libpacketdump, the decoding/dumping component that lives in
        the same source tree and that upstream's test/Makefile links into every
        test program (LDLIBS = -ltrace -lpacketdump).  Only three upstream
        programs actually call into it, but without it they cannot even link.
        Its parser is generated with flex and bison and the code is C++, so this
        returns None when any of those tools is missing on the build host and
        the three programs are then reported as unsupported."""
        flex = self._resolve_tool(["flex", "lex"])
        bison = self._resolve_tool(["bison", "yacc"])
        if not (flex and bison):
            self.output.info("libtrace: flex/bison missing - libpacketdump "
                             "not built, %s cannot link"
                             % sorted(self._PACKETDUMP_TESTS))
            return None
        cxx = None
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        for cand in (execs.get("cpp"), os.environ.get("CXX"),
                     shutil.which("clang++"), shutil.which("c++"),
                     shutil.which("g++")):
            if cand and self._tool_works(cand):
                cxx = cand
                break
        if not cxx:
            self.output.info("libtrace: no C++ compiler - libpacketdump not built")
            return None
        ar = self._resolve("ar")
        src = os.path.join(self.source_folder, "libpacketdump")
        gen = os.path.join(self.build_folder, "libpacketdump")
        os.makedirs(gen, exist_ok=True)
        inc = '%s -I"%s" -I"%s"' % (base_inc, src, gen)
        self.run('cd "%s" && "%s" -o lexer.c "%s" && "%s" -d -o parser.c "%s"'
                 % (gen, flex, os.path.join(src, "lexer.l"), bison,
                    os.path.join(src, "parser.y")), env="conanbuild")
        objs = []
        self.run('"%s" -O2 -fPIC -std=c++14 %s -DDIRNAME=\\"libpacketdump\\" '
                 '-c "%s" -o "%s"' % (cxx, inc, os.path.join(src, "libpacketdump.cc"),
                                      os.path.join(gen, "libpacketdump.o")),
                 env="conanbuild")
        objs.append(os.path.join(gen, "libpacketdump.o"))
        for name, path in (("lexer.o", "lexer.c"), ("parser.o", "parser.c"),
                           ("bitbuffer.o", os.path.join(src, "bitbuffer.c"))):
            self.run('"%s" -O2 -fPIC -pthread -std=gnu99 %s -c "%s" -o "%s"'
                     % (self._resolve("cc"), inc, path if os.path.isabs(path)
                        else os.path.join(gen, path), os.path.join(gen, name)),
                     env="conanbuild")
            objs.append(os.path.join(gen, name))
        lib = os.path.join(gen, "libpacketdump.a")
        self.run('"%s" rcs "%s" %s' % (ar, lib, " ".join('"%s"' % o for o in objs)),
                 env="conanbuild")
        self.output.info("libtrace: built libpacketdump support library %s" % lib)
        return {"lib": lib, "gen": gen, "src": src}

    def _test_arguments(self, test_dir):
        """Arguments for the upstream test programs, taken from upstream's own
        do-*.sh drivers.  test-etsi appears twice in do-tests.sh: the first
        invocation needs a live ETSI stream on 127.0.0.1:60198 fed by socat, so
        the offline invocation (a file in traces/) wins when both exist."""
        args = {}
        for drv in sorted(glob.glob(os.path.join(test_dir, "do-*.sh"))):
            for line in io.open(drv, encoding="utf-8", errors="replace"):
                m = re.match(r"\s*do_test\s+\./(test-[A-Za-z0-9_-]+)\s*(.*)$", line)
                if not m:
                    continue
                name, argv = m.group(1), m.group(2).strip()
                # do-live-tests.sh passes shell variables ("$w" "$r") for live
                # capture devices; there is no NIC to expand them to here.
                if "$" in argv:
                    continue
                if name in args and "127.0.0.1" in args[name] \
                        and "127.0.0.1" not in argv:
                    args[name] = argv
                else:
                    args.setdefault(name, argv)
        args.update(self._TEST_ARG_OVERRIDES)
        return args

    def _prepare_run_dir(self, test_dir):
        """wandio/4.2.7 as published for OHOS is a stdio/thread only build: the
        recipe generates HAVE_LIBZ/HAVE_LIBBZ2/HAVE_LIBLZMA/HAVE_LIBZSTD = 0, so
        libtrace cannot open a compressed trace through it.  The upstream
        programs are therefore run from a scratch copy of test/ in which the
        compressed trace fixtures are stored expanded (same packet bytes, same
        file names), so the cases that name them - test-fragment hard-codes
        traces/fragtest.erf.gz - exercise their real assertions instead of
        failing inside the decompressor.  Running from a copy also keeps the
        *.out.* files that test-write/test-convert produce out of the source
        tree."""
        import bz2
        import gzip
        import lzma
        run_dir = os.path.join(self.build_folder, "test-run")
        if os.path.isdir(run_dir):
            shutil.rmtree(run_dir)
        shutil.copytree(test_dir, run_dir)
        traces = os.path.join(run_dir, "traces")
        expanded = []
        for name in sorted(os.listdir(traces)):
            path = os.path.join(traces, name)
            try:
                if name.endswith(".gz"):
                    with gzip.open(path, "rb") as fh:
                        data = fh.read()
                elif name.endswith(".bz2"):
                    with bz2.open(path, "rb") as fh:
                        data = fh.read()
                elif name.endswith((".xz", ".lzma")):
                    with lzma.open(path, "rb") as fh:
                        data = fh.read()
                else:
                    continue
            except (OSError, EOFError, ValueError) as exc:
                self.output.info("LTEST-FIXTURE-SKIP %s :: %s" % (name, exc))
                continue
            with open(path, "wb") as fh:
                fh.write(data)
            expanded.append(name)
        self.output.info("libtrace: expanded %d compressed trace fixtures "
                         "(wandio on OHOS has no compression backend): %s"
                         % (len(expanded), ", ".join(expanded)))
        return run_dir

    def _first_error_line(self, path):
        try:
            with io.open(path, encoding="utf-8", errors="replace") as fh:
                lines = [ln.strip() for ln in fh if ln.strip()]
        except OSError:
            return "no output"
        for line in lines:
            if "error" in line.lower():
                return line[:200]
        return lines[0][:200] if lines else "no output"


    def _run_upstream_tests(self, cc, inc, dep_libdir, dep_libs, obj_list):
        """R51: compile and run the upstream test programs.

        The 4.x tree ships 43 test programs and a directory of trace fixtures,
        but `test` is not in the top-level SUBDIRS and test/ has no Makefile.am,
        so the autotools build never compiles or runs them.  They are built here
        against the library that was just compiled so that the numbers quoted in
        the pull request are measured rather than assumed.  Failures are
        reported, not enforced: the test sources use several APIs that only
        exist in a full autotools build (libpacketdump, DAG drivers) and some
        need command line arguments.
        """
        test_dir = os.path.join(self.source_folder, "test")
        lib = os.path.join(self.build_folder, "libtrace.a")
        test_objs = os.path.join(self.build_folder, "test-obj")
        os.makedirs(test_objs, exist_ok=True)
        cases = sorted(glob.glob(os.path.join(test_dir, "*.c")))
        self.output.info("libtrace: %d upstream test programs found" % len(cases))
        run_dir = self._prepare_run_dir(test_dir)
        packetdump = self._build_packetdump(inc)
        pd_inc = (' -I"%s" -I"%s"' % (packetdump["src"], packetdump["gen"])
                  if packetdump else ' -I"%s"' % os.path.join(self.source_folder,
                                                              "libpacketdump"))
        pd_lib = ' "%s"' % packetdump["lib"] if packetdump else ""
        # musl's headers do not pull signal.h in through netinet/* the way
        # glibc does, so every test is compiled with it explicitly included
        # (only test-etsi actually needs SIGINT/SIGALRM).
        test_inc = '%s -include signal.h -I"%s"%s' % (inc, test_dir, pd_inc)
        passed = 0
        cfail = 0
        rfail = 0
        driver_args = self._test_arguments(test_dir)
        for case in cases:
            name = os.path.basename(case)[:-2]
            exe = os.path.join(test_objs, name)
            extra_lib = pd_lib + " -lc++" if name in self._PACKETDUMP_TESTS else ""
            cc_log = exe + ".cc.log"
            cmd = ('"%s" -O2 -pthread -std=gnu99 %s "%s" "%s"%s %s %s '
                   '-o "%s" > "%s" 2>&1' % (cc, test_inc, case, lib, extra_lib,
                                            dep_libdir, dep_libs, exe, cc_log))
            try:
                self.run(cmd, env="conanbuild")
            except Exception:
                cfail += 1
                self.output.info("LTEST-FAIL-COMPILE %s :: %s"
                                 % (name, self._first_error_line(cc_log)))
                continue
            args = driver_args.get(name, "")
            run_log = exe + ".run.log"
            run = '"%s" %s < /dev/null > "%s" 2>&1' % (exe, args, run_log)
            if shutil.which("timeout"):
                run = "timeout 120 " + run
            try:
                self.run(run, cwd=run_dir, env="conanbuild")
                passed += 1
                self.output.info("LTEST-PASS %s" % name)
            except Exception:
                rfail += 1
                self.output.info("LTEST-FAIL-RUN %s :: %s"
                                 % (name, self._first_error_line(run_log)))
        self.output.info("LTEST-SUMMARY total=%d pass=%d compile_fail=%d run_fail=%d"
                         % (len(cases), passed, cfail, rfail))

    def package(self):
        libname = "libtrace.so" if self.options.shared else "libtrace.a"
        copy(self, libname, src=self.build_folder,
             dst=os.path.join(self.package_folder, "lib"))
        for header in _PUBLIC_HEADERS:
            copy(self, header, src=os.path.join(self.source_folder, "lib"),
                 dst=os.path.join(self.package_folder, "include"),
                 keep_path=True)
        copy(self, "COPYING*", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.libs = ["trace"]
        self.cpp_info.system_libs = ["pthread"]
        self.cpp_info.set_property("cmake_file_name", "libtrace")
        self.cpp_info.set_property("cmake_target_name", "libtrace::libtrace")
