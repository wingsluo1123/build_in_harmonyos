#!/usr/bin/env python3
"""Conan test_package — libuser 0.64-git20241106-dfsg (L1 official test).

Substantive verification (R34): compiles test_libuser.c against the real
libuser headers/library and really executes it. The 6 consumer groups call
the genuine API surface: lu_start/lu_end (context + back-end module dlopen
of libuser_files via a generated LIBUSER_CONF), lu_get_modules,
lu_user_default/lu_group_default plus lu_ent attribute round-trips, and
lu_cfg_read_single (proves the config plumbing honors LIBUSER_CONF).

HMBS machine evidence: test() runs the binary, counts the deterministic
"PASS:" lines it prints (one per group, single source, no fixups) for
HMBS_TEST_PACKAGE_RESULT, and re-emits the persisted
HMBS_UPSTREAM_TEST_RESULT so a Conan cache hit never loses upstream
evidence. A final literal self.run satisfies the PF3/L0d test-runner gate.
"""

import glob
import json
import os
import subprocess

from conan import ConanFile
from conan.tools.build import can_run
from conan.tools.cmake import CMake, cmake_layout

CONSUMER_GROUPS = 6


class LibuserTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "CMakeDeps", "CMakeToolchain", "VirtualRunEnv"

    def requirements(self):
        self.requires(self.tested_reference_str)
        # <libuser/user.h> includes <glib.h>; keep the same version the
        # recipe builds against (accountsservice test_package pattern).
        self.requires("glib/2.84.0.1", transitive_headers=True, transitive_libs=True)

    def layout(self):
        cmake_layout(self)

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def _package_libdir(self):
        try:
            folder = self.dependencies["libuser"].package_folder
        except Exception:
            return None
        libdir = os.path.join(folder, "lib")
        return libdir if os.path.isdir(libdir) else None

    def _write_libuser_conf(self):
        # Upstream honors LIBUSER_CONF (lib/config.c) when not setuid. Point
        # defaults/moduledir at the Conan package so lu_start() dlopens the
        # packaged libuser_files/libuser_shadow back ends (no patch needed).
        # CI #62950: minimal [defaults]-only conf left lu_start() failing
        # (context_start FAIL, 0/6). Mirror upstream tests/utils.conf.in
        # sections so the context has user/group defaults plus files/shadow
        # back-end directories (nonroot=yes, like the upstream harness).
        libdir = self._package_libdir()
        moduledir = os.path.join(libdir, "libuser") if libdir else ""
        conf_dir = os.path.join(self.build_folder, "hmbs-libuser-conf")
        os.makedirs(conf_dir, exist_ok=True)
        files_dir = os.path.join(conf_dir, "files")
        os.makedirs(files_dir, exist_ok=True)
        for name in ("passwd", "shadow", "group", "gshadow"):
            cand = os.path.join(files_dir, name)
            if not os.path.isfile(cand):
                with open(cand, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write("")
        conf_path = os.path.join(conf_dir, "libuser.conf")
        mod_posix = moduledir.replace("\\", "/")
        files_posix = files_dir.replace("\\", "/")
        with open(conf_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("# Generated by test_package: modules live in the Conan package.\n")
            handle.write("[defaults]\n")
            handle.write("moduledir = %s\n" % mod_posix)
            handle.write("skeleton = /etc/skel\n")
            handle.write("mailspooldir = /var/mail\n")
            handle.write("modules = files shadow\n")
            handle.write("create_modules = files shadow\n")
            handle.write("crypt_style = md5\n")
            handle.write("[userdefaults]\n")
            # NOTE: single %n/%u (upstream utils.conf.in spelling). Plain
            # file write, no printf-style escaping: CI #91463 logged
            # `%%n`/`%%u` and libuser warned `Invalid default value of
            # field userdefaults/LU_GIDNUMBER`, failing user/group_default.
            handle.write("LU_USERNAME = %n\n")
            handle.write("LU_UIDNUMBER = 500\n")
            handle.write("LU_GIDNUMBER = %u\n")
            handle.write("[groupdefaults]\n")
            handle.write("LU_GROUPNAME = %n\n")
            handle.write("LU_GIDNUMBER = 500\n")
            handle.write("[files]\n")
            handle.write("directory = %s\n" % files_posix)
            handle.write("nonroot = yes\n")
            handle.write("[shadow]\n")
            handle.write("directory = %s\n" % files_posix)
            handle.write("nonroot = yes\n")
        os.environ["LIBUSER_CONF"] = conf_path
        return conf_path, moduledir

    def _reemit_upstream_result(self):
        try:
            upstream = None
            try:
                pkg = self.dependencies["libuser"].package_folder
                cand = os.path.join(pkg, "res", "hmbs_upstream.json")
                if os.path.isfile(cand):
                    with open(cand, "r", encoding="utf-8") as handle:
                        upstream = json.load(handle)
            except Exception:
                upstream = None
            if isinstance(upstream, dict) and "discovered" in upstream:
                message = "HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(upstream, ensure_ascii=False)
                try:
                    print(message, flush=True)
                except OSError:
                    pass
                self.output.info(message)
            else:
                self.output.warning(
                    "persisted hmbs_upstream.json missing; "
                    "upstream evidence only available on fresh build"
                )
        except Exception as exc:
            self.output.warning("upstream re-emit failed: %r" % (exc,))

    def _emit_test_marker(self, passed, ok_count, reason="", output=""):
        marker = {
            "executed": True,
            "passed": passed,
            "command": "./test_libuser",
            "discovered": CONSUMER_GROUPS,
            "passedCount": ok_count,
        }
        if reason:
            marker["reason"] = reason
        # rule4: consumer short of 100% must carry concrete technical
        # cause + evidence (gaps sum == discovered - passedCount).
        if not passed:
            missing = CONSUMER_GROUPS - ok_count
            hay = "%s\n%s" % (reason, output or "")
            if "Cannot obtain lock" in hay or "Operation not permitted" in hay:
                category = "ohos_feature"
                detail = "consumer run hit worker filesystem lock/permission denial (see evidence)"
            elif "Error loading shared library" in hay or "symbol not found" in hay or "Error relocating" in hay:
                category = "test_failure"
                detail = "loader could not resolve the glib/intl runtime closure for ./test_libuser (see evidence)"
            else:
                category = "test_failure"
                detail = "consumer groups without PASS lines (see evidence tail)"
            marker["gaps"] = [{
                "count": missing,
                "category": category,
                "detail": detail,
                "evidence": hay[-800:],
            }]
        message = "HMBS_TEST_PACKAGE_RESULT=" + json.dumps(marker, ensure_ascii=False)
        try:
            print(message, flush=True)
        except OSError:
            pass
        self.output.info(message)

    def test(self):
        if not can_run(self):
            marker = {
                "executed": False,
                "passed": False,
                "command": "./test_libuser",
                "discovered": CONSUMER_GROUPS,
                "passedCount": 0,
                "reason": "cross-build: OHOS binaries are not runnable on the build host",
            }
            message = "HMBS_TEST_PACKAGE_RESULT=" + json.dumps(marker, ensure_ascii=False)
            try:
                print(message, flush=True)
            except OSError:
                pass
            self.output.info(message)
            return
        conf_path, moduledir = self._write_libuser_conf()
        self.output.info("LIBUSER_CONF=%s (moduledir=%s)" % (conf_path, moduledir))
        try:
            with open(conf_path, "r", encoding="utf-8", errors="replace") as handle:
                self.output.info("LIBUSER_CONF content:\n%s" % handle.read()[:1500])
        except OSError:
            pass
        try:
            if moduledir and os.path.isdir(moduledir):
                self.output.info("moduledir listing: %s" % sorted(os.listdir(moduledir))[:20])
            else:
                self.output.warning("moduledir missing/not-a-dir: %s" % moduledir)
        except OSError as exc:
            self.output.warning("moduledir listing failed: %r" % (exc,))
        if not moduledir or not os.path.isdir(moduledir):
            self._emit_test_marker(False, 0, "packaged module dir missing: %s" % moduledir)
            self._reemit_upstream_result()
            raise RuntimeError("libuser module dir missing: %s" % moduledir)
        bin_path = None
        for root, _, files in os.walk(self.build_folder):
            if "test_libuser" in files:
                cand = os.path.join(root, "test_libuser")
                if os.path.isfile(cand):
                    bin_path = cand
                    break
        if bin_path is None:
            self._emit_test_marker(False, 0, "test_libuser binary missing under build folder")
            self._reemit_upstream_result()
            raise RuntimeError("test_libuser binary missing")
        # Compose runtime env: package libdir first (libuser.so), then every
        # dependency libdir. The OHOS loader ignores LD_LIBRARY_PATH
        # (stale_runtime_library: consumer resolved system old glib and
        # failed with g_str_equal/g_ascii_table symbol-not-found, 0/6), so
        # LD_PRELOAD the exact packaged libuser plus the Conan glib shared
        # libs for both the capture run and the final self.run gate.
        run_env = dict(os.environ)
        libdirs = []
        libdir = self._package_libdir()
        if libdir and libdir not in libdirs:
            libdirs.append(libdir)
        try:
            for dep in self.dependencies.values():
                try:
                    dirs = dep.cpp_info.libdirs
                except Exception:
                    continue
                for path in dirs or []:
                    if path and os.path.isdir(path) and path not in libdirs:
                        libdirs.append(path)
        except Exception:
            pass
        if libdirs:
            old_ld = run_env.get("LD_LIBRARY_PATH", "")
            run_env["LD_LIBRARY_PATH"] = os.pathsep.join(libdirs + ([old_ld] if old_ld else []))
        def _is_elf(path):
            try:
                with open(path, "rb") as handle:
                    return handle.read(4) == b"\x7fELF"
            except OSError:
                return False

        preloads = []
        # Round-2 fix: the Conan libglib itself needs g_libintl_* at
        # relocation, so the shared intl provider (glib-bundled
        # libintl.so, wv/1.2.9 precedent) must come FIRST in LD_PRELOAD;
        # preloading libuser+glib alone repeats the missing-symbol failure.
        try:
            intl_dep = None
            try:
                intl_dep = self.dependencies.get("glib") if hasattr(self.dependencies, "get") else self.dependencies["glib"]
            except Exception:
                intl_dep = None
            intl_dirs = []
            if intl_dep is not None:
                try:
                    for path in (intl_dep.cpp_info.libdirs or []):
                        if path and os.path.isdir(path) and path not in intl_dirs:
                            intl_dirs.append(path)
                except Exception:
                    pass
            intl_pick = ""
            for intl_dir in intl_dirs if intl_dirs else libdirs:
                for cand in sorted(glob.glob(os.path.join(intl_dir, "libintl.so*"))):
                    try:
                        if os.path.isfile(cand) and ".so." in cand and _is_elf(cand):
                            intl_pick = cand
                            break
                    except OSError:
                        continue
                if intl_pick:
                    break
            if intl_pick:
                preloads.append(intl_pick)
                self.output.info("test LD_PRELOAD intl provider: %s" % intl_pick)
        except Exception:
            pass
        if libdir:
            cands = sorted(glob.glob(os.path.join(libdir, "libuser.so*")))
            pick = None
            for cand in cands:
                if os.path.isfile(cand) and ".so." in cand:
                    pick = cand
                    break
            if pick is None:
                for cand in cands:
                    if os.path.isfile(cand):
                        pick = cand
                        break
            if pick:
                preloads.append(pick)
        # Conan glib trio: versioned real files first (skip .so linker
        # stubs which may be text scripts on some packages).
        try:
            glib_dep = None
            try:
                glib_dep = self.dependencies.get("glib") if hasattr(self.dependencies, "get") else self.dependencies["glib"]
            except Exception:
                glib_dep = None
            glib_dirs = []
            if glib_dep is not None:
                try:
                    for path in (glib_dep.cpp_info.libdirs or []):
                        if path and os.path.isdir(path) and path not in glib_dirs:
                            glib_dirs.append(path)
                except Exception:
                    pass
            for glib_dir in glib_dirs if glib_dirs else libdirs:
                for pattern in ("libglib-2.0.so*", "libgobject-2.0.so*", "libgmodule-2.0.so*"):
                    for cand in sorted(glob.glob(os.path.join(glib_dir, pattern))):
                        try:
                            if os.path.isfile(cand) and cand not in preloads and not cand.endswith(".so") and _is_elf(cand):
                                preloads.append(cand)
                        except OSError:
                            continue
                if len(preloads) >= 2:
                    break
        except Exception:
            pass
        preloads = [p for p in preloads if p and os.path.isfile(p) and _is_elf(p)]
        if preloads:
            run_env["LD_PRELOAD"] = ":".join(preloads)
            self.output.info("LD_PRELOAD=%s" % run_env["LD_PRELOAD"])
        proc = subprocess.run(
            [bin_path],
            env=run_env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=120,
            cwd=os.path.dirname(bin_path),
        )
        out = proc.stdout or ""
        self.output.info(out[-2000:])
        ok_count = sum(1 for line in out.splitlines() if line.startswith("PASS:"))
        passed = proc.returncode == 0 and ok_count == CONSUMER_GROUPS
        self._emit_test_marker(passed, ok_count, output=out,
                               reason="" if passed else ("rc=%s" % proc.returncode))
        self._reemit_upstream_result()
        if not passed:
            raise RuntimeError(
                "consumer test failed: rc=%s ok=%s/%s" % (proc.returncode, ok_count, CONSUMER_GROUPS)
            )
        # Literal test-runner gate (PF3/L0d): real self.run execution with
        # the same runtime paths so the conanrun invocation also resolves
        # the packaged libs on OHOS.
        for key in ("LD_LIBRARY_PATH", "LD_PRELOAD", "LIBUSER_CONF"):
            if key in run_env:
                os.environ[key] = run_env[key]
        self.run(bin_path, env="conanrun")
