#!/usr/bin/env python3
"""Conan recipe — libvorbis 1.3.7 (Autotools).

Ogg Vorbis is a fully open, general-purpose compressed audio format.
"""
import os
import re
import subprocess

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class LibvorbisConan(ConanFile):
    name = "libvorbis"
    version = "1.3.7"
    description = "Ogg Vorbis is a fully open, general-purpose compressed audio format"
    license = "BSD-3-Clause"
    homepage = "https://xiph.org/vorbis/"
    url = ""

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("libogg/1.3.6")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # E114: On HMDFS, mktemp -d creates directories with restrictive
        # permissions (drwx--S---), preventing file creation inside.
        # Patch configure to bypass mktemp, then run configure manually.
        if self.settings.os in ("OHOS", "Linux"):
            _fix_hmdfs_mktemp(self, "configure")

        autotools = Autotools(self)

        # Run configure; if config.status fails (E114), patch it and re-run.
        try:
            autotools.configure()
        except Exception:
            # config.status was generated by configure but failed due to E114.
            # Patch the generated config.status and re-run it.
            _fix_hmdfs_mktemp(self, "config.status")
            self.run("sh ./config.status", env="conanbuild")
            # config.status should now succeed; continue to make.

        autotools.make(args=["-j2"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = ["vorbis", "vorbisenc", "vorbisfile"]
        self.cpp_info.requires = ["libogg::libogg"]


def _fix_hmdfs_mktemp(conanfile, filename):
    """Patch autotools script to bypass mktemp on HMDFS (E114).

    HMDFS creates mktemp directories with drwx--S--- permissions,
    preventing file creation inside. This patches the ac_tmp variable
    to use a pre-created directory instead.
    """
    from pathlib import Path

    src = Path(conanfile.build_folder) / filename
    if not src.exists():
        return

    content = src.read_text(encoding="utf-8", errors="replace")

    # Create a writable temp directory
    tmpdir = os.environ.get("TMPDIR", "/tmp")
    fixed_dir = os.path.join(tmpdir, f"ohc-fix-{os.getpid()}")
    os.makedirs(fixed_dir, exist_ok=True)

    # Replace ac_tmp=$tmp with fixed directory
    patched = content.replace("ac_tmp=$tmp", f"ac_tmp={fixed_dir}")
    if patched != content:
        src.write_text(patched, encoding="utf-8")
        conanfile.output.info(f"Patched {filename} for HMDFS mktemp (E114)")
