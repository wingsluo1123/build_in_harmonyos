int main(void)
{
	struct zc_ctx *ctx = NULL;
	struct zc_crk_bforce *crk = NULL;
	struct zc_crk_pwcfg cfg;
	char out[7];
	const char *zip_path = "ohos_stored.zip";
	FILE *f = fopen(zip_path, "wb");
	if (!f) {
		fprintf(stderr, "FAIL: cannot create fixture\n");
		return 1;
	}
	fwrite(stored_zip, 1, sizeof(stored_zip), f);
	fclose(f);

	if (zc_new(&ctx) != 0) {
		fprintf(stderr, "FAIL: zc_new\n");
		return 1;
	}
	if (zc_crk_bforce_new(ctx, &crk) != 0) {
		fprintf(stderr, "FAIL: zc_crk_bforce_new\n");
		zc_unref(ctx);
		return 1;
	}

	/* upstream test_bruteforce_stored: password "pass" */
	strcpy(cfg.set, "password");
	cfg.maxlen = 4;
	cfg.setlen = 8;
	memset(cfg.initial, 0, ZC_PW_MAXLEN + 1);

	if (zc_crk_bforce_init(crk, zip_path, &cfg) != 0) {
		fprintf(stderr, "FAIL: zc_crk_bforce_init\n");
		zc_crk_bforce_unref(crk);
		zc_unref(ctx);
		return 1;
	}

	/* finding the password triggers cancel_workers() -> OHOS fallback */
	int rc = zc_crk_bforce_start(crk, out, sizeof(out));
	if (rc != 0) {
		fprintf(stderr, "FAIL: zc_crk_bforce_start rc=%d\n", rc);
		zc_crk_bforce_unref(crk);
		zc_unref(ctx);
		return 1;
	}
	if (strcmp(out, "pass") != 0) {
		fprintf(stderr, "FAIL: got '%s', expected 'pass'\n", out);
		zc_crk_bforce_unref(crk);
		zc_unref(ctx);
		return 1;
	}

	zc_crk_bforce_unref(crk);
	zc_unref(ctx);
	remove(zip_path);
	printf("PASS: libzc OHOS cancellation fallback (bruteforce found '%s')\n", out);
	return 0;
}