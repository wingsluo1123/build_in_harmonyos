int main(void)
{
	struct zc_ctx *ctx = NULL;
	struct zc_file *file = NULL;
	const char *zip_path = "stored_test.zip";
	FILE *f = fopen(zip_path, "wb");
	if (!f)
		return 1;
	fwrite(stored_zip, 1, sizeof(stored_zip), f);
	fclose(f);

	if (zc_new(&ctx) != 0) {
		fprintf(stderr, "zc_new() failed\n");
		return 1;
	}
	if (zc_file_new_from_filename(ctx, zip_path, &file) != 0) {
		fprintf(stderr, "zc_file_new_from_filename() failed\n");
		zc_unref(ctx);
		return 1;
	}
	if (zc_file_open(file) != 0) {
		fprintf(stderr, "zc_file_open() failed\n");
		zc_file_unref(file);
		zc_unref(ctx);
		return 1;
	}
	if (!zc_file_isopened(file)) {
		fprintf(stderr, "zc_file_isopened() false\n");
		zc_file_unref(file);
		zc_unref(ctx);
		return 1;
	}

	/* enumerate entries — expect exactly test1/test2/test3 */
	struct zc_info *info = zc_file_info_next(file, NULL);
	int entries = 0, found = 0;
	while (info) {
		const char *name = zc_file_info_name(info);
		if (name && (strcmp(name, "test1") == 0 ||
			     strcmp(name, "test2") == 0 ||
			     strcmp(name, "test3") == 0))
			found++;
		entries++;
		info = zc_file_info_next(file, info);
	}
	zc_file_close(file);
	zc_file_unref(file);
	zc_unref(ctx);
	remove(zip_path);

	if (entries != 3 || found != 3) {
		fprintf(stderr, "unexpected entries: %d (matched %d)\n", entries, found);
		return 1;
	}
	printf("libzc 0.4.3 API test: OK (context/open/3 entries)\n");
	return 0;
}