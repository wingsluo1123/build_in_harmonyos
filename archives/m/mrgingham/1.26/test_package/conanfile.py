#!/usr/bin/env python3
"""Conan test_package for mrgingham 1.26 (Conan L1 consumer test).

Exercises the *installed* package from a consumer's point of view:

1. Compiles and links a C++ program against the public API (mrgingham.hh) and
   runs it.  The program calls mrgingham::find_grid_from_points() on a synthetic
   lattice and asserts that the detected grid is a correct permutation of the
   input points (a real functional assertion, not an exit-code-only check; R34).
2. Runs the installed `mrgingham` CLI with --help and asserts its usage text.

The consumer build uses pkg-config metadata generated by the recipe
(package_info.pkg_config_name = "mrgingham", whose .pc Requires: opencv4), so it
also verifies that the packaged pkg-config file is usable.
"""
import json
import os
import shutil

from conan import ConanFile
from conan.tools.build import can_run
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout


class MrginghamTestConan(ConanFile):
    settings = "os", "arch", "compiler", "build_type"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def layout(self):
        # Keep the generated pkg-config files / compiled test binary out of the
        # recipe's source directory (they land in build-release/ instead).
        basic_layout(self)

    def generate(self):
        PkgConfigDeps(self).generate()

    def test(self):
        if not can_run(self):
            return

        pkg = self.dependencies[self.tested_reference_str].package_folder
        gen = self.generators_folder
        _, cxx = self._compilers()
        # `env VAR=... pkg-config ...` so the substitution sees the generator
        # directory (a plain `VAR=... cmd $(sub)` prefix would not).
        pkg_config = (f'env PKG_CONFIG_PATH="{gen}" PKG_CONFIG_LIBDIR="{gen}" '
                      'pkg-config')

        src = os.path.join(self.source_folder, "test_mrgingham.cpp")
        exe = os.path.join(self.build_folder, "test_mrgingham")
        # The link runs the SDK's lld, which needs the SDK's own libxml2.so.16
        # (its RUNPATH is $ORIGIN/../lib).  `conanrun` puts this package's
        # transitive Conan lib dirs -- including libxml2 -- first on
        # LD_LIBRARY_PATH, which shadows the SDK copy and makes lld abort with
        # "Error loading shared library libxml2.so.16 ... symbol not found".
        # Prepend the SDK llvm/lib (evaluated after conanrun is sourced) so lld
        # resolves its own libxml2; the compiled test binary still runs under
        # conanrun below.
        sdk_ld = self._sdk_llvm_libdir()
        ld_env = f'LD_LIBRARY_PATH="{sdk_ld}:$LD_LIBRARY_PATH" ' if sdk_ld else ""
        self.run(
            f'{ld_env}{cxx} -std=c++17 "{src}" -o "{exe}" '
            f'$({pkg_config} --cflags --libs mrgingham)',
            env="conanrun",
        )
        self.run(f'"{exe}"', env="conanrun")

        # CLI smoke test: the packaged tool must run and print its usage.
        cli = os.path.join(pkg, "bin", "mrgingham")
        out = os.path.join(self.build_folder, "mrgingham-help.txt")
        self.run(f'"{cli}" --help > "{out}"', env="conanrun")
        with open(out, encoding="utf-8", errors="replace") as fh:
            help_text = fh.read()
        assert "Usage:" in help_text and "gridn" in help_text, \
            "mrgingham --help did not print the expected usage text"

    def _compilers(self):
        executables = self.conf.get("tools.build:compiler_executables", default={})
        if isinstance(executables, str):
            executables = json.loads(executables)
        return executables.get("c", "clang"), executables.get("cpp", "clang++")

    def _sdk_llvm_libdir(self):
        """SDK ``llvm/lib`` that holds ``libxml2.so.16``, or "" if not found.

        See test() for why the SDK copy must win over the Conan one for lld.
        """
        _, cxx = self._compilers()
        compiler = os.path.realpath(shutil.which(cxx) or cxx)
        llvm_lib = os.path.join(os.path.dirname(os.path.dirname(compiler)), "lib")
        if os.path.isfile(os.path.join(llvm_lib, "libxml2.so.16")):
            return llvm_lib
        return ""
