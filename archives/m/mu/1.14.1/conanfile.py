#!/usr/bin/env python3
"""Conan recipe — mu 1.14.1

Mu is a tool for dealing with e-mail, stored in Maildir-format.
It indexes mail using Xapian and provides tools for searching and viewing.
Meson project, depends on glib, gmime, xapian-core.
License: GPL-3.0-or-later
Homepage: https://github.com/djcb/mu
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.meson import Meson, MesonToolchain
from conan.tools.layout import basic_layout
from conan.tools.env import Environment
from conan.tools.gnu import PkgConfigDeps


class MuConan(ConanFile):
    name = "mu"
    version = "1.14.1"
    description = "Mu is a tool for dealing with e-mail, indexed by Xapian"
    license = "GPL-3.0-or-later"
    homepage = "https://github.com/djcb/mu"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("glib/2.84.0")
        self.requires("gmime/3.2.7")
        self.requires("xapian-core/1.4.26")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = MesonToolchain(self)
        # mu requires C++20 features (enable_bitops, charconv etc.)
        tc.cpp_std = "c++20"
        # Disable optional features not available on OHOS
        tc.project_options["scm"] = "disabled"
        tc.project_options["guile"] = "disabled"
        tc.project_options["cld2"] = "disabled"
        tc.project_options["readline"] = "disabled"
        tc.project_options["tests"] = "disabled"
        # Use embedded fmt and CLI11 (no conan packages available)
        tc.project_options["use-embedded-fmt"] = "true"
        tc.project_options["use-embedded-cli11"] = "true"
        # Disable emacs byte-compilation
        tc.project_options["emacs"] = ""
        tc.generate()

        # Generate .pc files for conan dependencies so meson can find them
        pkg_config = PkgConfigDeps(self)
        pkg_config.generate()

        # Copy original .pc files from dependency package dirs to generators folder
        # so meson can find sub-packages like gobject-2.0, gio-2.0 etc.
        gen_folder = self.generators_folder
        for dep_name, dep in self.dependencies.items():
            pkg_folder = getattr(dep, "package_folder", None)
            if not pkg_folder:
                for libdir in dep.cpp_info.libdirs:
                    if os.path.isabs(libdir):
                        pkg_folder = os.path.dirname(libdir)
                        break
            if pkg_folder:
                pc_dir = os.path.join(pkg_folder, "lib", "pkgconfig")
                if os.path.isdir(pc_dir):
                    import shutil as _shutil
                    for pc_file in os.listdir(pc_dir):
                        if pc_file.endswith(".pc"):
                            src = os.path.join(pc_dir, pc_file)
                            dst = os.path.join(gen_folder, pc_file)
                            # Only copy if not already generated by PkgConfigDeps
                            if not os.path.exists(dst):
                                # Fix prefix in .pc file
                                with open(src, "r") as f:
                                    content = f.read()
                                content = content.replace(
                                    "prefix=/\n",
                                    f"prefix={pkg_folder}\n"
                                )
                                with open(dst, "w") as f:
                                    f.write(content)

        # OHOS: ensure llvm tools are in PATH for meson
        env = Environment()
        env.define("AR", "/data/service/hnp/bin/llvm-ar")
        env.define("NM", "/data/service/hnp/bin/llvm-nm")
        env.define("RANLIB", "/data/service/hnp/bin/llvm-ranlib")
        env.define("STRIP", "/data/service/hnp/bin/llvm-strip")
        # Also add dependency package pkgconfig dirs to PKG_CONFIG_PATH
        # so sub-packages like gobject-2.0, gio-2.0 etc. are found
        pkg_config_paths = []
        for dep_name, dep in self.dependencies.items():
            # Try package_folder first
            pkg_folder = getattr(dep, "package_folder", None)
            if not pkg_folder:
                # Fall back to cpp_info libdirs
                for libdir in dep.cpp_info.libdirs:
                    if os.path.isabs(libdir):
                        pc_dir = os.path.join(libdir, "pkgconfig")
                        if os.path.isdir(pc_dir):
                            pkg_config_paths.append(pc_dir)
            else:
                pc_dir = os.path.join(pkg_folder, "lib", "pkgconfig")
                if os.path.isdir(pc_dir):
                    pkg_config_paths.append(pc_dir)
        if pkg_config_paths:
            existing = os.environ.get("PKG_CONFIG_PATH", "")
            all_paths = pkg_config_paths + ([existing] if existing else [])
            env.define_path("PKG_CONFIG_PATH", os.pathsep.join(all_paths))
        # OHOS: musl dynamic linker is in /lib
        env.append("LDFLAGS", "-L/lib")
        env.vars(self).save_script("mu_env")

    def build(self):
        apply_conandata_patches(self)
        meson = Meson(self)
        meson.configure()
        meson.build()

    def package(self):
        meson = Meson(self)
        meson.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
