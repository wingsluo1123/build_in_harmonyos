#!/bin/bash
# test_mwrap.sh — mwrap 1.3.5 consumer smoke test (R34).
#
# Drives the installed mwrap executable end to end:
#   1. mwrap runs and prints its usage banner
#   2. generates a MEX gateway (.cc) + MATLAB stub (.m) from a real .mw input
#   3. verifies the generated gateway content (entry point, version marker)
#   4. verifies the generated .m stub dispatches through the mex function
#
# Usage: test_mwrap.sh <bin_dir> <work_dir>
set -u

BINDIR="$1"
WORK="$2"
MWRAP="$BINDIR/mwrap"

pass=0
fail=0

ok()  { echo "PASS: $1"; pass=$((pass + 1)); }
bad() { echo "FAIL: $1"; fail=$((fail + 1)); }

mkdir -p "$WORK" || exit 1
cd "$WORK" || exit 1

# ── 1. mwrap runs and prints usage ──
out="$("$MWRAP" 2>&1)"
if [ $? -eq 0 ] && printf '%s' "$out" | grep -q "Syntax:"; then
  ok "mwrap runs and prints usage banner"
else
  bad "mwrap usage banner missing or nonzero exit"
fi

# ── 2. real .mw input → gateway + stub ──
cat > demo.mw <<'EOF'
% demo.mw — minimal mwrap consumer test input
$ void add(double a, double b, double *c) { *c = a + b; }
@function c=add(a,b)
# add(double a, double b, output double[1]c);
EOF

if "$MWRAP" -mex demomex -c demomex.cc -m demo.m demo.mw >/dev/null 2>&1; then
  ok "mwrap generates gateway and stub (exit 0)"
else
  bad "mwrap generation failed"
fi

# ── 3. gateway content checks ──
if [ -s demomex.cc ] && grep -q "mexFunction" demomex.cc; then
  ok "gateway demomex.cc exists with mexFunction entry point"
else
  bad "gateway demomex.cc missing or has no mexFunction"
fi

if grep -q "Code generated by mwrap 1.3.5" demomex.cc; then
  ok "gateway carries mwrap 1.3.5 version marker"
else
  bad "gateway version marker missing"
fi

# ── 4. .m stub dispatches through the mex gateway ──
if [ -s demo.m ] && grep -q "function c=add(a,b)" demo.m \
   && grep -q "demomex(mex_id_" demo.m; then
  ok ".m stub declares add() and dispatches via demomex"
else
  bad ".m stub missing or wrong dispatch"
fi

echo
echo "consumer smoke: pass=$pass fail=$fail"
[ "$fail" -eq 0 ]
