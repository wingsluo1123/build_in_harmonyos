use strict;
use warnings;
use Readonly ();
use JSON::PP;
Readonly->VERSION('2.05');
my @done;
Readonly::Scalar my $scalar => 'published-immutable-value';
my $error = ''; eval { $scalar = 'replaced' }; $error = $@;
die 'scalar mutation accepted' unless $error =~ /read-only/ && $scalar eq 'published-immutable-value';
die 'modern native readonly backend missing' unless $Readonly::XSokay && Internals::SvREADONLY($scalar) && !tied($scalar);
push @done, 'native-builtin-scalar';
my $missing = ''; eval { require Readonly::Array; 1 } or $missing = $@;
die 'qualified callable unexpectedly treated as module file' unless $missing =~ /Can't locate Readonly\/Array\.pm/;
die 'actual callable absent' unless Readonly->can('Array');
Readonly::Array my @array => ('actual','dependency','function');
eval { $array[1] = 'changed' }; $error = $@;
die 'array mutation accepted' unless $error =~ /read-only/ && join(':',@array) eq 'actual:dependency:function';
die 'spurious Readonly/Array.pm loaded' if exists $INC{'Readonly/Array.pm'};
push @done, 'qualified-callable-dependency';
Readonly::Hash my %hash => (payload => ['one','two']);
eval { $hash{payload}[0] = 'changed' }; $error = $@;
die 'deep hash mutation accepted' unless $error =~ /read-only/ && join(':',@{$hash{payload}}) eq 'one:two';
push @done, 'deep-hash';
open my $fh,'>','consumer-records.json' or die $!;
print $fh JSON::PP->new->canonical->encode({module=>$INC{'Readonly.pm'},version=>$Readonly::VERSION,passed=>\@done,qualified_callable=>JSON::PP::true,missing_module_error=>$missing,readonly_array_pm_loaded=>JSON::PP::false,builtin_backend=>JSON::PP::true});close $fh or die $!;
print "CONSUMER_TEST_COUNT=3\nCONSUMER_TEST_PASS=3/3\n";
