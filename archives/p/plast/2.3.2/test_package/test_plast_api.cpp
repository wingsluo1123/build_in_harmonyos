/*****************************************************************************
 * test_package/test_plast_api.cpp - PLAST 2.3.2 library API consumer test.
 *
 * Drives the PLAST algorithm through the *installed* public C++ API
 * (launcher::core::PlastOptionsParser + launcher::core::PlastCmd), which is
 * exactly the code path the shipped PlastCmd binary uses, then inspects the
 * tabulated result file.
 *
 * usage: test_plast_api <bank.fa> <query.fa> <output.txt>
 *****************************************************************************/

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <string>
#include <vector>

#include <designpattern/api/SmartPointer.hpp>
#include <designpattern/impl/Property.hpp>

#include <launcher/core/PlastCmd.hpp>
#include <launcher/core/PlastOptionsParser.hpp>

/* Generated by CMake (src/misc/api/version.hpp.in) and installed by the
 * recipe; including it also checks that the package ships the header. */
#include <misc/api/version.hpp>

/********************************************************************************/

static int failures = 0;

static void check (bool condition, const char* what)
{
    std::printf ("[%s] %s\n", condition ? " OK " : "FAIL", what);
    if (condition == false)  { failures++; }
}

/********************************************************************************/

/** Largest "%identity" value of a tabulated PLAST result file (0 when none). */
static double maxIdentity (const std::string& path, int& nbAlignments)
{
    std::ifstream in (path.c_str());
    double best = 0.0;
    nbAlignments = 0;

    std::string line;
    while (std::getline (in, line))
    {
        if (line.empty())  { continue; }

        /** Split on tabs the same way the tabulated output is written. */
        std::vector<std::string> fields;
        size_t start = 0;
        while (true)
        {
            size_t tab = line.find ('\t', start);
            fields.push_back (line.substr (start, tab == std::string::npos
                                                  ? std::string::npos : tab - start));
            if (tab == std::string::npos)  { break; }
            start = tab + 1;
        }
        if (fields.size() < 3)  { continue; }

        double identity = std::strtod (fields[2].c_str(), 0);
        if (identity > 0.0)
        {
            nbAlignments++;
            if (identity > best)  { best = identity; }
        }
    }
    return best;
}

/********************************************************************************/

int main (int argc, char** argv)
{
    if (argc < 4)
    {
        std::fprintf (stderr, "usage: %s <bank.fa> <query.fa> <output.txt>\n", argv[0]);
        return 2;
    }

    const char* bank   = argv[1];
    const char* query  = argv[2];
    const char* output = argv[3];

    /** The version macros live in the generated header. */
    std::printf ("[info] PLAST_VERSION=%s PLAST_BUILD_OS=%s\n", PLAST_VERSION, PLAST_BUILD_OS);
    check (std::strcmp (PLAST_VERSION, "2.3.2") == 0,
           "installed misc/api/version.hpp reports version 2.3.2");

    /** Build the command line the same way tools/PlastCmd.cpp does. */
    std::vector<std::string> options;
    options.push_back (argv[0]);
    options.push_back ("-p");      options.push_back ("plastp");
    options.push_back ("-i");      options.push_back (query);
    options.push_back ("-d");      options.push_back (bank);
    options.push_back ("-o");      options.push_back (output);
    options.push_back ("-e");      options.push_back ("1e-5");
    options.push_back ("-a");      options.push_back ("2");

    std::vector<char*> args;
    for (size_t i = 0; i < options.size(); i++)
    {
        args.push_back (const_cast<char*> (options[i].c_str()));
    }

    bool executed = true;
    {
        launcher::core::PlastOptionsParser parser;
        parser.parse (static_cast<int> (args.size()), args.data());

        dp::IProperties* props = new dp::impl::Properties ();
        LOCAL (props);
        props->add (0, parser.getProperties());

        launcher::core::PlastCmd cmd (props);
        try       {  cmd.execute ();  }
        catch (...)  {  executed = false;  }
    }
    check (executed, "PlastCmd::execute() ran through the library API without exception");

    int    nbAlignments = 0;
    double identity     = maxIdentity (output, nbAlignments);
    std::printf ("[info] library API: %d alignment(s), best identity %.2f%%\n",
                 nbAlignments, identity);

    check (nbAlignments >= 1, "library API reported at least one alignment");
    check (identity >= 90.0,  "library API alignment reaches at least 90% identity");

    std::printf ("%s\n", failures == 0 ? "PLAST API CONSUMER TEST PASSED"
                                       : "PLAST API CONSUMER TEST FAILED");
    return failures == 0 ? 0 : 1;
}
