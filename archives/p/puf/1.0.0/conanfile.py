#!/usr/bin/env python3
"""Conan recipe — puf 1.0.0 (Autotools, parallel URL fetch CLI tool).

puf is a "parallel url fetcher" for UN*X systems (a wget-like HTTP
downloader that fetches URLs in parallel). It builds a single `puf`
executable; there is no library API and no upstream test suite (see
test_package/MANIFEST.yml audit).

Build: standard Autotools (configure + make). Pre-generated `configure`
script ships in the source tarball, so no autoreconf is needed.
"""

import gc
import os
import shutil
import sys
import tempfile
import time

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout


# Scratch roots offered to config.status.  ${TMPDIR:-.} in the patched
# configure resolves to "." when TMPDIR is unset *or* set-but-empty; a
# repo-relative cache inside the build tree keeps the scratch on the same
# tested filesystem as the rest of the build and passes the fresh-dir probe.
_TMPDIR_CANDIDATES = (
    "/data/storage/el2/base/cache",
    "var/tmp",
    "/var/tmp",
    "/data/local/tmp",
    "/tmp",
)

# Substrings that identify a *transient* fork/exec resource failure (EAGAIN
# on fork, or the process table being momentarily exhausted) rather than a
# real compile/link error.  Only these are retried; any other error is
# propagated unchanged so genuine source/toolchain errors are never masked.
_FORK_PRESSURE_MARKERS = (
    "fork: retry",
    "fork: resource temporarily unavailable",
    "resource temporarily unavailable",
    "cannot fork",
    "can't fork",
    "fork failed",
    "posix_spawn",
    "out of memory",
)

# Wrapper installed as make's CCLD (see _link_retry_make_arg) so a single link
# command retries clang internally on a transient spawn failure.
#
# Why this is needed: the shared OHOS build host intermittently rejects fork()
# with EAGAIN under process-table pressure.  Bash *retries* fork() itself, so
# every compile survives (that is why the CI log is full of
# 'fork: retry: Resource temporarily unavailable' yet all translation units
# still compile).  clang, however, spawns the linker (ld.lld) with
# posix_spawn() and does **not** retry on EAGAIN, so one spike aborts the whole
# link: 'clang-15: error: unable to execute command: posix_spawn failed:
# Resource temporarily unavailable'.  A recipe-level make retry only gives
# clang one posix_spawn chance per attempt, which is far too coarse; this
# wrapper loops the *link command* so clang gets many rapid chances.
#
# Why the wrapper is Python and not a POSIX shell loop: a shell simply cannot
# implement this retry.  When a shell is asked to run an external command and
# the fork fails with EAGAIN, it does not return a non-zero status to the
# script -- it prints 'fork: retry: Resource temporarily unavailable' and then
# **aborts the whole script with exit 254**.  So the retry loop body never
# runs a second time: the retry mechanism is destroyed by the very failure it
# was written to absorb.  CI #94167 is exactly that: the old shell wrapper's
# log shows four 'fork: retry' lines and a bare 'fork: Resource temporarily
# unavailable' with **zero** 'link attempt N' lines, because the shell died on
# the first attempt.  Python has no such failure mode: a refused spawn raises a
# catchable ``OSError`` (errno EAGAIN), so the interpreter stays alive and
# keeps looping until the spike drains.  The wrapper is ``exec``-ed by make's
# shell so replacing the shell costs no extra fork.
#
# CI #94346 finally exposed the remaining asymmetry: the wrapper's *own*
# ``subprocess.run([clang, ...])`` never even forked.  On this host Python's
# ``subprocess`` takes the posix_spawn/vfork fast path (glibc >= 2.24 sets
# ``subprocess._USE_POSIX_SPAWN = True``), and that path returns EAGAIN under
# pressure -- all 60 attempts died with ``[Errno 11] ... '/data/service/hnp/bin/clang'``
# and clang produced no byte -- while bash's plain fork()+execv() for the
# *compilers* kept working (every translation unit compiled).  The wrapper now
# spawns the link with a raw ``os.fork()`` + ``os.execv()`` (the very primitive
# bash retries) instead of ``subprocess``, and additionally lifts the soft
# RLIMIT_NPROC/RLIMIT_NOFILE to their hard values.
#
# It retries ONLY on the transient spawn signature (errno EAGAIN/ENOMEM/... or
# the shell/clang EAGAIN text) and returns every other failure unchanged, so
# genuine link errors are never masked.
_LINK_RETRY_WRAPPER = r'''#!/usr/bin/env python3
"""hmbs-link-retry.py -- retry one link command on a transient process-creation EAGAIN.

Generated by the puf/1.0.0 Conan recipe.  Do not edit by hand.

The shared build host intermittently refuses process creation with EAGAIN while
its process table is exhausted.  On this host the refusal hits the
*vfork/posix_spawn* fast path -- used both by clang to spawn ld.lld and by
Python's ``subprocess`` -- while plain ``fork()`` keeps working because bash
retries it internally.  That asymmetry is why every translation unit compiles
yet the link fails: the link gets exactly one un-retried spawn chance.

This wrapper therefore launches the link with a raw ``os.fork()`` +
``os.execv()`` pair inside a retry loop -- the same primitive bash uses and
retries -- instead of ``subprocess`` (which may take the fragile vfork path),
and it re-runs the whole command when clang itself reports a transient
``posix_spawn failed`` for ld.lld.  It also lifts the soft RLIMIT_NPROC/
RLIMIT_NOFILE up to their hard values, since fork() returns EAGAIN when the
per-user process limit would be exceeded.  Only transient resource signatures
are retried; any other (real) link error is returned unchanged.
"""

import errno
import os
import sys
import time

# errno values that mean "the process creation itself was refused for a
# transient resource reason" rather than "the compiler ran and reported a real
# error".
_TRANSIENT_ERRNOS = frozenset(
    (errno.EAGAIN, errno.ENOMEM, errno.EMFILE, errno.ENFILE, errno.ENOSPC)
)

# Textual signatures of the same transient condition, as emitted by the shell
# (bash's 'fork: retry') or by clang ('posix_spawn failed: ...').
_TRANSIENT_TEXT = (
    "posix_spawn failed",
    "resource temporarily unavailable",
    "fork: retry",
    "can't fork",
    "cannot fork",
    "fork failed",
    "out of memory",
)


def _raise_process_limits():
    """Best-effort: lift soft process/fd limits up to their hard values.

    ``fork()`` returns EAGAIN when RLIMIT_NPROC would be exceeded.  A worker can
    be configured with a soft NPROC limit well below its hard limit; children
    inherit whatever we set here, so raising the soft limit gives the retry loop
    a real chance instead of failing every attempt.  Never fatal: an
    unprivileged process may only raise up to the hard limit.
    """
    try:
        import resource
    except ImportError:
        return
    for limit_name in ("RLIMIT_NPROC", "RLIMIT_NOFILE"):
        limit = getattr(resource, limit_name, None)
        if limit is None:
            continue
        try:
            soft, hard = resource.getrlimit(limit)
            if hard == resource.RLIM_INFINITY:
                continue
            if soft == resource.RLIM_INFINITY or soft < hard:
                resource.setrlimit(limit, (hard, hard))
        except (ValueError, OSError):
            continue


def _emit(data):
    if data:
        sys.stdout.buffer.write(data)
        sys.stdout.buffer.flush()


def _spawn(compiler, args, log_path):
    """fork()+execv() the command once; return (exit_code, output_bytes).

    ``log_path`` receives the child's combined stdout/stderr via dup2 so the
    parent can scan it for a transient signature after the child exits.  An
    EAGAIN from ``os.fork`` propagates as ``OSError`` for the caller to retry;
    the child never returns (execv replaces it, or _exit(127) on failure).
    """
    fd = os.open(log_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        # Flush our own buffers before forking so nothing is duplicated into
        # the child (the child immediately redirects stdio and execs, which
        # would otherwise silently drop or duplicate buffered bytes).
        sys.stdout.flush()
        sys.stderr.flush()
        pid = os.fork()
        if pid == 0:
            # Child: wire stdio to the log and become the compiler.
            try:
                devnull = os.open(os.devnull, os.O_RDONLY)
                os.dup2(devnull, 0)
                os.dup2(fd, 1)
                os.dup2(fd, 2)
                if fd > 2:
                    os.close(fd)
                argv = [compiler] + list(args)
                if os.path.isabs(compiler):
                    os.execv(compiler, argv)
                else:
                    os.execvp(compiler, argv)
            except BaseException:
                os._exit(127)
        os.close(fd)
        fd = -1
        _, status = os.waitpid(pid, 0)
    finally:
        if fd >= 0:
            os.close(fd)
    if os.WIFEXITED(status):
        code = os.WEXITSTATUS(status)
    elif os.WIFSIGNALED(status):
        code = 128 + os.WTERMSIG(status)
    else:
        code = 1
    try:
        with open(log_path, "rb") as handle:
            output = handle.read()
    except OSError:
        output = b""
    return code, output


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("hmbs-link-retry: no compiler argument\n")
        return 127
    compiler, args = argv[1], argv[2:]
    attempts = int(os.environ.get("HMBS_LINK_RETRY_ATTEMPTS", "200"))
    base_delay = float(os.environ.get("HMBS_LINK_RETRY_DELAY", "0.2"))
    max_delay = float(os.environ.get("HMBS_LINK_RETRY_MAX_DELAY", "2"))
    _raise_process_limits()
    log_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "hmbs-link-retry.log")
    last_rc = 1
    for attempt in range(1, attempts + 1):
        delay = min(base_delay * attempt, max_delay)
        try:
            code, output = _spawn(compiler, args, log_path)
        except OSError as exc:
            # The fork() itself was refused.  This is exactly the condition
            # this wrapper exists for: keep polling until a free slot appears
            # (bash retries its own fork() on EAGAIN the same way).
            if exc.errno in _TRANSIENT_ERRNOS and attempt < attempts:
                sys.stderr.write(
                    "hmbs-link-retry: fork attempt %d/%d hit EAGAIN (%s); "
                    "retrying in %gs\n" % (attempt, attempts, exc, delay))
                time.sleep(delay)
                continue
            sys.stderr.write(
                "hmbs-link-retry: fork failed after %d attempts (%s)\n"
                % (attempt, exc))
            return 254
        if code == 0:
            _emit(output)
            return 0
        last_rc = code
        text = output.decode("utf-8", "replace").lower()
        if (any(marker in text for marker in _TRANSIENT_TEXT)
                and attempt < attempts):
            sys.stderr.write(
                "hmbs-link-retry: link attempt %d/%d hit a transient spawn "
                "failure; retrying in %gs\n" % (attempt, attempts, delay))
            time.sleep(delay)
            continue
        _emit(output)
        return code
    return last_rc


if __name__ == "__main__":
    sys.exit(main(sys.argv))
'''


class PufConan(ConanFile):
    name = "puf"
    version = "1.0.0"
    description = "Parallel URL fetch utility (wget-like HTTP downloader)"
    license = "GPL-2.0-only"
    homepage = "https://sourceforge.net/projects/puf/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("Unsupported OS: %s"
                                            % self.settings.os)

    def layout(self):
        basic_layout(self)

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Install directly under $package_folder/bin (no /usr/local).
        tc.configure_args.append("--prefix=/")
        # The shared build host intermittently rejects fork() (EAGAIN) while the
        # shell launches the compiler.  Dependency tracking would wrap every
        # compile in an `if $(COMPILE) -MT ... -MD -MP -MF ...; then mv ...;
        # else ...; fi` shell block (depcomp + mv subprocesses) and adds no
        # value for a one-shot package build, so disable it to cut the fork
        # count per translation unit.
        tc.configure_args.append("--disable-dependency-tracking")
        # OHOS: the shipped 2005-era config.guess cannot guess the system
        # from HarmonyOS `uname` output ("unable to guess system type"),
        # so configure requires an explicit --build/--host. The linux-ohos
        # triplet is accepted by config.sub only thanks to
        # patches/0001-config.sub-ohos.patch (same approach as aalib).
        if str(self.settings.os) == "OHOS":
            if self.settings.arch != "armv8":
                raise ConanInvalidConfiguration(
                    "puf/1.0.0 currently supports only OHOS armv8/aarch64"
                )
            tc.configure_args.extend([
                "--build=aarch64-linux-ohos",
                "--host=aarch64-linux-ohos",
            ])
        # OHOS shell: do NOT force SHELL/CONFIG_SHELL=/bin/sh here.  The
        # ohos-aarch64 profile already exposes a working POSIX shell at
        # /data/service/hnp/bin/bash via its [buildenv], and AutotoolsToolchain
        # (without an env override) keeps those values for configure/make.
        # Pinning /bin/sh (the HMBS shim) as the build shell was observed to
        # make the 2005-era configure fragile on the real-machine worker: it
        # failed to exec the toolchain `sed` ("Operation not permitted") and to
        # fork sub-shells ("can't fork - try again") during the early argument /
        # trap sections.  The same --build/--host autotools pattern (aalib)
        # builds fine with no SHELL override, so we follow that proven recipe.
        tc.generate()

    @staticmethod
    def _usable_tmpdir(candidate):
        """True if autoconf/config.status can really use *candidate* as a scratch root.

        Replays what config.status does: create a fresh directory and
        immediately redirect into it.  On HMFS/HMDFS (the /storage user volume)
        a just-created directory can come back without usable owner permissions,
        and chmod itself is unsupported (HMBS_CAP_CHMOD=0), so every later
        ``> "$tmp"/<file>`` becomes "Permission denied".  A plain "is it
        writable?" check does not catch that because the *parent* is fine -- only
        a write into a directory we created a moment ago does.
        """
        try:
            os.makedirs(candidate, exist_ok=True)
            previous_umask = os.umask(0o077)
            try:
                probe_dir = tempfile.mkdtemp(dir=candidate)
            finally:
                os.umask(previous_umask)
        except OSError:
            return False
        try:
            probe_file = os.path.join(probe_dir, "probe")
            with open(probe_file, "w") as handle:
                handle.write("ok")
            with open(probe_file) as handle:
                return handle.read() == "ok"
        except OSError:
            return False
        finally:
            shutil.rmtree(probe_dir, ignore_errors=True)

    def _resolve_tmpdir(self):
        """Locate, create and probe the scratch root config.status will use.

        config.status (patches/0002) resolves its scratch via
        ``${TMPDIR:-.}``.  That colon-default fires for a TMPDIR that is unset
        *or* set-but-empty, and it can only point somewhere productive if
        TMPDIR is an absolute, existing, writable directory.  Walk the
        candidate roots, materialise each one and keep the first that passes
        the fresh-dir probe; a repo-relative candidate (``var/tmp``) keeps the
        scratch inside the build tree, i.e. on exactly the filesystem whose
        behaviour the rest of the build already exercises.  Returns the chosen
        path, or None when nothing is usable (caller then leaves the
        environment alone so the ``.`` default still applies).
        """
        candidates = list(_TMPDIR_CANDIDATES)
        for name in ("HMBS_TMPDIR", "TMPDIR", "TMP", "TEMP"):
            value = os.environ.get(name)
            if value:
                candidates.append(value)
        candidates.append(os.path.join(self.build_folder, "hmbs-tmp"))
        seen = set()
        for candidate in candidates:
            if not candidate or candidate in seen:
                continue
            seen.add(candidate)
            resolved = (candidate if os.path.isabs(candidate)
                        else os.path.join(self.build_folder, candidate))
            if self._usable_tmpdir(resolved):
                return os.path.abspath(resolved)
        return None

    def _pin_tmpdir(self):
        """Export TMPDIR for config.status, preferring the build-folder root.

        Only the recipe's own candidate wins: the device/host TMPDIR that
        HMBS injects is still probed and can be used, but the final fallback is
        the repo-relative ``var/tmp`` inside the build folder, so the scratch
        never falls back to the config.status ``.`` default unverified.
        """
        resolved = self._resolve_tmpdir()
        if not resolved:
            self.output.warning(
                "no candidate TMPDIR passed the write-into-fresh-dir probe; "
                "leaving TMPDIR={0} (config.status then uses '.')".format(
                    os.environ.get("TMPDIR")))
            return
        for name in ("TMPDIR", "TMP", "TEMP"):
            os.environ[name] = resolved
        self.output.info("Using usable TMPDIR={0}".format(resolved))

    def _log_has_fork_pressure(self, path):
        """True if *path* (a build log) contains a transient fork/exec failure.

        Used to distinguish an EAGAIN fork-pressure spike on the shared build
        host (the process table momentarily exhausted, reported by the shell as
        'fork: Resource temporarily unavailable') from a genuine compile/link
        error.  Only the former is safe to retry; a real error is re-raised
        unchanged so it is never masked by retries.
        """
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                tail = handle.read()[-20000:].lower()
        except OSError:
            return False
        return any(marker in tail for marker in _FORK_PRESSURE_MARKERS)

    def _make_program(self):
        """Resolve the make executable, preferring the injected absolute path."""
        configured = self.conf.get("tools.gnu:make_program",
                                   default=None, check_type=str)
        if configured:
            return configured
        return os.environ.get("HMBS_MAKE") or shutil.which("make") or "make"

    def _python_program(self):
        """Resolve the Python interpreter used to run the link-retry wrapper.

        HMBS injects an absolute interpreter path in ``HMBS_PYTHON3``; fall
        back to the interpreter running this recipe (``sys.executable``) and
        finally to a PATH lookup.  The wrapper is Python because a shell
        aborts the whole script on a failed fork (see ``_LINK_RETRY_WRAPPER``),
        so the interpreter must be a real executable we can ``exec``.
        """
        for candidate in (os.environ.get("HMBS_PYTHON3"), sys.executable):
            if candidate and os.path.isabs(candidate) and os.path.exists(candidate):
                return candidate
        return shutil.which("python3") or "python3"

    def _write_link_retry_wrapper(self):
        """Materialise the link-retry wrapper; return its absolute path.

        The wrapper is invoked by make as
        ``$(SHELL) exec <python> <wrapper> $(CC)`` (see
        ``_link_retry_make_arg``), so it only needs to be readable, not
        executable -- important on HMFS where the exec bit of a freshly written
        file can be unreliable.  Returns None when no writable location is
        available, in which case the caller falls back to a plain link.
        """
        wrapper = os.path.join(self.build_folder, "hmbs-link-retry.py")
        try:
            with open(wrapper, "w", encoding="utf-8") as handle:
                handle.write(_LINK_RETRY_WRAPPER)
        except OSError as error:
            self.output.warning(
                "could not write link-retry wrapper (%s); linking without "
                "per-link retry" % error)
            return None
        return wrapper

    def _link_retry_make_arg(self):
        """Build the make command-line override that routes links via the wrapper.

        Returns a single shell-quoted ``CCLD=...`` argument (or None).  The
        value keeps ``$(CC)`` unexpanded -- the outer shell is prevented from
        touching it by single quotes -- so make resolves it to the OHOS clang.
        The interpreter is a concrete absolute path (resolved by
        ``_python_program``), and ``exec`` replaces make's shell with it so the
        wrapper costs no extra fork.  This override is propagated to the
        recursive ``make`` in ``src/`` through MAKEFLAGS, replacing the
        generated ``CCLD = $(CC)``.
        """
        wrapper = self._write_link_retry_wrapper()
        if not wrapper:
            return None
        interpreter = self._python_program()
        if not interpreter or any(ch in interpreter for ch in (" ", "\t", "'")):
            self.output.warning(
                "python interpreter %r is not usable for the link-retry "
                "wrapper; skipping per-link retry" % interpreter)
            return None
        if any(ch in wrapper for ch in (" ", "\t", "'")):
            self.output.warning(
                "build path %r is not space/quote-free; skipping per-link "
                "retry wrapper" % wrapper)
            return None
        # Single-quoted so the invoking shell passes the literal make syntax
        # through; make then expands $(CC) itself.  `exec` avoids a lingering
        # shell around the interpreter on a fork-starved host.
        return "'CCLD=exec %s %s $(CC)'" % (interpreter, wrapper)

    def _run_make_with_fork_retry(self, target=None, extra_args=None,
                                  attempts=6):
        """Run `make` serially, retrying only on transient fork pressure.

        puf compiles a handful of small C files, yet the shared OHOS build host
        intermittently rejects fork() (EAGAIN) while the shell launches the
        compiler/linker, e.g. '/data/service/hnp/bin/bash: fork: retry:
        Resource temporarily unavailable' or 'clang-15: error: unable to
        execute command: posix_spawn failed: Resource temporarily
        unavailable'.  That is a resource spike on the host, not a defect in
        puf's sources: `make` is incremental, so re-running it after a backoff
        resumes exactly where it stopped.  A failure without the fork-pressure
        signature is propagated immediately so real errors are never masked.

        CI build #93827 showed the spike can outlast a short 3-attempt / ~15s
        window: every translation unit compiled, then the *link* spawn failed
        three times in a row.  A wider retry window alone (CI #93925, 6
        attempts / ~3.5min) still failed every time, because the asymmetry is
        structural: bash retries its own fork() on EAGAIN (so compiles survive
        the 'fork: retry' spam) but clang does **not** retry the posix_spawn()
        of ld.lld, and one make invocation gives that spawn exactly one chance.
        The real fix is therefore to make the link spawn itself retryable:
        make's ``CCLD`` is overridden to
        ``exec <python> <wrapper> $(CC)`` so the wrapper loops the link command
        rapidly on the spawn signature (see ``_LINK_RETRY_WRAPPER``).  The
        coarse make-level backoff is kept as a second line of defence for spawn
        failures that happen outside a link.

        CI #94128 first showed that a *shell* link-retry wrapper is useless
        under the very pressure it was built for: from attempt 2 on, `make`
        finds all objects up to date and goes straight to the link, and on that
        host even a single ``clang > log 2>&1`` invocation could not be forked
        at all -- every run failed with `fork: retry` / `fork: Resource
        temporarily unavailable` before clang produced a single byte, and the
        wrapper's own attempt counter never advanced (no
        `hmbs-link-retry: link attempt N` lines).  A shell-heredoc rewrite
        (CI #94167) still failed identically: the shell prints four
        `fork: retry` lines and a bare `fork: Resource temporarily
        unavailable`, then **aborts the whole script with exit 254** -- a shell
        cannot fork the command and therefore never reaches the second
        iteration of its own retry loop.  The wrapper was rewritten as Python
        (run via ``exec <python>``) because a refused spawn raises a catchable
        ``OSError`` instead of killing the interpreter.

        CI #94346 (build #94346, worker OpenHarmonyPCDeveloper-CI-001) finally
        isolated the remaining asymmetry.  In that log every one of the ten
        translation units compiled and only the link command failed, and the
        wrapper *did* run its loop (60 `spawn attempt N/60` lines) yet every
        ``subprocess.run([clang]+args)`` raised ``[Errno 11] ... clang`` without
        clang producing a byte.  Bash, which launches the shells for those same
        compiles, kept succeeding (its own ``fork: retry`` lines are its
        internal EAGAIN retry).  The difference is the syscall: OHOS CPython
        forces ``subprocess`` onto the posix_spawn (vfork/clone) fast path,
        which returns EAGAIN under this worker's pressure, whereas plain
        ``fork()`` keeps succeeding.  The wrapper therefore builds the child
        with a raw ``os.fork()`` + ``os.execv()`` pair -- the same primitive
        bash retries -- instead of ``subprocess``, and lifts the soft
        RLIMIT_NPROC/RLIMIT_NOFILE to their hard values first.
        """
        from conan.tools.build import load_toolchain_args
        toolchain_args = load_toolchain_args(self.generators_folder)
        make_args = toolchain_args.get("make_args") or ""
        make_program = self._make_program()
        link_retry = self._link_retry_make_arg()
        command = " ".join(
            part for part in (make_program, make_args, link_retry, target,
                              " ".join(extra_args or ()), "-j1") if part)
        if link_retry:
            self.output.info(
                "per-link fork-retry wrapper enabled (CCLD override)")
        log_path = os.path.join(self.build_folder, "hmbs-make.log")
        last_error = None
        for attempt in range(1, attempts + 1):
            self.output.info(
                "puf make attempt %d/%d: %s" % (attempt, attempts, command))
            try:
                with open(log_path, "w", encoding="utf-8",
                          errors="replace") as log_file:
                    self.run(command, cwd=self.build_folder, env="conanbuild",
                             stdout=log_file, stderr=log_file)
                self._echo_build_log(log_path)
                return
            except ConanException as error:
                last_error = error
                fork_pressure = self._log_has_fork_pressure(log_path)
                self.output.warning(
                    "make attempt %d/%d failed (fork_pressure=%s): %s"
                    % (attempt, attempts, fork_pressure, error))
                self._echo_build_log(log_path)
                if not fork_pressure or attempt >= attempts:
                    break
                # Back off with exponential growth (capped) so the host
                # process table can drain; free the Python heap first so the
                # next spawn has more headroom.
                gc.collect()
                delay = min(5 * (2 ** (attempt - 1)), 60)
                self.output.info(
                    "fork pressure detected; reclaim + retry in %ds" % delay)
                time.sleep(delay)
        raise last_error

    def _echo_build_log(self, path, prefix="make"):
        """Replay a redirected build log to Conan's output stream.

        `configure`/`make` run with stdout/stderr redirected to *path* so the
        fork-pressure signature can be inspected after a failure.  Echoing the
        log keeps the real error lines visible in the CI transcript (watchdog
        liveness and evidence) without an extra pipe/tee process.
        """
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                text = handle.read()
        except OSError:
            return
        for line in text.splitlines():
            self.output.info("  [%s] %s" % (prefix, line))

    def _configure_command(self):
        """Reconstruct the exact command ``Autotools.configure()`` would run.

        ``Autotools.configure()`` executes ``"<source>/configure" <args>`` with
        cwd=build_folder and does not accept stdout/stderr redirection, so the
        recipe rebuilds the same command from the generated toolchain args in
        order to capture the output.  On OHOS/Linux the subsystem is POSIX, so
        ``subsystem_path`` is the identity and the source folder path is used
        verbatim.
        """
        from conan.tools.build import load_toolchain_args
        toolchain_args = load_toolchain_args(self.generators_folder)
        configure_args = toolchain_args.get("configure_args") or ""
        configure_cmd = os.path.join(self.source_folder, "configure")
        return '"{0}" {1}'.format(configure_cmd, configure_args).strip()

    def _run_configure(self, max_attempts=4, spawn_fail_fatal=True):
        """Run configure capturing *all* output to a replayable log.

        The recipe level is the only place that can see configure's failure
        detail: Conan logs its own ``RUN: "<source>/configure" <args>`` line but
        discards the child's stdout/stderr, so a failing configure reaches the
        CI transcript as a bare ``ConanException: Error 1 while executing`` --
        zero diagnostic evidence, and hint rules keyed on the configure output
        (``configure: error: ...``) never fire.

        The command mirrors ``autotools.configure()`` (same source-folder
        script, same generated ``configure_args``) but adds output capture.
        The child log is the *only* input the retry decision below reads: a
        retry happens only after the log has shown a transient namespace/process
        failure (``can't fork`` / ``Resource temporarily unavailable`` / ...),
        so a deterministic configure failure is replayed once and left alone.

        ``spawn_fail_fatal`` controls the critical fork-EAGAIN policy.  On the
        CI worker the *spawn itself* of the configure script (``SHELL=``
        conftest, compile probes, sub-shells) is what fails under process-table
        pressure -- not configure's logic.  Distinguishing the two is cheap and
        safe here: configure writes a fresh ``config.log`` per run, and the
        script's own diagnostics go to the (captured) ``hmbs-configure.log``.
        So when the run fails we inspect *both* logs for the transient
        signature *before* deciding to retry: if either shows the signature,
        the failure is classified as environmental, the log is preserved and a
        retry is allowed.  ``spawn_fail_fatal=False`` widens that classification
        (and is used only while the compile probe itself fails to spawn);
        ``spawn_fail_fatal=True`` keeps the strict, evidence-only behaviour.
        """
        command = self._configure_command()
        log_path = os.path.join(self.build_folder, "hmbs-configure.log")
        last_error = None
        for attempt in range(1, max_attempts + 1):
            self.output.info(
                "configure attempt %d/%d (log: %s)"
                % (attempt, max_attempts, log_path))
            try:
                # ConanFile.run forwards stdout/stderr verbatim to
                # subprocess.run, so they must be file-like objects (or
                # DEVNULL) -- never a path string, which raises
                # "'str' object has no attribute 'fileno'".
                with open(log_path, "w", encoding="utf-8",
                          errors="replace") as log_file:
                    self.run(command, cwd=self.build_folder,
                             env="conanbuild",
                             stdout=log_file, stderr=log_file)
                self._echo_build_log(log_path, prefix="configure")
                return
            except ConanException as error:
                last_error = error
                pressure = (self._log_has_fork_pressure(log_path)
                            or self._config_log_has_fork_pressure())
                if spawn_fail_fatal:
                    pressure = pressure and self._log_has_fork_pressure(
                        log_path)
                self.output.warning(
                    "configure attempt %d/%d failed (fork_pressure=%s)"
                    % (attempt, max_attempts, pressure))
                self._echo_build_log(log_path, prefix="configure")
                if not pressure or attempt >= max_attempts:
                    break
                # Same backoff as make: let a transient fork/exec spike drain
                # (reclaim the Python heap first, then wait with exponential
                # growth so the constrained process table has time to recover).
                gc.collect()
                delay = min(5 * (2 ** (attempt - 1)), 60)
                self.output.info(
                    "configure fork pressure detected; reclaim + retry in %ds"
                    % delay)
                time.sleep(delay)
        raise last_error

    def _config_log_has_fork_pressure(self):
        """True if the configure run's ``config.log`` shows a transient spawn failure.

        ``config.log`` is written fresh by each configure run and records the
        compiler-probe transcript.  When the compiler driver or the linker it
        spawns is killed by fork EAGAIN, the transcript ends with lines such as
        ``cannot create executables`` (the macro result, which is the *only*
        line echoed to stdout) while the detail -- ``fork: retry`` /
        ``Resource temporarily unavailable`` / ``can't fork - try again`` /
        ``posix_spawn failed`` / ``out of memory`` -- lands in ``config.log``.
        Using this source keeps the retry decision grounded in the actual
        diagnostic rather than in the summary line alone.
        """
        config_log = os.path.join(self.build_folder, "config.log")
        try:
            with open(config_log, "r", encoding="utf-8",
                      errors="replace") as handle:
                tail = handle.read()[-20000:].lower()
        except OSError:
            return False
        return any(marker in tail for marker in _FORK_PRESSURE_MARKERS)

    def build(self):
        apply_conandata_patches(self)
        # puf's generated config.status creates its scratch temp directory under
        # $TMPDIR (see patches/0002-configure-confstat-tmpdir.patch). On HMFS the
        # permission metadata of a just-created directory is not immediately
        # effective, which made the historical `/build-tree/confstatXXXXXX`
        # scratch dir unusable (EACCES on every redirect -> no Makefile). The
        # config.sub/config.guess/autotools ecosystem shares this quirk; pin
        # TMPDIR to a probe-verified writable root before configure runs so
        # config.status lands its scratch there.
        if str(self.settings.os) == "OHOS":
            self._pin_tmpdir()
        self._run_configure()
        # -j1 caps peak link memory on the device (Signal 9/OOM hardening) and
        # keeps configure/make deterministic on HMDFS.  Run make through the
        # fork-pressure retry wrapper: the shared host occasionally rejects
        # fork() (EAGAIN) while launching the compiler, which aborts the build
        # with a spurious 'Error 254' rather than a real compile error.
        self._run_make_with_fork_retry()

    def package(self):
        from conan.tools.microsoft import unix_path
        dest = unix_path(self, self.package_folder)
        # `make install` also forks a shell per install step; reuse the same
        # fork-pressure retry wrapper (idempotent: already-installed files are
        # simply re-copied).
        self._run_make_with_fork_retry(target="install",
                                       extra_args=["DESTDIR=%s" % dest])
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        bin_dir = os.path.join(self.package_folder, "bin")
        if os.path.isdir(bin_dir):
            for fn in sorted(os.listdir(bin_dir)):
                fp = os.path.join(bin_dir, fn)
                self.output.info("pkg bin entry: %s link=%s exec=%s" % (
                    fn, os.path.islink(fp), os.access(fp, os.X_OK)))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = []
        self.cpp_info.libs = []
        bin_dir = os.path.join(self.package_folder, "bin")
        if os.path.isdir(bin_dir):
            self.buildenv_info.prepend_path("PATH", bin_dir)
            self.runenv_info.prepend_path("PATH", bin_dir)
