#!/usr/bin/env python3
"""Conan recipe for Qt WebChannel 6.11.1 (CMake)."""
import glob
import json
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.build import can_run
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.env import VirtualRunEnv
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)


class QtWebChannelConan(ConanFile):
    name = "qtwebchannel"
    version = "6.11.1.1"
    description = "Qt WebChannel enables peer-to-peer communication between "
    "a C++/QML application and an HTML/JavaScript client"
    license = "GPL-3.0-only OR LGPL-3.0-only OR LicenseRef-Qt-Commercial"
    homepage = "https://doc.qt.io/qt-6/qtwebchannel-index.html"
    package_type = "shared-library"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires(
            "qtbase/6.11.1.3", override=True,
            transitive_headers=True,
            transitive_libs=True,
        )
        self.requires(
            "qtdeclarative/6.11.1.2",
            transitive_headers=True,
            transitive_libs=True,
        )

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "qtwebchannel supports Linux and OHOS"
            )

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        qtbase = self.dependencies["qtbase"].package_folder
        tc.variables["Qt6_DIR"] = os.path.join(qtbase, "lib", "cmake", "Qt6")
        tc.variables["CMAKE_FIND_ROOT_PATH_MODE_PACKAGE"] = "BOTH"
        if self.settings.os == "OHOS":
            tc.variables["QT_QMAKE_TARGET_MKSPEC"] = "harmonyos-clang"
        tc.variables["QT_BUILD_TESTS"] = True
        tc.variables["QT_BUILD_TESTS_BY_DEFAULT"] = True
        tc.variables["QT_BUILD_EXAMPLES"] = False
        tc.variables["QT_BUILD_EXAMPLES_BY_DEFAULT"] = False
        tc.variables["QT_BUILD_BENCHMARKS"] = False
        tc.variables["QT_BUILD_MANUAL_TESTS"] = False
        tc.generate()
        VirtualRunEnv(self).generate()

    # OHOS 的 SDK `lld` 自身需要 SDK 里的 `libxml2.so.16`（无 RPATH，靠加载器路径搜索）。
    # 上游 `module_includes` 这个 CTest 会做一次嵌套 CMake 配置+链接；在 Conan 运行环境里
    # qtsvg/qtdeclarative 传递进来的 libxml2 会排在 SDK 之前，导致
    # `Error loading shared library libxml2.so.16 (needed by .../llvm/bin/lld)` +
    # `xmlNewNs: symbol not found`，链接直接失败。这里生成一个只做"把 SDK llvm/lib 提到
    # LD_LIBRARY_PATH 首位"的 env 文件，并与 conanrun 一起作用于 ctest（子进程全部继承），
    # 不改动编译器/工具链本身（与已发布的 akonadi/25.12.3 同类修法）。
    _OHOS_SDK_LLVM_LIB_GLOBS = (
        "/data/service/hnp/ohos-sdk.org/*/ohos/native/llvm/lib",
        "/data/service/hnp/ohos-sdk_*/native/llvm/lib",
        "~/.harmonybrew/Cellar/ohos-sdk/*/native/llvm/lib",
        "~/ohos-sdk/*/native/llvm/lib",
    )

    def _ohos_sdk_llvm_libdir(self):
        if str(self.settings.os) != "OHOS":
            return None
        candidates = []
        # 1) 从 conf 里实际使用的编译器反推 SDK（最可靠，且不依赖固定安装布局）
        try:
            raw = self.conf.get("tools.build:compiler_executables", default=None)
            data = raw if isinstance(raw, dict) else json.loads(raw or "{}")
            for value in data.values():
                if value:
                    candidates.append(
                        os.path.join(os.path.dirname(os.path.dirname(value)), "lib")
                    )
        except (ValueError, TypeError, KeyError):
            pass
        # 2) 显式 SDK 根
        sdk_root = os.environ.get("OHOS_SDK_ROOT")
        if sdk_root:
            candidates.append(os.path.join(sdk_root, "native", "llvm", "lib"))
        # 3) 已知安装布局的 glob（CI worker / harmonybrew / 手工解包）
        for pattern in self._OHOS_SDK_LLVM_LIB_GLOBS:
            candidates.extend(sorted(glob.glob(os.path.expanduser(pattern)), reverse=True))
        for candidate in candidates:
            if os.path.isfile(os.path.join(candidate, "libxml2.so.16")):
                return candidate
        return None

    def _ohos_llvm_libxml2_env_file(self):
        libdir = self._ohos_sdk_llvm_libdir()
        if not libdir:
            return None
        path = os.path.join(
            self.generators_folder, "ohos-llvm-libxml2-env.sh"
        )
        script = (
            "#!/bin/sh\n"
            "# Generated by the qtwebchannel recipe: keep the OHOS SDK's own\n"
            "# libxml2.so.16 ahead of any Conan-provided copy so the SDK lld\n"
            "# can relocate its symbols during nested CMake link checks.\n"
            'if [ -n "$LD_LIBRARY_PATH" ]; then\n'
            f'    export LD_LIBRARY_PATH="{libdir}:$LD_LIBRARY_PATH"\n'
            "else\n"
            f'    export LD_LIBRARY_PATH="{libdir}"\n'
            "fi\n"
        )
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(script)
        return path

    def _ctest_executable(self):
        for candidate in (
            shutil.which("ctest"),
            "/data/service/hnp/bin/ctest",
            "/data/service/hnp/cmake.org/cmake_4.1.2/bin/ctest",
        ):
            if (
                candidate
                and os.path.isfile(candidate)
                and os.access(candidate, os.X_OK)
            ):
                return candidate
        raise ConanInvalidConfiguration("ctest executable was not found")

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()
        if can_run(self):
            self.output.info(
                "Running configured upstream Qt WebChannel auto tests with "
                "the Conan runtime environment"
            )
            ctest = self._ctest_executable()
            test_env = ["conanrun"]
            llvm_env = self._ohos_llvm_libxml2_env_file()
            if llvm_env:
                test_env.append(llvm_env)
            self.run(
                f'"{ctest}" --test-dir "{self.build_folder}" '
                "--output-on-failure -j1",
                env=test_env,
            )
        else:
            self.output.info(
                "Cross-building: upstream Qt WebChannel tests require "
                "a runnable target"
            )

    def _ohos_sdk_tool(self, name):
        """Locate an OHOS SDK tool next to the configured compiler, else on PATH."""
        candidates = []
        try:
            raw = self.conf.get("tools.build:compiler_executables", default=None)
            data = raw if isinstance(raw, dict) else json.loads(raw or "{}")
            for value in data.values():
                if not value:
                    continue
                sdk_bin = os.path.dirname(value)
                candidates.append(os.path.join(sdk_bin, name))
                candidates.append(
                    os.path.join(os.path.dirname(sdk_bin), "native", "llvm", "bin", name)
                )
        except (ValueError, TypeError, KeyError):
            pass
        which = shutil.which(name)
        if which:
            candidates.append(which)
        for candidate in candidates:
            if candidate and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
                return candidate
        return ""

    @staticmethod
    def _is_elf(path):
        try:
            with open(path, "rb") as handle:
                return handle.read(4) == b"\x7fELF"
        except OSError:
            return False

    def _sign_ohos_elfs(self):
        """OHOS 加载器拒绝执行/加载未签名 ELF（报 `Error loading shared library`），
        因此包内所有 ELF 必须重新签名后才能被消费者与 test_package 使用。"""
        if str(self.settings.os) != "OHOS":
            return
        objcopy = self._ohos_sdk_tool("llvm-objcopy")
        signer = self._ohos_sdk_tool("binary-sign-tool")
        if not objcopy or not signer:
            self.output.warning(
                "OHOS ELF signing tools not found (llvm-objcopy/binary-sign-tool); "
                "package ELFs will stay unsigned"
            )
            return
        signed = 0
        for root, _dirs, files in os.walk(self.package_folder):
            for name in files:
                path = os.path.join(root, name)
                if os.path.islink(path) or not self._is_elf(path):
                    continue
                self.run(
                    f'"{objcopy}" --remove-section .codesign "{path}"',
                    ignore_errors=True,
                )
                self.run(
                    f'"{signer}" sign -inFile "{path}" -outFile "{path}" -selfSign 1',
                    ignore_errors=True,
                )
                try:
                    os.chmod(path, 0o755)
                except OSError:
                    pass
                signed += 1
        self.output.info(f"Signed {signed} OHOS ELF file(s) in the package")

    def package(self):
        CMake(self).install()
        # 交付物补齐版本化名字：Qt 单模块安装只落地 libQt6WebChannel.so（HMDFS 下
        # 版本化符号链接未随打包保留），而消费者/测试的 DT_NEEDED 是
        # libQt6WebChannel.so.6 ⇒ 包内补同名链接（不可链接时退化为实体副本），
        # 使 qtwebengine 等真实消费者也能加载。
        _libdir = os.path.join(self.package_folder, "lib")
        _plain = os.path.join(_libdir, "libQt6WebChannel.so")
        _soname = os.path.join(_libdir, "libQt6WebChannel.so.6")
        if os.path.exists(_plain) and not os.path.lexists(_soname):
            try:
                os.symlink("libQt6WebChannel.so", _soname)
            except OSError:
                shutil.copy2(_plain, _soname)
        copy(
            self,
            "*",
            src=os.path.join(self.source_folder, "LICENSES"),
            dst=os.path.join(self.package_folder, "licenses"),
        )
        self._sign_ohos_elfs()

    def package_info(self):
        self.cpp_info.libs = ["Qt6WebChannel"]
        # Qt installs complete Qt6WebChannelConfig.cmake files. Reuse them so
        # consumers keep the upstream Qt6::WebChannel target and avoid a
        # generated CMakeDeps config that would search for qtbaseConfig.cmake.
        self.cpp_info.set_property("cmake_find_mode", "none")
        self.cpp_info.builddirs = [os.path.join("lib", "cmake")]
        # 导出运行时环境：Qt 模块在构建树外不会自动带上本包 lib/ 的 RPATH，
        # 消费者与 test_package 依赖 conanrun 的 LD_LIBRARY_PATH 才能加载
        # libQt6WebChannel.so.6（与 libkleo/ktextaddons/akonadi 的做法一致）。
        self.runenv_info.prepend_path(
            "LD_LIBRARY_PATH", os.path.join(self.package_folder, "lib")
        )
