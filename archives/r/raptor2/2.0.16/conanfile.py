#!/usr/bin/env python3
"""Conan 2 recipe — raptor2 2.0.16 (Raptor RDF Syntax Library) for HarmonyOS PC (aarch64).

Upstream is a C library (autotools) providing RDF parsers/serializers.  This
recipe builds it natively on OHOS/aarch64 with its full upstream test suite
(`make check`) and with all upstream parsers/serializers enabled (libxml2,
libxslt for GRDDL, yajl for RDF/JSON, libcurl as the WWW backend and ICU for the
Unicode NFC check).  See notes.md for the five adaptation patches.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get, rm
from conan.tools.gnu import Autotools, AutotoolsToolchain, PkgConfigDeps
from conan.tools.layout import basic_layout
from conan.tools.env import VirtualBuildEnv


class Raptor2Conan(ConanFile):
    name = "raptor2"
    version = "2.0.16"
    package_type = "library"
    description = ("Raptor RDF Syntax Library — high-performance C library for "
                   "parsing and serializing RDF/XML, Turtle, N-Triples, N-Quads, "
                   "TriG, RSS, RDFa and JSON-LD style RDF/JSON")
    license = "LGPL-2.1-or-later OR GPL-2.0-or-later OR Apache-2.0"
    homepage = "https://librdf.org/raptor/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("rdf", "xml", "semantic-web", "parser", "serializer")

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    exports_sources = "conandata.yml", "patches/*"

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "raptor2 is adapted and validated for Linux/OHOS, got {}".format(self.settings.os)
            )
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration(
                "raptor2/2.0.16 is validated for OHOS armv8, got {}".format(self.settings.arch)
            )

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # libxml2 is the XML parser and is required by the RDF/XML and RSS parsers.
        # libxslt/1.1.45.2 declares libxml2/2.15.3; override so the whole graph
        # resolves against the newer published revision (same pattern as
        # archives/a/abiword-plugin-gdict/3.0.8).
        self.requires("libxml2/2.15.3.1", override=True)
        self.requires("libxslt/1.1.45.2")   # GRDDL parser
        self.requires("yajl/2.1.0")         # RDF/JSON parser
        self.requires("curl/8.22.0")        # WWW backend (upstream default)
        self.requires("icu4c/78.3")         # Unicode NFC check for RDF/XML

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Force the pkg-config detection path for libxslt.  When an xslt-config
        # script from a dependency prefix is on PATH, configure takes the
        # xslt-config branch whose libxslt probe fails on this target and the
        # GRDDL parser is silently disabled; pkg-config (generated by
        # PkgConfigDeps) resolves it correctly.
        tc.configure_args.append("--without-xslt-config")
        # yajl has no pkg-config-friendly probe in configure.ac; point it at the
        # dependency prefix so the RDF/JSON parser is built (upstream default).
        tc.configure_args.append("--with-yajl={}".format(self.dependencies["yajl"].package_folder))
        # ICU is a C++ library and is linked statically, so the C linker driver
        # must be told to link the C++ runtime explicitly (same fix as
        # archives/a/audiofile/0.3.6).
        tc.extra_ldflags.append("-lc++")
        tc.generate()
        PkgConfigDeps(self).generate()
        VirtualBuildEnv(self).generate()

    def build(self):
        apply_conandata_patches(self)
        self._prepend_dependency_libdirs()
        autotools = Autotools(self)
        autotools.configure()
        self._assert_full_feature_set()
        autotools.make()
        # Upstream full test suite (src unit tests + tests/ RDF corpus).
        # Do not treat a successful library build as a substitute for it.
        # Serial on purpose: within tests/<suite>/ the check-local loop targets
        # (check-rdf, check-rdfdiff, ...) share per-file result names, so running
        # them in parallel makes them clobber each other's *.res files.
        autotools.make(target="check", args=["-j1"])

    def _prepend_dependency_libdirs(self):
        """Put this graph's shared dependency libdirs first on the loader path.

        `make check` runs freshly linked binaries in the build environment, whose
        LD_LIBRARY_PATH (from the OHOS profile) contains the OHOS SDK lld runtime
        directory.  That directory ships its own libxml2.so.16, and shared
        dependencies built by Conan (libxml2, yajl) would otherwise either be
        shadowed by it or not be found at all ("libyajl.so.2: not found").
        """
        libdirs = []
        for dep in self.dependencies.host.values():
            for libdir in dep.cpp_info.aggregated_components().libdirs:
                if libdir and libdir not in libdirs:
                    libdirs.append(libdir)
        if not libdirs:
            return
        current = os.environ.get("LD_LIBRARY_PATH", "")
        if current:
            libdirs.append(current)
        os.environ["LD_LIBRARY_PATH"] = ":".join(libdirs)

    def _assert_full_feature_set(self):
        """Fail loudly if configure silently dropped an upstream feature.

        raptor2 degrades quietly when a dependency is not detected (e.g. GRDDL
        without libxslt, RDF/JSON without yajl, the libxml nanohttp WWW backend
        when libcurl is not detected).  A build that only "compiles" while
        dropping parsers is not an acceptable adaptation, so the expected
        feature macros are asserted here.
        """
        config_header = os.path.join(self.build_folder, "src", "raptor_config.h")
        if not os.path.exists(config_header):
            config_header = os.path.join(self.source_folder, "src", "raptor_config.h")
        with open(config_header, "r", encoding="utf-8", errors="replace") as handle:
            defines = handle.read()
        expected = [
            "RAPTOR_PARSER_RDFXML", "RAPTOR_PARSER_NTRIPLES", "RAPTOR_PARSER_TURTLE",
            "RAPTOR_PARSER_TRIG", "RAPTOR_PARSER_NQUADS", "RAPTOR_PARSER_RSS",
            "RAPTOR_PARSER_RDFA", "RAPTOR_PARSER_GUESS",
            "RAPTOR_PARSER_GRDDL", "RAPTOR_PARSER_JSON",
            "RAPTOR_SERIALIZER_RDFXML", "RAPTOR_SERIALIZER_TURTLE",
            "RAPTOR_SERIALIZER_NTRIPLES", "RAPTOR_SERIALIZER_JSON",
            "RAPTOR_SERIALIZER_ATOM", "RAPTOR_SERIALIZER_DOT",
            "RAPTOR_WWW_LIBCURL", "RAPTOR_ICU_NFC", "RAPTOR_XML_LIBXML",
        ]
        missing = [macro for macro in expected if "#define {}".format(macro) not in defines]
        if missing:
            raise ConanInvalidConfiguration(
                "raptor2 configure silently disabled upstream features: {}. "
                "Refusing to package a reduced build.".format(", ".join(missing))
            )

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        copy(self, "LICENSE*", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))
        copy(self, "COPYING*", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))
        copy(self, "NOTICE", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))
        # libtool archives are not useful to consumers (R26/E236).
        rm(self, "*.la", os.path.join(self.package_folder, "lib"))

    def package_info(self):
        self.cpp_info.libs = ["raptor2"]
        # Upstream installs the headers into <prefix>/include/raptor2/ and its
        # raptor2.pc exports includedir=<prefix>/include/raptor2 (so consumers
        # write #include <raptor2.h>).  Export both roots, like the OHPCD
        # libxml2 recipe does, so <raptor2.h> and <raptor2/raptor2.h> both work.
        self.cpp_info.includedirs = ["include", os.path.join("include", "raptor2")]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["m", "dl", "pthread"]
        # raptor2 links ICU statically (C++), so a consumer of the static archive
        # must also link the C++ runtime.  Declare it explicitly instead of
        # leaving undefined C++ symbols for the consumer to trip over.
        self.cpp_info.system_libs.append("c++")
        self.cpp_info.set_property("cmake_file_name", "raptor2")
        self.cpp_info.set_property("cmake_target_name", "raptor2::raptor2")
        self.cpp_info.set_property("pkg_config_name", "raptor2")
        # The upstream rapper CLI and the raptor2 pkg-config module are installed.
        self.cpp_info.bindirs = ["bin"]
