#!/usr/bin/env python3
"""Conan recipe — rc 1.7.4 (Plan 9 shell reimplemented for Unix).

rc is the Plan 9 shell, reimplemented for Unix by Byron Rakitzis.
Build system: Autotools (autoconf + automake)
Platform: OHOS aarch64 / Linux
Dependencies: None (standalone C program)

The GitHub archive lacks pre-built configure/Makefile.in. Since the CI
worker has autoconf but not automake, patches 0005-0011 add the
automake-generated files (Makefile.in, aclocal.m4, missing, depcomp,
compile, install-sh, mkinstalldirs). autoconf and autoheader (available
on CI) then generate configure and config.h.in from configure.ac.
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, chdir
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class RcConan(ConanFile):
    name = "rc"
    version = "1.7.4"
    description = "Plan 9 shell reimplemented for Unix by Byron Rakitzis"
    license = "Zlib"
    homepage = "https://github.com/rakitzis/rc"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        # Apply patches: adds automake-generated files (Makefile.in,
        # aclocal.m4, missing, depcomp, compile, install-sh, mkinstalldirs)
        apply_conandata_patches(self)

        # Generate configure and config.h.in using autoconf (available on CI)
        # aclocal.m4 is provided via patch (automake not available on CI)
        with chdir(self, self.source_folder):
            self.run("autoconf --force", env="conanbuild")
            self.run("autoheader --force", env="conanbuild")
            # Fix HMDFS SGID + umask 077 issue (E081):
            # autoconf creates temp dirs with umask 077, which on HMDFS results
            # in drwx--S--- (unwritable) directories. Remove umask 077.
            self.run("sed -i 's|umask 077 && mktemp -d|mktemp -d|g' configure", env="conanbuild")
            self.run("sed -i 's|umask 077 && mkdir|mkdir|g' configure", env="conanbuild")
            # Touch generated files to prevent make from trying to run automake/autoconf
            # (automake is not available on CI worker)
            self.run("touch Makefile.in aclocal.m4 config.h.in missing depcomp compile install-sh mkinstalldirs 2>/dev/null || true", env="conanbuild")
            # Touch configure LAST so it's newer than all its dependencies
            self.run("touch configure 2>/dev/null || true", env="conanbuild")

        autotools = Autotools(self)
        autotools.configure()

        # config.status (generated by configure) also has umask 077
        with chdir(self, self.build_folder):
            self.run("sed -i 's|umask 077 && mktemp -d|mktemp -d|g' config.status 2>/dev/null || true", env="conanbuild")
            self.run("sed -i 's|umask 077 && mkdir|mkdir|g' config.status 2>/dev/null || true", env="conanbuild")

        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = []
