#!/usr/bin/env python3
"""Conan recipe — seyon 2.20c (X11/Xaw serial-communication terminal, 1993-1999).

Seyon is an old-style X11/Athena (Xaw) communication program.  Upstream ships
only an Imakefile (imake/X11R5); this recipe rewrites the build with a
generated POSIX Makefile that compiles every translation unit against the
Conan-provided X11 stack, and additionally packages the object set as a static
library so consumers can link and call seyon's script parser (``ParseThis``).

OHOS adaptation notes (see patches/)
------------------------------------
- ``SeParse.y`` epilogue carries multi-line string literals inside an
  ``#ifdef TEST`` block; bison >= 3.0 lexes the epilogue and rejects them
  ("missing '"' at end of line").  Patch 0001 joins the literals with
  backslash-newline continuations (same fix Debian ships as
  01-debian-diff-to-be-split-some-day.patch).
- ``SeDecl.h`` K&R-declares ``usleep()`` and ``getline()``; OHOS libc
  (``<unistd.h>`` / ``<stdio.h>``) already declares them with different
  prototypes.  Patch 0002 drops the ``usleep`` prototype and renames the local
  ``getline`` to ``seyon_getline`` (declaration + ``SeScript.c`` call sites +
  ``SeSupp.c`` definition), matching Debian's 02-rename-getline patch.
- ``-fcommon`` is required: ``SeDial.c`` and ``SeTrans.c`` both carry a
  tentative definition of the global ``mlw``; modern clang defaults to
  ``-fno-common`` and lld rejects the duplicate symbol.
- ``version.h`` is generated by the upstream ``makever.sh``; ``Seyon.ad.h`` by
  the upstream ``ad2c`` sed filter; ``SeParse.c``/``y.tab.h`` by ``yacc``
  (bison), exactly as the Imakefile does.

Build tools: ``yacc``/``bison`` and ``sed`` are host tools shipped in
``/data/service/hnp/bin`` on the OHOS device (same approach as archives/b/boxes).
The compiler/archiver come from ``tools.build:compiler_executables`` / PATH.
"""
import os
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout

# explicit link order, most specific first (mirrors upstream XawClientLibs)
LINK_LIBS = ["Xaw", "Xmu", "Xt", "Xext", "X11", "Xpm", "ICE", "SM",
             "xcb", "Xau", "Xdmcp"]

# translation units (Imakefile SRCS); SeParse.c is generated by yacc
SRCS = ["Seyon", "SeActions", "SeScan", "SeDial", "SeErr", "SeGeneric",
        "SeInit", "SeIo", "SeMisc", "SeParse", "SePort", "SeScript", "SeSet",
        "SeSig", "SeString", "SeSubs", "SeSubsX", "SeSupp", "SeTerm",
        "SeTrans", "SeWin", "MultiList"]

# objects that go into libseyon.a: everything except Seyon.o (which defines main)
LIB_SRCS = [s for s in SRCS if s != "Seyon"]

HEADERS = ["seyon.h", "config.h", "SeDecl.h", "SeParse.h", "SeSig.h",
           "MultiList.h", "MultiListP.h"]

DATA_FILES = ["seyon.help", "phonelist", "protocols", "startup",
              "script.CIS", "script.PCBoard", "script.QWK", "script.unix"]

# seyon's compile-time fallback for the help file (Imakefile -DHELPFILE)
HELPFILE = "/usr/share/seyon/seyon.help"


class SeyonConan(ConanFile):
    name = "seyon"
    version = "2.20c"
    description = ("seyon: an X11/Athena (Xaw) serial-communication program "
                   "with a scriptable command language")
    license = "LicenseRef-Seyon-Berkeley"
    homepage = "https://www.seyon.org/"
    url = "https://deb.debian.org/debian/pool/main/s/seyon/"

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def requirements(self):
        # X11/Xaw stack. libxaw/1.0.14 pulls libxmu/libxt/libx11/libxext/libxpm
        # transitively (all os=OHOS/armv8/clang15 on the ohpcd remote).
        self.requires("libx11/1.8.13")
        self.requires("libxaw/1.0.14")
        self.requires("libxmu/1.3.1.1")
        self.requires("libxt/1.3.1")
        self.requires("libxext/6.4.0.1")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"seyon is validated on Linux/OHOS, got {self.settings.os}")
        if self.settings.arch not in ("armv8", "aarch64"):
            raise ConanInvalidConfiguration("seyon builds require aarch64 (armv8)")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    # ── helpers ────────────────────────────────────────────────────────────
    def _compiler(self, name, fallback):
        exes = self.conf.get("tools.build:compiler_executables",
                             default={}, check_type=dict) or {}
        return exes.get(name) or fallback

    def _archiver(self, cc):
        for cand in (os.path.join(os.path.dirname(cc), "llvm-ar"),
                     shutil.which("llvm-ar"), shutil.which("ar")):
            if cand and os.path.isfile(cand):
                return cand
        return "llvm-ar"

    def _dep_dirs(self):
        incs, libs = [], []
        for dep in self.dependencies.values():
            cpp = dep.cpp_info.aggregated_components()
            for d in cpp.includedirs:
                if d not in incs:
                    incs.append(d)
            for d in cpp.libdirs:
                if d not in libs:
                    libs.append(d)
        return incs, libs

    # ── build ──────────────────────────────────────────────────────────────
    def build(self):
        apply_conandata_patches(self)
        src = self.source_folder
        cc = self._compiler("c", "clang")
        ar = self._archiver(cc)

        # 1) version.h (upstream makever.sh)
        self.run("sh makever.sh", cwd=src, env="conanbuild")
        if not os.path.isfile(os.path.join(src, "version.h")):
            raise ConanException("makever.sh did not produce version.h")

        # 2) Seyon.ad.h (upstream ad2c sed filter) — capture stdout, write file
        ad2c = subprocess.run(["sh", "ad2c", "Seyon.ad"], cwd=src,
                              capture_output=True, text=True)
        if ad2c.returncode != 0:
            raise ConanException(f"ad2c failed: {ad2c.stderr.strip()}")
        with open(os.path.join(src, "Seyon.ad.h"), "w") as fh:
            fh.write(ad2c.stdout)

        # 3) SeParse.c + y.tab.h (upstream: yacc -d SeParse.y; mv y.tab.c SeParse.c)
        self.run("yacc -d SeParse.y", cwd=src, env="conanbuild")
        if not os.path.isfile(os.path.join(src, "y.tab.c")):
            raise ConanException("yacc did not produce y.tab.c")
        os.replace(os.path.join(src, "y.tab.c"), os.path.join(src, "SeParse.c"))

        # 4) generated Makefile.ohos (upstream ships only an Imakefile)
        incs, libdirs = self._dep_dirs()
        opt = "-O2" if str(self.settings.build_type) == "Release" else "-g -O0"
        cflags = ("-fcommon " + opt +
                  "".join(" -I%s" % d for d in incs) +
                  " -I." + ' -DHELPFILE=\\"%s\\"' % HELPFILE)
        ldflags = ("".join(" -L%s" % d for d in libdirs) +
                   "".join(" -l%s" % l for l in LINK_LIBS))
        objs = " ".join("%s.o" % s for s in SRCS)
        libobjs = " ".join("%s.o" % s for s in LIB_SRCS)
        makefile = """# Generated by conanfile.py (OHOS port); upstream uses an Imakefile.
CC = {cc}
AR = {ar}
CFLAGS = {cflags}
LDFLAGS = {ldflags}
OBJS = {objs}
LIBOBJS = {libobjs}

all: seyon libseyon.a

seyon: $(OBJS)
\t$(CC) -o $@ $(OBJS) $(LDFLAGS)

libseyon.a: $(LIBOBJS)
\t$(AR) rcs $@ $(LIBOBJS)

%.o: %.c
\t$(CC) $(CFLAGS) -c $< -o $@

clean:
\trm -f $(OBJS) seyon libseyon.a
""".format(cc=cc, ar=ar, cflags=cflags, ldflags=ldflags,
           objs=objs, libobjs=libobjs)
        with open(os.path.join(src, "Makefile.ohos"), "w") as fh:
            fh.write(makefile)

        self.run("make -f Makefile.ohos -j1", cwd=src, env="conanbuild")
        for produced in ("seyon", "libseyon.a"):
            if not os.path.isfile(os.path.join(src, produced)):
                raise ConanException(f"build did not produce {produced}")

    # ── package ────────────────────────────────────────────────────────────
    def package(self):
        src = self.source_folder
        bindir = os.path.join(self.package_folder, "bin")
        libdir = os.path.join(self.package_folder, "lib")
        incdir = os.path.join(self.package_folder, "include", "seyon")
        sharedir = os.path.join(self.package_folder, "share", "seyon")
        appdefs = os.path.join(self.package_folder, "share", "X11", "app-defaults")
        licenses = os.path.join(self.package_folder, "licenses")

        copy(self, "seyon", src, bindir, keep_path=False)
        os.chmod(os.path.join(bindir, "seyon"), 0o755)
        copy(self, "libseyon.a", src, libdir, keep_path=False)
        for h in HEADERS:
            copy(self, h, src, incdir, keep_path=False)
        for d in DATA_FILES:
            copy(self, d, src, sharedir, keep_path=False)
        copy(self, "Seyon.ad", src, appdefs, keep_path=False)
        os.rename(os.path.join(appdefs, "Seyon.ad"),
                  os.path.join(appdefs, "Seyon"))
        copy(self, "Seyon-co.ad", src, appdefs, keep_path=False)
        os.rename(os.path.join(appdefs, "Seyon-co.ad"),
                  os.path.join(appdefs, "Seyon-color"))
        copy(self, "1-COPYING", src, licenses, keep_path=False)
        copy(self, "COPYING", src, licenses, keep_path=False)

        if self.settings.os == "OHOS":
            self._sign_ohos_elf(os.path.join(bindir, "seyon"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libs = ["seyon"]
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))

    # ── OHOS ELF signing (fail-closed) ─────────────────────────────────────
    @staticmethod
    def _sign_ohos_elf(path):
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        readelf = shutil.which("llvm-readelf") or "/data/service/hnp/bin/llvm-readelf"
        if not os.path.isfile(path):
            raise ConanException(f"missing packaged executable: {path}")
        if not os.path.isfile(signer) or not os.path.isfile(readelf):
            raise ConanException("required OHOS signing tools are missing")
        output = path + ".signed"
        subprocess.run(
            [signer, "sign", "-inFile", path, "-outFile", output, "-selfSign", "1"],
            check=True, timeout=60,
        )
        sections = subprocess.run(
            [readelf, "-SW", output], check=True, capture_output=True,
            text=True, timeout=30,
        ).stdout
        if sections.count(".codesign") != 1:
            raise ConanException("signed packaged executable has invalid .codesign count")
        os.chmod(output, (os.stat(path).st_mode & 0o777) | 0o055)
        os.replace(output, path)
