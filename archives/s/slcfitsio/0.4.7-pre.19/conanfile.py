#!/usr/bin/env python3
"""Conan recipe — slcfitsio 0.4.7-pre.19 (S-Lang CFITSIO module).

slcfitsio is the S-Lang language binding for CFITSIO: it wraps the FITS I/O
library so FITS files can be read and written directly from the S-Lang
interpreter (slsh, jed, ...).  Upstream builds a single loadable module,
``cfitsio-module.so``, plus three S-Lang wrapper scripts and a help file.

Upstream/Conan version mapping
------------------------------
``src/version.h`` declares ``MODULE_VERSION_STRING "pre0.4.7-19"`` and
``MODULE_VERSION_NUMSTR "0.4.7"``; the tarball is named
``slcfitsio-pre0.4.7-19.tar.gz``.  The Debian/Ubuntu spelling of that release
is ``0.4.7~pre.19``, i.e. the platform version ``0.4.7-pre.19``.

Why this is not a linkable library
----------------------------------
S-Lang resolves ``import ("cfitsio")`` to ``<name>-module.so`` inside
``SLANG_MODULE_PATH`` (libslang carries the ``"%s-module.%s"`` template and
the default ``<prefix>/lib/slang/v2/modules`` search directory).  The artifact
is therefore dlopen()ed by the interpreter at run time and is packaged as a
shared module, not as ``libslcfitsio.so``.

OHOS adaptations (all verified against this exact tarball)
----------------------------------------------------------
1. The release tarball ships a pre-generated autoconf 2.69 ``configure``, so
   no autotools regeneration is required.  Its bundled
   ``config.sub``/``config.guess`` are 2007 vintage and reject any ``-ohos``
   OS component (``system `ohos' not recognized``), so configure is driven
   with an explicit ``--build=x86_64-linux-gnu
   --host=aarch64-unknown-linux-gnu`` pair (the jlog 2.6.0 precedent).  Both
   ``JD_ELF_COMPILER`` (``case $host_os in *linux*``) and
   ``JD_CHECK_FOR_LIBRARY`` (``lib<name>.so``/``.a`` extension list) then take
   exactly the branch this project needs, and because build != host, autoconf
   compiles its ``AC_CHECK_SIZEOF`` probes instead of running them.
2. ``src/cfitsio-version.h`` is generated by upstream by compiling and then
   *executing* a helper that prints the cfitsio version the module is built
   against.  The helper only calls ``fits_get_version()``, but upstream's link
   line feeds it the whole ``$(LIBS)``, including ``-lslang``.  It is linked
   here with ``SLANG_LIB=`` (slang-free), which leaves libc as its only
   runtime dependency; the cross-compiled helper then runs and the real
   version number is captured (verified value below).
3. ``JD_SET_RPATH`` would bake the *build machine's* conan cache path into the
   module's ``DT_RUNPATH``.  The module is therefore linked with ``RPATH=``
   (the makefile variable is overridable from the command line), so nothing
   build-host specific ships.  libslang.so.2 is found through the consumer's
   runtime environment (conanrun / ``LD_LIBRARY_PATH``), as for any other
   consumer of the slang package.
4. cfitsio is pulled with its default ``shared=False``: ``libcfitsio.a`` is
   linked into the module, so the shipped ``.so`` has no runtime dependency on
   libcfitsio.  ``libcfitsio.a`` needs zlib (``inflate``/``deflate``), which
   the upstream makefile has no slot for; it is passed through the makefile's
   own ``OTHER_LIBS`` extension point.  The zlib conan package ships only
   ``libz.a``, so pointing ``-L`` at it links zlib statically and the module
   keeps exactly one runtime dependency, libslang.so.2.
5. SHELL/CONFIG_SHELL are pinned to ``/bin/sh`` and configure is driven
   through ``sh`` (HMFS/HMDFS ``shell_getcwd`` hardening, same as jlog and
   spectools).
6. E114 / HMBS diagnosis ``unsafe_local_mktemp``: HMFS ``mktemp -d`` under
   ``umask 077`` makes an unwritable ``drwx--S---`` temp dir and chmod is a
   no-op (``HMBS_CAP_CHMOD=0``), so the embedded ``config.status`` template
   dies with ``./confXXXXXX/subs1.awk: Permission denied``.  The shipped
   autoconf-2.69 ``configure`` is patched in ``build()`` (``umask 077`` ->
   ``umask 022``) so config.status' temp dir is writable.  Same remediation
   as jlog/spectools/zzuf/ytnef/bluez.
"""

import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, get
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout

# Upstream JD_SLANG_MODULE_INSTALL_DIR keys the module directory off the
# S-Lang MAJOR version parsed out of slang.h (2 for slang 2.3.3).
MODULE_SUBDIR = os.path.join("lib", "slang", "v2", "modules")
SL_FILES_SUBDIR = os.path.join("share", "slsh", "local-packages")


class SlcfitsioConan(ConanFile):
    name = "slcfitsio"
    version = "0.4.7-pre.19"
    description = ("S-Lang module wrapping the CFITSIO library: read and write "
                   "FITS files from the S-Lang interpreter")
    license = "GPL-2.0-or-later"
    homepage = "https://space.mit.edu/cxc/software/slang/modules/cfitsio/"
    url = "https://www.jedsoft.org/snapshots/"
    topics = ("fits", "cfitsio", "slang", "astronomy", "module")

    # The deliverable is a dlopen()ed S-Lang module; there is no
    # libslcfitsio.so for consumers to link against, so the recipe declares no
    # `shared` option (Conan rejects a `shared` option on static-library /
    # shared-library package types).
    package_type = "shared-library"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "slcfitsio is built for Linux/OHOS only")

    def requirements(self):
        # static libcfitsio.a -> linked into the module (no runtime dep)
        self.requires("cfitsio/4.6.4")
        # shared libslang.so.2 + the slsh interpreter and its header
        self.requires("slang/2.3.3")

    def layout(self):
        basic_layout(self)
        # Upstream AC_OUTPUT writes both Makefile and src/Makefile in the
        # source tree, and src/Makefile.in has no VPATH support, so this is an
        # in-source build.
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # R33: compiler and flags come from the Conan toolchain, never from
        # bare shell variables.
        AutotoolsToolchain(self).generate()

    def build(self):
        # HMFS/HMDFS shell_getcwd: the on-device HNP bash cannot resolve the
        # build folder, so every subprocess is routed through /bin/sh.
        os.environ["SHELL"] = "/bin/sh"
        os.environ["CONFIG_SHELL"] = "/bin/sh"

        # E114 / HMBS diagnosis [unsafe_local_mktemp]: HMDFS `mktemp -d` under
        # `umask 077` makes an unwritable drwx--S--- temp dir, and chmod is a
        # no-op here (HMBS_CAP_CHMOD=0), so config.status dies with
        # `can't create ./confXXXXXX/subs1.awk: Permission denied`.  The
        # shipped autoconf-2.69 `configure` carries config.status as an
        # embedded template, so relaxing umask 077 -> 022 in configure fixes
        # both.  Same remediation as jlog/spectools/zzuf/ytnef/bluez/...
        self._harden_configure_tmpdir()

        slang = self.dependencies["slang"].cpp_info
        cfitsio = self.dependencies["cfitsio"].cpp_info
        # libcfitsio.a calls zlib's inflate/deflate; the upstream makefile has
        # no slot for it, hence OTHER_LIBS.  The zlib package ships only
        # libz.a, so this links zlib statically.
        other_libs = "-L%s -lz" % self.dependencies["zlib"].cpp_info.libdir
        staging = os.path.join(self.source_folder, "install-staging")

        # Seed PWD and inline-override SHELL/CONFIG_SHELL so autoconf's re-exec
        # and config.status use /bin/sh even if getcwd() fails on HMFS.
        self.run(
            "export SHELL=/bin/sh CONFIG_SHELL=/bin/sh PWD='%s'; "
            "exec sh ./configure --prefix=/usr"
            " --build=x86_64-linux-gnu --host=aarch64-unknown-linux-gnu"
            " --with-slanginc=%s --with-slanglib=%s"
            " --with-cfitsioinc=%s --with-cfitsiolib=%s"
            % (self.source_folder, slang.includedir, slang.libdir,
               cfitsio.includedir, cfitsio.libdir),
            cwd=self.source_folder, env="conanbuild")

        # 1) src/cfitsio-version.h.  Upstream generates it by compiling and
        #    running a helper; that helper is linked slang-free here (see the
        #    module docstring) so it can actually execute during a cross
        #    build.  It prints the real cfitsio version
        #    (4.060400 for cfitsio 4.6.4).
        self.run(
            "make -C src SHELL=/bin/sh SLANG_LIB= OTHER_LIBS='%s' "
            "cfitsio-version.h" % other_libs,
            cwd=self.source_folder, env="conanbuild")

        # 2) the module, linked with RPATH= so the generated
        #    -Wl,-R<build machine conan cache dirs> never reaches the package.
        self.run(
            "make -C src SHELL=/bin/sh RPATH= OTHER_LIBS='%s'" % other_libs,
            cwd=self.source_folder, env="conanbuild")

        # 3) install (module + .sl wrappers + .hlp) into the staging tree.
        self.run(
            "make -C src SHELL=/bin/sh RPATH= install DESTDIR=%s" % staging,
            cwd=self.source_folder, env="conanbuild")

    def _harden_configure_tmpdir(self):
        # E011/E060/E112/E114 (HMBS diagnosis [unsafe_local_mktemp]):
        # HMDFS mktemp -d under `umask 077` creates a `drwx--S---` temp dir
        # that not even its owner can write into, and chmod is a no-op on this
        # filesystem (HMBS_CAP_CHMOD=0), so config.status dies with
        # `can't create ./confXXXXXX/subs1.awk: Permission denied`.  Patch the
        # shipped `configure` (config.status is emitted from a template embedded
        # in it, so fixing configure covers both) to create temp dirs with
        # umask 022 -> writable.  Returns True if modified.
        path = os.path.join(self.source_folder, "configure")
        if not os.path.isfile(path):
            self.output.warning("[E114] configure missing: %s" % path)
            return False
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        fixed = text.replace("umask 077", "umask 022")
        if fixed == text:
            return False
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(fixed)
        self.output.info("E114: relaxed umask 077->022 in shipped configure")
        return True

    def package(self):
        staging_usr = os.path.join(self.source_folder, "install-staging", "usr")
        copy(self, "*", src=staging_usr, dst=self.package_folder)
        copy(self, "COPYRIGHT", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        # Not linkable: the module is loaded at run time by the S-Lang
        # interpreter through SLANG_MODULE_PATH.
        self.cpp_info.libs = []
        self.cpp_info.bindirs = []
        self.cpp_info.includedirs = []
        self.cpp_info.set_property("cmake_file_name", "slcfitsio")
        self.cpp_info.set_property("cmake_target_name", "slcfitsio::slcfitsio")
        # Where the module and the wrapper .sl files were installed, for
        # consumers that want to extend SLANG_MODULE_PATH / the S-Lang load
        # path.
        self.cpp_info.set_property("slcfitsio.module_subdir", MODULE_SUBDIR)
        self.cpp_info.set_property("slcfitsio.sl_files_subdir", SL_FILES_SUBDIR)
