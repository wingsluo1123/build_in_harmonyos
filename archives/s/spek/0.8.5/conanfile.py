#!/usr/bin/env python3
"""Conan recipe — spek 0.8.5 (Autotools, headless CLI build)."""
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout
import os


class SpekConan(ConanFile):
    name = "spek"
    version = "0.8.5"
    description = "Spek - Acoustic spectrum analyser (headless CLI build)"
    license = "GPL-3.0"
    homepage = "https://www.spek.cc/"
    url = "https://github.com/alexkay/spek"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # spek decodes audio via FFmpeg (libavformat/libavcodec/libavutil).
        # configure.ac probes these unconditionally with PKG_CHECK_MODULES,
        # so the dependency is required in both GUI and headless modes.
        # ffmpeg/8.1.1 provides libavformat 62.x, libavcodec 62.x, libavutil 60.x,
        # satisfying spek's >= 59.27.100 / >= 59.37.100 / >= 57.28.100 minimums.
        self.requires("ffmpeg/8.1.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Headless build: skip wxWidgets GUI
        tc.configure_args.append("--disable-gui")
        # R26: System-name libraries default to static
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")

        # FFmpeg's .pc files are exposed by the ffmpeg/8.1.1 requirement
        # declared above; Conan 2.x injects PKG_CONFIG_PATH automatically
        # via the conanbuild env generated by tc.generate().
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # Regenerate configure from patched configure.ac (patch adds --disable-gui)
        # Use autoconf instead of autoreconf -fi (autopoint not available on CI worker)
        self.run("autoconf", cwd=self.source_folder)
        # E046: HMDFS does not preserve +x on autoconf-generated configure,
        # causing "Permission denied" (exit 126) when Autotools.exec() runs it.
        # chmod every configure we can find in source/build folders.
        for pattern in (
            os.path.join(self.source_folder, "configure"),
            os.path.join(self.build_folder, "configure"),
            os.path.join(os.path.dirname(self.build_folder), "configure"),
        ):
            if os.path.exists(pattern):
                os.chmod(pattern, 0o755)
        # HMDFS noexec: Autotools.configure() exec'es ./configure directly,
        # which Permission-denies (exit 126) on noexec mounts. Invoke via
        # explicit `sh` interpreter to bypass exec-bit requirement; this is
        # the Autotools-standard invocation form and works on CI workers too.
        # Configure lives in source_folder (Autotools.configure uses
        # script_folder=source_folder, not build_folder); build runs in a
        # separate build-release/ dir, so reference configure by its source
        # path and let autotools make() reuse the generated Makefile.
        tc = AutotoolsToolchain(self)
        configure_args = tc.configure_args
        if not self.options.shared:
            configure_args = list(configure_args) + ["--enable-static", "--disable-shared"]
        args_str = " ".join(configure_args)
        configure_path = os.path.join(self.source_folder, "configure")
        self.run(f'sh "{configure_path}" {args_str}', cwd=self.build_folder)
        autotools = Autotools(self)
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]