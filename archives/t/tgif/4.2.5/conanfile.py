#!/usr/bin/env python3
"""Conan recipe for tgif 4.2.5 — an X11/Motif-style interactive 2-D drawing tool.

tgif is a large C application (autotools) built on libX11 + libXt (Xt
Intrinsics) with zlib for its compressed-file (PNG-transparency / GIF) paths.
The upstream release ships a pre-generated `configure`, so the recipe drives the
shipped configure script directly and never regenerates it.
"""

import os
import platform
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class TgifConan(ConanFile):
    name = "tgif"
    version = "4.2.5"
    description = (
        "Interactive 2-D drawing tool for X11 (Motif-style), with HyperGraphics "
        "and Tangram-II support"
    )
    license = "QPL-1.0"
    homepage = "https://sourceforge.net/projects/tgif/"
    url = "https://atomgit.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("graphics", "x11", "drawing", "editor", "ohos")
    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # X11 client stack. libxt/1.3.1 pins the libx11/1.8.13 "X11 katamari"
        # track, so the whole graph is aligned on it (libx11 carries the X11
        # headers — Xlib/Xutil/keysym — plus the transitive xorgproto).
        self.requires("libx11/1.8.13", transitive_headers=True, transitive_libs=True)
        self.requires("libxt/1.3.1", transitive_headers=True, transitive_libs=True)
        # src/pngtrans.c and src/z_intrf.c call zlib's inflate() API.
        self.requires("zlib/1.3.2", transitive_headers=True, transitive_libs=True)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"tgif supports Linux and OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        # Upstream's release tarball is dirty: it was packed from a tree that had
        # already been configured in-place on the maintainer's machine, so it
        # ships config.status / config.h / config.log / Makefile with a hardcoded
        # srcdir. Conan builds out-of-tree (VPATH), where the stale config.status
        # makes configure abort with "source directory already configured; run
        # make distclean there first". All of these are regenerated by configure,
        # so drop them for a pristine source tree (same handling as libmng/didiwiki).
        for residue in ("config.status", "config.log", "config.cache",
                        "config.h", "stamp-h1", "Makefile"):
            path = os.path.join(self.source_folder, residue)
            if os.path.isfile(path):
                os.remove(path)

    def generate(self):
        # AutotoolsDeps feeds the dependency -I/-L/-l flags into configure's
        # AC_CHECK_LIB probes and into the link line; AutotoolsToolchain supplies
        # the compiler and its flags. Without AutotoolsDeps the AC_CHECK_LIB
        # probes for -lX11/-lXt fall back to the (absent) system X11 stack.
        AutotoolsDeps(self).generate()
        tc = AutotoolsToolchain(self)
        tc.generate()
        # The OHOS dynamic loader has no default search path for the Conan-cached
        # shared libraries, so configure's compile-and-run probes fail with
        # "cannot run C compiled programs" once AutotoolsDeps links the
        # dependencies into the conftest. Point LD_LIBRARY_PATH at the dependency
        # lib dirs for the build scope (same handling as archives/a/aaphoto/0.45).
        env = Environment()
        for dep in self.dependencies.values():
            for libdir in dep.cpp_info.libdirs:
                env.prepend_path("LD_LIBRARY_PATH", libdir)
        env.vars(self, scope="build").save_script("conanbuild_runpath")

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        # -j1: GNU make's jobserver creates a FIFO under $TMPDIR that HMDFS
        # (HarmonyOS) refuses with EPERM, leaving the parallel jobserver broken
        # (E074); pin a single job, as the other autotools recipes in this repo do.
        autotools.make(args=["-j1"])
        # Upstream registers no test suite; running the upstream `check` target
        # records the empty-suite result (see notes.md, R51 census).
        autotools.make(target="check", args=["-j1"])

    def package(self):
        Autotools(self).install()
        copy(
            self,
            "LICENSE.QPL",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )
        if self.settings.os == "OHOS":
            self._sign_ohos_binary(os.path.join(self.package_folder, "bin", "tgif"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]

    @staticmethod
    def _sign_ohos_binary(binary):
        """Self-sign the packaged ELF so it is loadable on HarmonyOS (fail-closed).

        E077: OHOS kernels refuse to exec unsigned ELFs ("Operation not permitted").
        Unlike a best-effort signer, this **fails loudly**: a missing packaged
        binary, a missing signing tool, a non-zero signer exit, or a signed
        output whose `.codesign` count is not exactly 1 all raise. That makes the
        later `.codesign` assertion in test_package meaningful — it can no longer
        be satisfied by the toolchain's default section alone. Same pattern as
        `archives/p/pan/0.165` and `archives/a/abx/0.1`.
        """
        from conan.errors import ConanInvalidConfiguration

        readelf = (
            shutil.which("llvm-readelf")
            or shutil.which("readelf")
            or "/data/service/hnp/bin/llvm-readelf"
        )
        if not os.path.isfile(binary):
            raise ConanInvalidConfiguration(f"Missing packaged executable: {binary}")
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(signer) or not os.path.isfile(readelf):
            raise ConanInvalidConfiguration(
                "Required OHOS signing tools are missing (binary-sign-tool / llvm-readelf)"
            )
        signed = binary + ".signed"
        subprocess.run(
            [signer, "sign", "-inFile", binary, "-outFile", signed, "-selfSign", "1"],
            check=True,
            timeout=120,
        )
        sections = subprocess.run(
            [readelf, "-SW", signed],
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        ).stdout
        if sections.count(".codesign") != 1:
            raise ConanInvalidConfiguration(
                "Signed tgif binary has invalid .codesign count: "
                f"{sections.count('.codesign')} (expected exactly 1)"
            )
        os.replace(signed, binary)
        os.chmod(binary, 0o755)
