#!/usr/bin/env python3
"""Conan recipe — theseus 3.3.0 (plain Makefile, HarmonyOS PC / aarch64)

THESEUS: maximum-likelihood superpositioning and analysis of macromolecular
structures (C, GSL-based). Build system: plain GNU make driven by a make.inc
platform include — upstream's own documented extension point ("Do not modify
this file, modify make.inc instead").

Upstream make.inc ships defaults that cannot work for an OHOS cross build
(ARCH=libtool, CC=/usr/bin/gcc, -mtune=native), so build() regenerates
make.inc with the Conan-resolved toolchain and GSL include/lib/rpath.
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, copy, save, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class TheseusConan(ConanFile):
    name = "theseus"
    version = "3.3.0"
    description = "Maximum likelihood superpositioning and analysis of macromolecular structures"
    license = "GPL-3.0-or-later"
    homepage = "http://www.theseus3d.org/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("gsl/2.8")

    def layout(self):
        basic_layout(self)
        # in-source build: Makefile + make.inc live at the source root
        self.folders.build = "."

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)
        # R33: compiler/ar/ranlib from Conan conf, never bare shell env vars;
        # fall back to the archive tool the environment actually has. The CI
        # worker PATH carries llvm-ar/llvm-ranlib from the OHOS toolchain; the
        # local WSL box only has GNU ar/ranlib — ar archives are
        # arch-agnostic containers, so a host ar packing cross .o files links
        # fine (and so does its ranlib index).
        compilers = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}

        def _pick(names):
            for n in names:
                found = shutil.which(n)
                if found:
                    return found
            return names[0]

        cc = compilers.get("c", "clang")
        ar = compilers.get("ar") or _pick(["llvm-ar", "ar"])
        ranlib = compilers.get("ranlib") or _pick(["llvm-ranlib", "ranlib"])

        gsl = self.dependencies["gsl"].cpp_info.aggregated_components()
        gsl_incs = " ".join(f"-I{d}" for d in gsl.includedirs)
        gsl_libs = " ".join(f"-L{d}" for d in gsl.libdirs)
        gsl_rpath = " ".join(f"-Wl,-rpath,{d}" for d in gsl.libdirs)

        make_inc = f"""# Generated by Conan (theseus 3.3.0) — OHOS cross build.
# Upstream extension point: "modify make.inc instead" for platform changes.
ARCH = {ar}
ARCHFLAGS = -rvs
RANLIB = {ranlib}
CC = {cc}
LOCALLIBDIR = /usr/local/lib
LIBS = -lgsl -lgslcblas -ldistfit -lmsa -ldssplite -ldltmath -lDLTutils -ltheseus
SYSLIBS = -lpthread -lm -lc
LIBDIR = -L./lib {gsl_libs}
INCDIR = {gsl_incs}
INSTALLDIR = /usr/local/bin
OPT = -O3 -ffast-math -fstrict-aliasing -funroll-loops -fomit-frame-pointer
WARN = -Wall -pedantic -std=c99
CFLAGS += $(WARN)
LDFLAGS = {gsl_rpath}
"""
        save(self, os.path.join(self.source_folder, "make.inc"), make_inc)

        # R9: -j1 for reproducible builds (Makefile has no parallel-safe order
        # between the subdirectory static libs and ltheseus)
        self.run("make -j1")

    def package(self):
        # main executable
        copy(self, "theseus", self.source_folder, os.path.join(self.package_folder, "bin"))
        # static component libraries (upstream ships them via installlibs)
        copy(self, "*.a", os.path.join(self.source_folder, "lib"),
             os.path.join(self.package_folder, "lib"))
        # public API headers
        copy(self, "theseus.h", self.source_folder, os.path.join(self.package_folder, "include"))
        copy(self, "theseuslib.h", self.source_folder, os.path.join(self.package_folder, "include"))
        # license + docs
        lic = os.path.join(self.package_folder, "licenses")
        for fn in ("COPYING", "README", "AUTHORS", "theseus.1"):
            copy(self, fn, self.source_folder, lic)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.libs = ["theseus", "distfit", "DLTutils", "msa", "dltmath", "dssplite"]
