#!/usr/bin/env python3
"""Conan recipe — ttyplot 1.7.1 (Makefile)"""

import os

from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class TtyplotConan(ConanFile):
    name = "ttyplot"
    version = "1.7.1"
    description = "Realtime plotting utility for terminal with data input from stdin"
    license = "Apache-2.0"
    homepage = "https://github.com/tenox7/ttyplot"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)

        # Get compiler from Conan profile env (generated by tools.build:compiler_executables)
        cc = os.environ.get("CC", "clang")

        # ncurses is installed as a system package (via cmd-pkgs) without .pc files.
        # The Makefile uses pkg-config --cflags/libs ncursesw, so we create .pc files
        # and set PKG_CONFIG_PATH so the backtick pkg-config calls resolve correctly.
        prefix = os.environ.get(
            "DEFAULT_PREFIX",
            os.path.join(os.path.expanduser("~"), "usr", "local"),
        )
        pkgconfig_dir = os.path.join(prefix, "lib", "pkgconfig")
        os.makedirs(pkgconfig_dir, exist_ok=True)

        for pc_name, extra_cflags in [("ncursesw", "-D_XOPEN_SOURCE_EXTENDED"), ("ncurses", "")]:
            pc_path = os.path.join(pkgconfig_dir, f"{pc_name}.pc")
            if not os.path.exists(pc_path):
                with open(pc_path, "w") as f:
                    f.write(
                        f"prefix={prefix}\n"
                        f"exec_prefix=${{prefix}}\n"
                        f"libdir=${{exec_prefix}}/lib\n"
                        f"includedir=${{prefix}}/include\n"
                        f"\n"
                        f"Name: {pc_name}\n"
                        f"Description: ncurses 6.4 library\n"
                        f"Version: 6.4\n"
                        f"Libs: -L${{libdir}} -lncurses\n"
                        f"Cflags: -I${{includedir}} {extra_cflags}\n"
                    )

        # Ensure pkg-config can find the .pc files we just created
        existing_pcpath = os.environ.get("PKG_CONFIG_PATH", "")
        os.environ["PKG_CONFIG_PATH"] = (
            f"{pkgconfig_dir}:{existing_pcpath}" if existing_pcpath else pkgconfig_dir
        )

        # R9: Use make -j1 (never -j$(nproc))
        self.run(f"make CC={cc} -j1", cwd=self.source_folder)

    def package(self):
        copy(self, "ttyplot", self.source_folder, os.path.join(self.package_folder, "bin"))
        copy(self, "ttyplot.1", self.source_folder, os.path.join(self.package_folder, "man", "man1"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
