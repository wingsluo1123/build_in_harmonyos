def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: fixture-blobs.py <dest_dir>\n")
        return 2
    dest = sys.argv[1]
    os.makedirs(dest, exist_ok=True)
    bad = 0
    for name, (sha, b64) in BLOBS.items():
        data = base64.b64decode(b64)
        got = hashlib.sha256(data).hexdigest()
        if got != sha:
            sys.stderr.write("ERROR: %s sha256 mismatch (want %s, got %s)\n"
                             % (name, sha, got))
            bad += 1
            continue
        path = os.path.join(dest, name)
        dirname = os.path.dirname(path)
        if dirname:
            os.makedirs(dirname, exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        print("%s: %d bytes sha256=%s ok" % (name, len(data), sha[:16]))
    if bad:
        sys.stderr.write("ERROR: %d blob(s) failed integrity check\n" % bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
