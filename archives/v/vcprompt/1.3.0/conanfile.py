#!/usr/bin/env python3
"""Conan recipe for vcprompt 1.3.0 (powerman fork of gward/vcprompt).

vcprompt prints version-control information (name, branch, revision, dirty
flags) for the current working directory, so it can be embedded in a shell
prompt.  It is a plain C99 program with no mandatory external dependency:
git/hg/svn/cvs/fossil working copies are detected directly from their
on-disk metadata, and external VCS binaries are only spawned by the optional
`%u` / `%m` format specifiers.

Adaptation notes for HarmonyOS (OHOS):
- Upstream tarball ships configure.ac/config.h.in/Makefile.in only, so
  `autoconf` runs before `./configure` (same pattern as archives/b/bird).
  `autoconf`/`m4` are declared as tool_requires because the OHOS device image
  does not provide them (verified on the device: both MISSING in
  /data/service/hnp/bin and ~/usr/local/bin); ohpcd publishes prebuilt
  binaries for os=OHOS.
- The `configure` generated by autoconf demands config.guess/config.sub next to
  it.  The tarball does not ship them, so the recipe provides OHOS-aware
  versions in autotools/ (the GNU config.guess shipped by the autoconf package
  prints `aarch64-unknown-linux-ohos` on the device, which is what the shipped
  config.guess reproduces).
- sqlite3 support (svn >= 1.7 working copies) is disabled: this recipe has no
  sqlite3 dependency, and enabling it silently would make the build depend on
  a header/library that is not part of the recipe.  svn 1.3-1.6 detection
  stays available and the built-in feature list reflects that.
- OHOS/HMDFS: autoconf's config.status creates its temporary directory with
  `umask 077`, which on HMDFS produces `drwx--S---` and blocks file creation
  inside it (knowledge E011/E052/E129/E136).  Reproduced on the device:
  `./config.status[697]: can't create ./conf49901-963/subs1.awk: Permission
  denied`.  The generated `configure` is therefore patched to `umask 022`;
  after that configure, make and `make check-simple` all succeed.
- OHOS has no writable `/tmp`; the upstream assert suite hardcodes
  `/tmp/vcprompt.XXXXXX` in tests/common.sh, hence
  patches/0001-tests-common.sh-honour-TMPDIR.patch plus an explicit TMPDIR.
- The Perl wrapper `vcprompt-hgst` is intentionally not packaged (it would add
  a Perl runtime dependency to a C-only package).
"""
import os
import shlex
import shutil

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.build import build_jobs
from conan.tools.env import Environment
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    load,
    save,
)
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout

# OHOS default install roots for tools provided by the device image.
_OHOS_EXTRA_BIN_DIRS = (
    "/data/service/hnp/bin",
    "/storage/Users/currentUser/usr/local/bin",
)

# Direct source URL used only when every URL from conandata.yml fails (the CI
# mirror rewrite turns that one into a list tried in order).  Verified identical
# to the primary tarball: same sha256, same top-level directory, same file list.
_FALLBACK_SOURCE_URL = (
    "https://codeload.github.com/powerman/vcprompt/tar.gz/refs/tags/v1.3.0"
)


class VcpromptConan(ConanFile):
    name = "vcprompt"
    version = "1.3.0"
    description = "Version control information (branch, revision, dirty) for shell prompts"
    license = "GPL-2.0-or-later"
    homepage = "https://github.com/powerman/vcprompt"
    url = ""
    package_type = "application"

    # R32: the recipe must accept both Linux and OHOS
    settings = "os", "compiler", "build_type", "arch"
    # Explicit so the autoconf/m4 tool_requires bin dirs are on PATH for the
    # plain `autoconf` invocation in build().
    generators = "VirtualBuildEnv"

    def export_sources(self):
        export_conandata_patches(self)
        copy(
            self,
            "*",
            src=os.path.join(self.recipe_folder, "autotools"),
            dst=os.path.join(self.export_sources_folder, "autotools"),
        )

    def layout(self):
        basic_layout(self, src_folder="src")
        # The upstream Makefile is generated by configure into the source tree
        # and its own `Makefile:` rule expects Makefile.in next to it
        # ("make: *** No rule to make target 'Makefile.in', needed by 'Makefile'"
        # when built out-of-source), so build in-source like upstream does.
        self.folders.build = "src"

    def build_requirements(self):
        # The OHOS device image ships neither autoconf nor m4 (verified on the
        # device); ohpcd publishes prebuilt binaries for os=OHOS, so the recipe
        # provides them instead of relying on the worker image.
        self.tool_requires("autoconf/2.72")
        self.tool_requires("m4/1.4.19")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"vcprompt {self.version} is only supported on Linux/OHOS "
                f"in this recipe, got {self.settings.os}"
            )

    def source(self):
        # `conandata.yml` carries the mirror-friendly `github.com/...` URL, which
        # the CI script rewrites to a list of mirrors (gh-proxy.com first) and
        # which conan tries in order.  A platform CI run failed with
        # "源码下载超时" (worker network restriction), so keep the direct codeload
        # URL as an explicit fallback.  The fallback deliberately lives here and
        # NOT in conandata.yml: any extra key matching `^\s*url:` would displace
        # the mirror list as the first match that the CI metadata step greps for,
        # which would leave `ci-metadata.json.source_trace.url` empty.
        # Both URLs were verified on the device to serve byte-identical tarballs
        # (same sha256, same top-level dir `vcprompt-1.3.0/`, same file list).
        data = self.conan_data["sources"]
        kwargs = {
            "sha256": data["sha256"],
            "filename": "vcprompt-1.3.0.tar.gz",
            "strip_root": True,
            "verify": True,
        }
        try:
            get(self, url=data["url"], **kwargs)
        except Exception as exc:  # noqa: BLE001
            self.output.warning(
                f"primary source URLs failed ({exc.__class__.__name__}): "
                f"retrying {_FALLBACK_SOURCE_URL}"
            )
            get(self, url=_FALLBACK_SOURCE_URL, **kwargs)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Optional dependency deliberately not enabled: no sqlite3 in this recipe.
        tc.configure_args.append("--with-sqlite3=no")
        tc.generate()

        # Expose the bin/ dirs contributed by the autoconf/m4 tool_requires so a
        # plain `autoconf` invocation resolves inside build().  AutotoolsToolchain
        # has already put them on PATH, this keeps them there for `make check`.
        env = Environment()
        for dep in self.dependencies.build.values():
            for bindir in dep.cpp_info.bindirs:
                env.prepend_path("PATH", bindir)
        # OHOS has no writable /tmp.  Expose a writable TMPDIR so the upstream
        # assert suite (mktemp) and config.status temporary files work.
        env.define("TMPDIR", self._writable_tmpdir())
        env.vars(self).save_script("vcprompt_build_env")

    def build(self):
        apply_conandata_patches(self)
        # Serial build on purpose: `make -jN` uses a jobserver FIFO, and mkfifo
        # is denied on the OHOS hmdfs data partition (verified: "jobserver
        # mkfifo: ... Operation not permitted").  make continues there, but a
        # serial build keeps the log clean and the project is 8 small C files.
        jobs = 1 if self.settings.os == "OHOS" else max(1, build_jobs(self))

        # The GitHub tag tarball has no pre-generated configure script.
        self._install_autotools_helpers()
        self.run("autoconf", cwd=self.source_folder)
        configure = os.path.join(self.source_folder, "configure")
        if not os.path.exists(configure):
            raise ConanException("autoconf did not generate configure")
        self._patch_autoconf_tempdir(configure)

        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=[f"-j{jobs}"])

        # L1: run the upstream assert suites that this environment can execute.
        # Upstream `make check` is check-simple + check-hg + check-git +
        # check-svn + check-fossil:
        #   * check-simple needs no external tool (fake VCS metadata only)
        #   * check-git needs a real git binary, which the OHOS image provides
        #     (verified on the device: /data/service/hnp/bin/git 2.45.2)
        #   * check-hg / check-svn / check-fossil need Mercurial, Subversion and
        #     Fossil, which are not part of the image and are not published on
        #     ohpcd, so those three suites cannot run here.
        for target in ("check-simple", "check-git"):
            autotools.make(args=[f"-j{jobs}"], target=target)

    def package(self):
        # Upstream `make install` also installs vcprompt-hgst (a Perl script)
        # and would add a Perl runtime requirement for an auxiliary feature, so
        # the two wanted artifacts are copied explicitly instead.
        copy(
            self,
            "vcprompt",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "bin"),
            keep_path=False,
        )
        os.chmod(os.path.join(self.package_folder, "bin", "vcprompt"), 0o755)
        copy(
            self,
            "vcprompt.1",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "share", "man", "man1"),
            keep_path=False,
        )
        # The upstream tarball carries the GPL-2.0-or-later notice only in the
        # file headers, so the full text is shipped from the recipe itself.
        copy(
            self,
            "LICENSE",
            src=os.path.join(self.recipe_folder, "licenses"),
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )
        copy(
            self,
            "README.md",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )
        for name in self._packaged_binaries():
            path = os.path.join(self.package_folder, "bin", name)
            if os.path.exists(path):
                self._sign_ohos_binary(path)
                os.chmod(path, 0o755)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = []
        self.cpp_info.set_property("cmake_file_name", "vcprompt")
        self.cpp_info.set_property("cmake_target_name", "vcprompt::vcprompt")
        self.cpp_info.set_property("pkg_config_name", "vcprompt")

    # ── helpers ──────────────────────────────────────────────────────────

    @staticmethod
    def _packaged_binaries():
        return ("vcprompt",)

    def _writable_tmpdir(self):
        """First writable candidate for TMPDIR on the build machine."""
        candidates = (
            "/data/service/hnp/tmp",
            "/storage/Users/currentUser/tmp",
            "/var/tmp",
            "/tmp",
        )
        if self.settings.os == "OHOS":
            for candidate in candidates:
                try:
                    os.makedirs(candidate, exist_ok=True)
                    probe = os.path.join(candidate, ".vcprompt-write-probe")
                    with open(probe, "w", encoding="utf-8") as handle:
                        handle.write("ok")
                    os.remove(probe)
                    return candidate
                except OSError:
                    continue
            raise ConanException(
                "no writable temporary directory found on OHOS "
                "(probed: " + ", ".join(candidates) + ")"
            )
        import tempfile

        return tempfile.gettempdir()

    def _install_autotools_helpers(self):
        """Place config.guess/config.sub next to configure.ac.

        The generated `configure` refuses to run without them
        ("cannot find required auxiliary files: config.guess config.sub") and the
        upstream tarball does not ship them.
        """
        helpers = os.path.join(self.export_sources_folder, "autotools")
        for name in ("config.guess", "config.sub"):
            target = os.path.join(self.source_folder, name)
            copy(self, name, src=helpers, dst=self.source_folder, keep_path=False)
            if not os.path.exists(target):
                raise ConanException(f"autotools helper {name} was not installed")
            os.chmod(target, 0o755)

    def _patch_autoconf_tempdir(self, configure_path):
        """HMDFS: autoconf's `umask 077` yields drwx--S--- temp dirs (E129/E136)."""
        if self.settings.os != "OHOS":
            return
        content = load(self, configure_path)
        if "umask 077" not in content:
            # Reproduced on the device with autoconf 2.72: without this patch
            # config.status fails with "can't create ./confXXXXXX/subs1.awk:
            # Permission denied".  Treat a missing pattern as a hard error so a
            # silently unpatched build cannot be published.
            raise ConanException(
                "E129/E136: 'umask 077' not found in the generated configure "
                "script; autoconf changed its temp-dir handling and the HMDFS "
                "workaround must be re-verified before building"
            )
        content = content.replace("umask 077", "umask 022")
        save(self, configure_path, content)
        os.chmod(configure_path, 0o755)
        self.output.info("patched configure: umask 077 -> umask 022 (HMDFS/E129)")

    def _resolve_tool(self, name, fallback_names=(), extra_dirs=()):
        found = shutil.which(name)
        if found:
            return found
        bindir = ""
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        if compilers.get("c"):
            bindir = os.path.dirname(compilers["c"])
        search_dirs = [bindir, *extra_dirs]
        if self.settings.os == "OHOS":
            search_dirs += list(_OHOS_EXTRA_BIN_DIRS)
        search_dirs.append(os.path.join(os.path.expanduser("~"), "usr", "local", "bin"))
        for directory in search_dirs:
            if not directory:
                continue
            for candidate in (name, *fallback_names):
                path = os.path.join(directory, candidate)
                if os.path.exists(path):
                    return path
        return None

    def _sign_ohos_binary(self, path):
        """OHOS denies execution of unsigned ELF binaries (ML-0043)."""
        if self.settings.os != "OHOS":
            return
        signer = self._resolve_tool("binary-sign-tool")
        objcopy = self._resolve_tool("llvm-objcopy", extra_dirs=("/data/service/hnp/bin",))
        if not signer:
            self.output.warning(
                "binary-sign-tool not found; packaged vcprompt stays unsigned "
                "and may not be executable on the device"
            )
            return
        if objcopy:
            self.run(
                f"{shlex.quote(objcopy)} --remove-section .codesign {shlex.quote(path)}",
                quiet=True,
            )
        signed = path + ".signed"
        self.run(
            f"{shlex.quote(signer)} sign -inFile {shlex.quote(path)} "
            f"-outFile {shlex.quote(signed)} -selfSign 1",
            quiet=True,
        )
        os.replace(signed, path)
        self.output.info(f"signed OHOS binary: {os.path.basename(path)}")
