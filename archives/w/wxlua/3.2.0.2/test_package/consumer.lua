require('wx')
local n = 0
local function check(value, label)
    assert(value, label)
    n = n + 1
    print('CONSUMER_OK', label)
end
check(wxlua.wxLUA_VERSION_STRING:find('3.2.0.2', 1, true) ~= nil, 'version')
check(wx.wxString('HarmonyOS'):GetData() == 'HarmonyOS', 'string binding')
local frame = wx.wxFrame(wx.NULL, wx.wxID_ANY, 'wxLua HarmonyOS consumer', wx.wxDefaultPosition, wx.wxSize(400, 240))
check(frame:GetTitle() == 'wxLua HarmonyOS consumer', 'frame title')
local panel = wx.wxPanel(frame, wx.wxID_ANY)
local button = wx.wxButton(panel, wx.wxID_ANY, 'Run callback')
check(button:GetLabel() == 'Run callback', 'button label')
local count = 0
button:Connect(wx.wxEVT_COMMAND_BUTTON_CLICKED, function(event) count = count + 1 end)
local event = wx.wxCommandEvent(wx.wxEVT_COMMAND_BUTTON_CLICKED, button:GetId())
button:GetEventHandler():ProcessEvent(event)
check(count == 1, 'Lua event callback')
local text = wx.wxTextCtrl(panel, wx.wxID_ANY, '')
text:SetValue('中文与 Unicode ✓')
check(text:GetValue() == '中文与 Unicode ✓', 'UTF-8 control roundtrip')
frame:Show(true)
wx.wxYield()
check(frame:IsShown(), 'frame mapped')
local image = wx.wxImage(4, 3)
check(image:GetWidth() == 4 and image:GetHeight() == 3, 'image dimensions')
local ok = pcall(function() wx.wxPoint('invalid', {}) end)
check(not ok, 'invalid argument rejected')
frame:Destroy()
wx.wxYield()
local alive = pcall(function() return button:GetLabel() end)
check(not alive, 'destroyed window userdata invalidated')
assert(n == 10)
print('WXLUA_CONSUMER_PASS 10')
os.exit(0)
