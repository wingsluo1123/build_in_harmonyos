#!/data/service/hnp/bin/bash
# test_package/test.sh — end-to-end consumer test for the packaged xine-ui.
#
# Everything here runs headless (there is no X display on the build workers):
# the packaged `xine` binary is exercised through its keymap emitter and its
# user-config loader, `xine-check` is run as the shipped diagnostic entry
# point, and the adapted desktop/mime data files are verified in the package.
#
# No `set -e` on purpose: every one of the 27 assertions must run so the report
# carries a complete denominator, and several upstream invocations exit 1 by
# design (--version/--help/--keymap), which `set -e` would abort on. Failures
# are accumulated by bad() and turned into exit status at the end.
set -uo pipefail

pass=0
fail=0
ok()  { echo "  [ok]   $1"; pass=$((pass + 1)); }
bad() { echo "  [FAIL] $1"; fail=$((fail + 1)); }
expect() { # expect <name> <expected> <actual>
    if [ "$2" = "$3" ]; then ok "$1 (= $2)"; else bad "$1: expected '$2', got '$3'"; fi
}

XINE="$(command -v xine || true)"
[ -n "$XINE" ] || { echo "FATAL: packaged xine is not on PATH"; exit 1; }
PKG_ROOT="$(dirname "$(dirname "$XINE")")"
SHARE="$PKG_ROOT/share"

# Isolated HOME so the test never touches the worker's real ~/.xine.
WORK="$(pwd)/.consumer-test"
rm -rf "$WORK"
mkdir -p "$WORK/.xine"
export HOME="$WORK"
trap 'rm -rf "$WORK"' EXIT

echo "== A. packaged binary identity"
"$XINE" --version > "$WORK/version.txt" 2>&1
rc=$?
expect "A1 'xine --version' exit code (upstream returns 1 after printing)" 1 "$rc"
grep -q "v0\.99\.14" "$WORK/version.txt" \
    && ok "A2 banner reports the adapted version 0.99.14" \
    || bad "A2 banner does not contain v0.99.14"
"$XINE" --help > "$WORK/help.txt" 2>&1
rc=$?
expect "A3 'xine --help' exit code" 1 "$rc"
grep -q "^Usage: xine" "$WORK/help.txt" \
    && ok "A4 usage synopsis printed" \
    || bad "A4 usage synopsis missing"
grep -q -- "--keymap" "$WORK/help.txt" \
    && ok "A5 --keymap documented in usage" \
    || bad "A5 --keymap missing from usage"

echo "== B. keymap dump -> \$HOME/.xine/keymap -> re-emission round trip"
"$XINE" --keymap=default > "$WORK/default.keymap" 2>/dev/null
rc=$?
expect "B1 '--keymap=default' exit code" 1 "$rc"
expect "B2 default keymap line count" 914 "$(wc -l < "$WORK/default.keymap" | tr -d ' ')"
expect "B3 default keymap binding count" 151 "$(grep -c '^[[:space:]]*key = ' "$WORK/default.keymap")"
grep -q "Automatically generated by xine-ui version 0.99\.14" "$WORK/default.keymap" \
    && ok "B4 table carries the xine-ui generator header" \
    || bad "B4 generator header missing"
# Cross-checked against the compiled-in table in src/xitk/kbindings_common.c.
grep -A1 "^Play {"  "$WORK/default.keymap" | grep -q "key = Return" \
    && ok "B5 Play is bound to Return as upstream declares" \
    || bad "B5 Play binding differs from kbindings_common.c"
grep -A1 "^Pause {" "$WORK/default.keymap" | grep -q "key = space" \
    && ok "B6 Pause is bound to space as upstream declares" \
    || bad "B6 Pause binding differs from kbindings_common.c"
grep -A1 "^Stop {"  "$WORK/default.keymap" | grep -q "key = S$" \
    && ok "B7 Stop is bound to S as upstream declares" \
    || bad "B7 Stop binding differs from kbindings_common.c"

cp "$WORK/default.keymap" "$HOME/.xine/keymap"
"$XINE" --keymap=remapped > "$WORK/remapped.keymap" 2>/dev/null
rc=$?
expect "B8 '--keymap=remapped' exit code" 1 "$rc"
if [ ! -s "$WORK/default.keymap" ] || [ ! -s "$WORK/remapped.keymap" ]; then
    bad "B9 skipped guard: a keymap file is empty, so the packaged xine emitted nothing"
elif cmp -s "$WORK/default.keymap" "$WORK/remapped.keymap"; then
    ok "B9 re-emission of the installed keymap is byte-identical (parse/serialise round trip)"
else
    bad "B9 remapped keymap is not byte-identical to the installed one"
fi
"$XINE" --keymap=lirc > "$WORK/lirc.keymap" 2>/dev/null
rc=$?
expect "B10 '--keymap=lirc' exit code" 1 "$rc"
expect "B11 lirc keymap line count" 1367 "$(wc -l < "$WORK/lirc.keymap" | tr -d ' ')"
lirc_blocks="$(grep -c '^begin' "$WORK/lirc.keymap")"
expect "B12 lirc keymap remote-entry count" 151 "$lirc_blocks"
xine_bindings="$(grep -c '^[[:space:]]*key = ' "$WORK/default.keymap")"
if [ "$xine_bindings" -eq 0 ] || [ "$lirc_blocks" -eq 0 ]; then
    bad "B13 skipped guard: one serialiser emitted zero bindings, so comparing counts is meaningless"
else
    expect "B13 both serialisers emit the same binding count" "$xine_bindings" "$lirc_blocks"
fi

echo "== C. packaged desktop/mime/man data (patched configure path)"
grep -q "^Exec=xine %U" "$SHARE/applications/xine.desktop" 2>/dev/null \
    && ok "C1 xine.desktop registers the packaged launcher" \
    || bad "C1 xine.desktop missing or without Exec=xine %U"
mime_count="$(sed -n 's/^MimeType=//p' "$SHARE/applications/xine.desktop" | tr ';' '\n' | grep -c .)"
if [ "$mime_count" -ge 50 ]; then
    ok "C2 desktop MimeType table populated from in-tree mime.default (measured $mime_count)"
else
    bad "C2 desktop MimeType table too small ($mime_count); mime fallback did not run"
fi
[ -f "$SHARE/mime/packages/xine-ui.xml" ] \
    && ok "C3 xine-ui.xml mime package installed" \
    || bad "C3 mime package xine-ui.xml missing"
[ -f "$SHARE/man/man1/xine.1" ] \
    && ok "C4 xine(1) man page installed" \
    || bad "C4 xine(1) man page missing"
skin_count="$(ls "$SHARE/xine/skins" 2>/dev/null | wc -l | tr -d ' ')"
if [ "$skin_count" -ge 1 ]; then
    ok "C5 skin data installed ($skin_count entries)"
else
    bad "C5 no skin data installed under share/xine/skins"
fi

echo "== D. xine-check headless diagnostic on HarmonyOS"
"$PKG_ROOT/bin/xine-check" > "$WORK/xine-check.txt" 2>&1 < /dev/null
rc=$?
expect "D1 'xine-check' exit code" 0 "$rc"
grep -q "is in your PATH" "$WORK/xine-check.txt" \
    && ok "D2 xine-check finds the packaged xine on the conan run PATH" \
    || bad "D2 xine-check did not locate xine in PATH"
grep -q "unknown operating system (HarmonyOS)" "$WORK/xine-check.txt" \
    && ok "D3 xine-check runs on the HarmonyOS kernel (uname reports HarmonyOS)" \
    || bad "D3 HarmonyOS platform line missing"
grep -q "No DISPLAY found" "$WORK/xine-check.txt" \
    && ok "D4 X checks are skipped headless without aborting the report" \
    || bad "D4 headless DISPLAY branch missing"

echo
echo "ASSERTIONS=$((pass + fail)) PASSED=$pass FAILED=$fail"
if [ "$fail" -ne 0 ]; then
    exit 1
fi
exit 0
