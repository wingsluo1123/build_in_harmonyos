#!/usr/bin/env python3
"""Conan recipe for zram-init 13.3 — POSIX shell zRAM initializer (vaeth/zram-init).

zram-init is a pure interpreted POSIX shell program (sbin/zram-init.in) plus
data files (man page, modprobe.d config, zsh completion, gettext catalogs,
systemd/OpenRC units). There is no C/C++ compilation: GNU make only substitutes
the @MODIR@/@EXENAME@ placeholders into sbin/zram-init.in via sed.

OHOS adaptation decisions — all expressed as upstream make flags, zero source
patches:

  - GETTEXT=FALSE        .mo message catalogs need msgfmt on the build host and
                         a runtime locale infrastructure that the OHOS shell
                         environment does not provide; the script degrades
                         gracefully to English messages ("Call with LANG=C...").
  - SYSTEMD=FALSE        HarmonyOS ships neither systemd nor OpenRC, so the
  - OPENRC=FALSE         corresponding unit files are not packaged.
  - MODIFY_SHEBANG=FALSE keep the upstream '#!/usr/bin/env sh' shebang: portable
                         on OHOS and reproducible across build hosts (the make
                         default would bake the build host's `command -v sh`
                         path into the artifact).
  - MODPROBED=TRUE       modprobe.d/zram.conf is part of the runtime contract
                         ("options zram num_devices=3") and stays packaged.

`make install` is deliberately NOT used: its INSTALL_EXE rule hardcodes
`install -D`, which the toybox userland of the OHOS build host does not
provide (knowledge E392 raw-makefile pattern). Files are staged explicitly in
package() instead.

The package is architecture independent (package_id cleared): the very same
script bytes are consumed by any OHOS aarch64 sh at runtime.
"""
import os

from conan import ConanFile
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class ZramInitConan(ConanFile):
    name = "zram-init"
    version = "13.3"
    description = ("POSIX shell script to set up (and release) zRAM devices "
                   "as swap or tmpfs mounts")
    license = "GPL-2.0-only"
    homepage = "https://github.com/vaeth/zram-init"
    url = "https://github.com/vaeth/zram-init"
    topics = ("shell", "zram", "swap", "memory", "init-script")
    package_type = "application"

    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def package_id(self):
        # Interpreted shell script + data files: no ABI, no toolchain influence.
        self.info.clear()

    def layout(self):
        basic_layout(self)

    def source(self):
        # E483/E276: the codeload URL has no archive extension in its basename,
        # so pass an explicit filename to let conan decode the tar.gz properly.
        get(self, **self.conan_data["sources"], strip_root=True,
            filename=f"zram-init-{self.version}.tar.gz")

    def build(self):
        apply_conandata_patches(self)
        # R9: sequential make. Run inside the source folder (basic_layout keeps
        # the Makefile there; the generated script lands in sbin/zram-init).
        # R33: no shell CC/CFLAGS involved — the build is pure sed substitution.
        make_vars = ("GETTEXT=FALSE SYSTEMD=FALSE OPENRC=FALSE "
                     "MODIFY_SHEBANG=FALSE")
        self.run(f"make {make_vars} -j1 sbin/zram-init",
                 cwd=self.source_folder)

    def package(self):
        src = self.source_folder
        pkg = self.package_folder
        # Executable script generated by make from sbin/zram-init.in.
        copy(self, "sbin/zram-init", src=src,
             dst=os.path.join(pkg, "bin"), keep_path=False)
        # Upstream man page (man8 section).
        copy(self, "man/zram-init.8", src=src,
             dst=os.path.join(pkg, "share", "man", "man8"), keep_path=False)
        # zsh completion.
        copy(self, "zsh/_zram-init", src=src,
             dst=os.path.join(pkg, "share", "zsh", "site-functions"),
             keep_path=False)
        # modprobe.d module options consumed at runtime by `modprobe zram`.
        copy(self, "modprobe.d/zram.conf", src=src,
             dst=os.path.join(pkg, "res", "modprobe.d"), keep_path=False)
        # HMDFS may drop group/other bits (E046); the user exec bit is what
        # matters and is forced explicitly.
        os.chmod(os.path.join(pkg, "bin", "zram-init"), 0o755)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.resdirs = ["res"]
